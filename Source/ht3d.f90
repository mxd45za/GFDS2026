    INTEGER, ALLOCATABLE, SAVE :: GLOBAL_NODE_COUNTS_H(:),GLOBAL_NODE_OFFSETS_H(:),GLOBAL_NODE_META_H(:)
    INTEGER, ALLOCATABLE, SAVE :: REMOTE_SOURCE_RANK_H(:),REMOTE_SOURCE_POS_H(:)

