            IF (SF_THERMAL_BC_INDEXD(SF_IDX) /= NO_CONVECTION) RETURN

            WALL_TMP_FD(IW) = WALL_TMP_GD(IW)
            IF (RADIATION_FLAG /= 0) WALL_Q_RAD_OUTD(IW) = SIGMA*WALL_EMISSIVITYD(IW)*WALL_TMP_FD(IW)**4

