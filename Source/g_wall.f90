            REAL(EB), DEVICE, DIMENSION(0:*) :: SF_RAMP_TEMP_TAUD, WALL_T_IGND, WALL_TMP_FD, WALL_HEAT_TRANS_COEFD, WALL_Q_CON_FD
            REAL(EB), DEVICE, DIMENSION(0:*) :: WALL_K_GD
            REAL(EB), DEVICE, DIMENSION(0:*) :: WALL_EMISSIVITYD, WALL_Q_RAD_OUTD
