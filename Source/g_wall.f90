    INTEGER, PARAMETER :: WALL_OUTPUT_RHO_D_DZDN_F    = 65536
    INTEGER, PARAMETER :: WALL_OUTPUT_M_DOT_ADJUST    = 131072
    INTEGER, PARAMETER :: WALL_OUTPUT_M_DOT_ACTUAL    = 262144
