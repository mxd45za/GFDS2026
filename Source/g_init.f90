        SUBROUTINE CHECK_GPU_WALL_SETUP
            INTEGER :: NM,IW
            TYPE(WALL_TYPE), POINTER :: WC
            TYPE(SURFACE_TYPE), POINTER :: SF

            IF (.NOT.WALL_BC_ON) RETURN
            DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
                DO IW=1,MESHES(NM)%N_EXTERNAL_WALL_CELLS+MESHES(NM)%N_INTERNAL_WALL_CELLS
                    WC => MESHES(NM)%WALL(IW)
                    IF (WC%BOUNDARY_TYPE==NULL_BOUNDARY) CYCLE
                    IF (WC%SURF_INDEX<1 .OR. WC%SURF_INDEX>SIZE(SURFACE)) CYCLE
                    SF => SURFACE(WC%SURF_INDEX)
                    IF (SF%THERMAL_BC_INDEX/=THERMALLY_THICK) CYCLE
                    IF (HT1D_GPU_WALL_ACTIVE(NM,IW)) CYCLE
                    WRITE(LU_ERR,'(A,I0,A,I0,A,A)') 'ERROR: GPU wall setup, mesh ',NM, &
                        ', wall ',IW,', SURF=',TRIM(SF%ID)
                    ERROR STOP 'GPU wall model unavailable for this surface; use --c/--gc'
                ENDDO
            ENDDO
        END SUBROUTINE CHECK_GPU_WALL_SETUP

        SUBROUTINE CHECK_GPU_RAMP_SETUP
            INTEGER :: IS,N

            DO IS=LBOUND(SURFACE,1),UBOUND(SURFACE,1)
                CALL CHECK_GPU_TIME_RAMP_SUPPORTED(SURFACE(IS)%RAMP(TIME_HEAT)%INDEX,'SURF RAMP_Q')
                CALL CHECK_GPU_TIME_RAMP_SUPPORTED(SURFACE(IS)%RAMP(TIME_TEMP)%INDEX,'SURF RAMP_T')
                CALL CHECK_GPU_TIME_RAMP_SUPPORTED(SURFACE(IS)%RAMP(TIME_VELO)%INDEX,'SURF RAMP_V')
                CALL CHECK_GPU_TIME_RAMP_SUPPORTED(SURFACE(IS)%RAMP(TIME_EFLUX)%INDEX,'SURF RAMP_EF')
                DO N=1,N_TRACKED_SPECIES
                    IF (ABS(SURFACE(IS)%MASS_FLUX(N))>TWO_EPSILON_EB) &
                        CALL CHECK_GPU_TIME_RAMP_SUPPORTED(SURFACE(IS)%RAMP(N)%INDEX,'SURF RAMP_MF')
                ENDDO
            ENDDO
        END SUBROUTINE CHECK_GPU_RAMP_SETUP

        SUBROUTINE CHECK_GPU_TIME_RAMP_SUPPORTED(RAMP_INDEX,CONTEXT)
            IMPLICIT NONE

            INTEGER, INTENT(IN) :: RAMP_INDEX
            CHARACTER(*), INTENT(IN) :: CONTEXT
            CHARACTER(MESSAGE_LENGTH) :: MESSAGE

            IF (RAMP_INDEX <= 0) RETURN

            IF (.NOT.ALLOCATED(RAMPS)) THEN
                WRITE(MESSAGE,'(A,A)') 'ERROR: GPU RAMP support expected RAMPS for ',TRIM(CONTEXT)
                CALL SHUTDOWN(MESSAGE,PROCESS_0_ONLY=.FALSE.)
                RETURN
            ENDIF

            IF (RAMP_INDEX > SIZE(RAMPS)) THEN
                WRITE(MESSAGE,'(A,A,A,I0)') 'ERROR: GPU RAMP support found invalid ramp index for ',TRIM(CONTEXT),': ',RAMP_INDEX
                CALL SHUTDOWN(MESSAGE,PROCESS_0_ONLY=.FALSE.)
                RETURN
            ENDIF

            IF (RAMPS(RAMP_INDEX)%DEVC_INDEX > 0 .OR. RAMPS(RAMP_INDEX)%CTRL_INDEX > 0 .OR. &
                RAMPS(RAMP_INDEX)%DEVC_DEP_INDEX > 0 .OR. RAMPS(RAMP_INDEX)%CTRL_DEP_INDEX > 0 .OR. &
                RAMPS(RAMP_INDEX)%EXTERNAL_FILE) THEN
                WRITE(MESSAGE,'(A,A,A,A)') 'ERROR: GPU wall RAMP only supports time ramps. Unsupported ramp in ', &
                                          TRIM(CONTEXT),': ',TRIM(RAMPS(RAMP_INDEX)%ID)
                CALL SHUTDOWN(MESSAGE,PROCESS_0_ONLY=.FALSE.)
                RETURN
            ENDIF

            IF (.NOT.ALLOCATED(RAMPS(RAMP_INDEX)%INTERPOLATED_DATA)) THEN
                WRITE(MESSAGE,'(A,A,A,A)') 'ERROR: GPU wall RAMP missing interpolated data in ',TRIM(CONTEXT),': ', &
                                          TRIM(RAMPS(RAMP_INDEX)%ID)
                CALL SHUTDOWN(MESSAGE,PROCESS_0_ONLY=.FALSE.)
            ENDIF

        END SUBROUTINE CHECK_GPU_TIME_RAMP_SUPPORTED

        !--------------------------------------------------------------------------
        ! Remote-mesh geometry mirrors
        !--------------------------------------------------------------------------
        SUBROUTINE INITIALIZE_GPU_REMOTE_READ_ONLY_MESHES
            USE MATH_FUNCTIONS, ONLY: EVALUATE_RAMP
            IMPLICIT NONE

            INTEGER :: NM,NOM,IC,K,CELL_LB,CELL_UB
            LOGICAL :: REQUIRED
            TYPE(GPU_MESH_TYPE), POINTER :: REMOTE_GM
            LOGICAL, ALLOCATABLE :: CELL_SOLID_H(:)
            REAL(EB), ALLOCATABLE :: P_0_H(:)

            IF (.NOT.ALLOCATED(GPU_MESHES)) ALLOCATE(GPU_MESHES(1:NMESHES))

            DO NOM=1,NMESHES
                IF (PROCESS(NOM)==MY_RANK) CYCLE
                REQUIRED = .FALSE.
                DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
                    IF (.NOT.ALLOCATED(GPU_MESHES(NM)%OMESH)) CYCLE
                    IF (GPU_MESHES(NM)%OMESH(NOM)%ACTIVE) THEN
                        REQUIRED = .TRUE.
                        EXIT
                    ENDIF
                ENDDO
                IF (.NOT.REQUIRED) CYCLE
                REMOTE_GM => GPU_MESHES(NOM)
                REMOTE_GM%NM = NOM

                ALLOCATE(REMOTE_GM%DXD(LBOUND(MESHES(NOM)%DX,1):UBOUND(MESHES(NOM)%DX,1)))
                ALLOCATE(REMOTE_GM%DYD(LBOUND(MESHES(NOM)%DY,1):UBOUND(MESHES(NOM)%DY,1)))
                ALLOCATE(REMOTE_GM%DZD(LBOUND(MESHES(NOM)%DZ,1):UBOUND(MESHES(NOM)%DZ,1)))
                ALLOCATE(REMOTE_GM%P_0D(0:MESHES(NOM)%KBP1),P_0_H(0:MESHES(NOM)%KBP1))
                P_0_H = P_INF
                IF (STRATIFICATION) THEN
                    DO K=0,MESHES(NOM)%KBP1
                        P_0_H(K) = EVALUATE_RAMP(MESHES(NOM)%ZC(K),I_RAMP_P0_Z)
                    ENDDO
                ENDIF
                REMOTE_GM%P_0D = P_0_H
                DEALLOCATE(P_0_H)
                ALLOCATE(REMOTE_GM%RDXND(LBOUND(MESHES(NOM)%RDXN,1):UBOUND(MESHES(NOM)%RDXN,1)))
                ALLOCATE(REMOTE_GM%RDYND(LBOUND(MESHES(NOM)%RDYN,1):UBOUND(MESHES(NOM)%RDYN,1)))
                ALLOCATE(REMOTE_GM%RDZND(LBOUND(MESHES(NOM)%RDZN,1):UBOUND(MESHES(NOM)%RDZN,1)))
                ALLOCATE(REMOTE_GM%CELL_INDEXD( &
                    LBOUND(MESHES(NOM)%CELL_INDEX,1):UBOUND(MESHES(NOM)%CELL_INDEX,1), &
                    LBOUND(MESHES(NOM)%CELL_INDEX,2):UBOUND(MESHES(NOM)%CELL_INDEX,2), &
                    LBOUND(MESHES(NOM)%CELL_INDEX,3):UBOUND(MESHES(NOM)%CELL_INDEX,3)))

                CELL_LB = LBOUND(MESHES(NOM)%CELL,1)
                CELL_UB = UBOUND(MESHES(NOM)%CELL,1)
                ALLOCATE(REMOTE_GM%CELL_SOLID(CELL_LB:CELL_UB),CELL_SOLID_H(CELL_LB:CELL_UB))
                DO IC=CELL_LB,CELL_UB
                    CELL_SOLID_H(IC) = MESHES(NOM)%CELL(IC)%SOLID
                ENDDO

                REMOTE_GM%DXD = MESHES(NOM)%DX
                REMOTE_GM%DYD = MESHES(NOM)%DY
                REMOTE_GM%DZD = MESHES(NOM)%DZ
                REMOTE_GM%RDXND = MESHES(NOM)%RDXN
                REMOTE_GM%RDYND = MESHES(NOM)%RDYN
                REMOTE_GM%RDZND = MESHES(NOM)%RDZN
                REMOTE_GM%CELL_INDEXD = MESHES(NOM)%CELL_INDEX
                REMOTE_GM%CELL_SOLID = CELL_SOLID_H
                DEALLOCATE(CELL_SOLID_H)
            ENDDO

        END SUBROUTINE INITIALIZE_GPU_REMOTE_READ_ONLY_MESHES

        !--------------------------------------------------------------------------
        ! CUDA launch-shape selection
        !--------------------------------------------------------------------------
        INTEGER FUNCTION INITIAL_GPU_BLOCK_DIM(N)
            IMPLICIT NONE
            INTEGER, INTENT(IN) :: N

            IF (N >= 8) THEN
                INITIAL_GPU_BLOCK_DIM = 8
            ELSEIF (N >= 4) THEN
                INITIAL_GPU_BLOCK_DIM = 4
            ELSEIF (N >= 2) THEN
                INITIAL_GPU_BLOCK_DIM = 2
            ELSE
                INITIAL_GPU_BLOCK_DIM = 1
            ENDIF
        END FUNCTION INITIAL_GPU_BLOCK_DIM

        SUBROUTINE CHOOSE_GPU_BLOCK_3D(NI,NJ,NK,BSX,BSY,BSZ)
            IMPLICIT NONE
            INTEGER, INTENT(IN) :: NI,NJ,NK
            INTEGER, INTENT(OUT) :: BSX,BSY,BSZ
            INTEGER :: THREADS
            REAL(EB) :: SCORE_X,SCORE_Y,SCORE_Z

            BSX = MAX(1,MIN(INITIAL_GPU_BLOCK_DIM(NI),NI))
            BSY = MAX(1,MIN(INITIAL_GPU_BLOCK_DIM(NJ),NJ))
            BSZ = MAX(1,MIN(INITIAL_GPU_BLOCK_DIM(NK),NK))

            ! Assign remaining block threads to the longest grid directions.
            REDISTRIBUTE_FACTORS_OF_TWO: DO
                THREADS = BSX*BSY*BSZ
                IF (THREADS*2 > GPU_3D_TARGET_THREADS) EXIT REDISTRIBUTE_FACTORS_OF_TWO

                SCORE_X = -1._EB
                SCORE_Y = -1._EB
                SCORE_Z = -1._EB

                IF (BSX*2 <= MIN(GPU_3D_MAX_BLOCK_DIM,NI)) SCORE_X = REAL(NI,EB)/REAL(BSX,EB)
                IF (BSY*2 <= MIN(GPU_3D_MAX_BLOCK_DIM,NJ)) SCORE_Y = REAL(NJ,EB)/REAL(BSY,EB)
                IF (BSZ*2 <= MIN(GPU_3D_MAX_BLOCK_DIM,NK)) SCORE_Z = REAL(NK,EB)/REAL(BSZ,EB)

                IF (MAX(SCORE_X,SCORE_Y,SCORE_Z) < 0._EB) EXIT REDISTRIBUTE_FACTORS_OF_TWO

                IF (SCORE_X >= SCORE_Y .AND. SCORE_X >= SCORE_Z) THEN
                    BSX = BSX*2
                ELSEIF (SCORE_Y >= SCORE_Z) THEN
                    BSY = BSY*2
                ELSE
                    BSZ = BSZ*2
                ENDIF
            ENDDO REDISTRIBUTE_FACTORS_OF_TWO
        END SUBROUTINE CHOOSE_GPU_BLOCK_3D

        SUBROUTINE SET_GPU_GRID_CACHE(NM)
            IMPLICIT NONE
            INTEGER, INTENT(IN) :: NM
            INTEGER :: NI,NJ,NK,NEDGE_ACTIVE

            ! Choose a 3D block for arrays A(0:IBP1,0:JBP1,0:KBP1), with contiguous X storage.
            NI = IBP1 + 1
            NJ = JBP1 + 1
            NK = KBP1 + 1

            CALL CHOOSE_GPU_BLOCK_3D(NI,NJ,NK,GPU_BSX_3D_BP1,GPU_BSY_3D_BP1,GPU_BSZ_3D_BP1)

            GPU_BLKD_3D_BP1 = DIM3(GPU_BSX_3D_BP1,GPU_BSY_3D_BP1,GPU_BSZ_3D_BP1)
            GPU_GRDD_3D_BP1 = DIM3((NI + GPU_BSX_3D_BP1 - 1)/GPU_BSX_3D_BP1, &
                                   (NJ + GPU_BSY_3D_BP1 - 1)/GPU_BSY_3D_BP1, &
                                   (NK + GPU_BSZ_3D_BP1 - 1)/GPU_BSZ_3D_BP1)

            NEDGE_ACTIVE = MAX(0,EDGE_COUNT(NM))
            GPU_GRDD_EXTERNAL_WALL_1D = (N_EXTERNAL_WALL_CELLS + N_INTERNAL_WALL_CELLS + GPU_BLKD_1D - 1) / GPU_BLKD_1D
            GPU_GRDD_TOTAL_WALL_1D = (N_EXTERNAL_WALL_CELLS + N_INTERNAL_WALL_CELLS + GPU_BLKD_1D - 1) / GPU_BLKD_1D
            GPU_GRDD_EDGE_ACTIVE_1D = (NEDGE_ACTIVE + GPU_BLKD_1D - 1) / GPU_BLKD_1D
        END SUBROUTINE SET_GPU_GRID_CACHE


        !--------------------------------------------------------------------------
        ! Neighboring-mesh device mirrors
        !--------------------------------------------------------------------------
        SUBROUTINE INITIALIZE_GPU_OMESHES(NM)
            IMPLICIT NONE

            INTEGER, INTENT(IN) :: NM
            INTEGER :: NOM,I1,I2,J1,J2,K1,K2,N_ACTIVE,IJK_SIZE_S,IJK_SIZE_R,N_SEND,N_RECV
            TYPE(OMESH_TYPE), POINTER :: CPU_OM
            TYPE(GPU_OMESH_TYPE), POINTER :: GOM_LOCAL

            CALL POINT_TO_MESH(NM)
            GM => GPU_MESHES(NM)

            IF (.NOT.ALLOCATED(MESHES(NM)%OMESH)) RETURN
            IF (.NOT.ALLOCATED(GM%OMESH)) ALLOCATE(GM%OMESH(1:NMESHES))

            N_ACTIVE = 0
            DO NOM=1,NMESHES
                CPU_OM => MESHES(NM)%OMESH(NOM)
                GOM_LOCAL => GM%OMESH(NOM)

                GOM_LOCAL%SOURCE_NM = NOM
                GOM_LOCAL%TARGET_NM = NM
                GOM_LOCAL%SOURCE_IBP1 = MESHES(NOM)%IBP1
                GOM_LOCAL%SOURCE_JBP1 = MESHES(NOM)%JBP1
                GOM_LOCAL%SOURCE_KBP1 = MESHES(NOM)%KBP1
                GOM_LOCAL%I_MIN_R = CPU_OM%I_MIN_R
                GOM_LOCAL%I_MAX_R = CPU_OM%I_MAX_R
                GOM_LOCAL%J_MIN_R = CPU_OM%J_MIN_R
                GOM_LOCAL%J_MAX_R = CPU_OM%J_MAX_R
                GOM_LOCAL%K_MIN_R = CPU_OM%K_MIN_R
                GOM_LOCAL%K_MAX_R = CPU_OM%K_MAX_R
                GOM_LOCAL%NIC_R = CPU_OM%NIC_R
                GOM_LOCAL%I_MIN_S = CPU_OM%I_MIN_S
                GOM_LOCAL%I_MAX_S = CPU_OM%I_MAX_S
                GOM_LOCAL%J_MIN_S = CPU_OM%J_MIN_S
                GOM_LOCAL%J_MAX_S = CPU_OM%J_MAX_S
                GOM_LOCAL%K_MIN_S = CPU_OM%K_MIN_S
                GOM_LOCAL%K_MAX_S = CPU_OM%K_MAX_S
                GOM_LOCAL%NIC_S = CPU_OM%NIC_S

                ! WALL back-side requests already have a stable ordering from
                ! INITIALIZE_BACK_WALL_EXCHANGE. Mirror only that ordering and
                ! the five values needed by the GPU HT1D boundary solve.
                N_SEND = CPU_OM%WALL_SEND_BUFFER%N_ITEMS
                N_RECV = CPU_OM%WALL_RECV_BUFFER%N_ITEMS
                GOM_LOCAL%HT1D_N_SEND = N_SEND
                GOM_LOCAL%HT1D_N_RECV = N_RECV
                IF (PROCESS(NM)/=PROCESS(NOM)) THEN
                    IF (N_SEND>0) THEN
                        ALLOCATE(GOM_LOCAL%HT1D_WALL_INDEX_S_D(1:N_SEND))
                        ALLOCATE(GOM_LOCAL%HT1D_SEND_PKG_D(HT1D_BACKSIDE_FIELD_COUNT*N_SEND))
                        GOM_LOCAL%HT1D_WALL_INDEX_S_D = CPU_OM%WALL_SEND_BUFFER%ITEM_INDEX(1:N_SEND)
                    ENDIF
                    IF (N_RECV>0) THEN
                        ALLOCATE(GOM_LOCAL%HT1D_RECV_PKG_D(HT1D_BACKSIDE_FIELD_COUNT*N_RECV))
                    ENDIF
                ENDIF

                ! GPU mesh exchange uses contiguous device packages only for neighbors on another rank.
                IF (PROCESS(NM)/=PROCESS(NOM)) THEN
                    IF (GOM_LOCAL%NIC_S>0) THEN
                        IJK_SIZE_S = (GOM_LOCAL%I_MAX_S-GOM_LOCAL%I_MIN_S+1)* &
                                     (GOM_LOCAL%J_MAX_S-GOM_LOCAL%J_MIN_S+1)* &
                                     (GOM_LOCAL%K_MAX_S-GOM_LOCAL%K_MIN_S+1)
                        ALLOCATE(GOM_LOCAL%SEND_PKG1_D(GOM_LOCAL%NIC_S*(6+2*N_TOTAL_SCALARS)))
                        ALLOCATE(GOM_LOCAL%SEND_PKG3_D(4*IJK_SIZE_S))
                        ALLOCATE(GOM_LOCAL%SEND_PKG7_D(3*GOM_LOCAL%NIC_S))
                    ENDIF
                    IF (GOM_LOCAL%NIC_R>0) THEN
                        IJK_SIZE_R = (GOM_LOCAL%I_MAX_R-GOM_LOCAL%I_MIN_R+1)* &
                                     (GOM_LOCAL%J_MAX_R-GOM_LOCAL%J_MIN_R+1)* &
                                     (GOM_LOCAL%K_MAX_R-GOM_LOCAL%K_MIN_R+1)
                        ALLOCATE(GOM_LOCAL%RECV_PKG1_D(GOM_LOCAL%NIC_R*(6+2*N_TOTAL_SCALARS)))
                        ALLOCATE(GOM_LOCAL%RECV_PKG3_D(4*IJK_SIZE_R))
                        ALLOCATE(GOM_LOCAL%RECV_PKG7_D(3*GOM_LOCAL%NIC_R))
                    ENDIF
                ENDIF

                IF (ALLOCATED(CPU_OM%IIO_R)) THEN
                    ALLOCATE(GOM_LOCAL%IIO_R_H(LBOUND(CPU_OM%IIO_R,1):UBOUND(CPU_OM%IIO_R,1)))
                    ALLOCATE(GOM_LOCAL%JJO_R_H(LBOUND(CPU_OM%JJO_R,1):UBOUND(CPU_OM%JJO_R,1)))
                    ALLOCATE(GOM_LOCAL%KKO_R_H(LBOUND(CPU_OM%KKO_R,1):UBOUND(CPU_OM%KKO_R,1)))
                    ALLOCATE(GOM_LOCAL%IOR_R_H(LBOUND(CPU_OM%IOR_R,1):UBOUND(CPU_OM%IOR_R,1)))
                    ALLOCATE(GOM_LOCAL%IIO_R_D(LBOUND(CPU_OM%IIO_R,1):UBOUND(CPU_OM%IIO_R,1)))
                    ALLOCATE(GOM_LOCAL%JJO_R_D(LBOUND(CPU_OM%JJO_R,1):UBOUND(CPU_OM%JJO_R,1)))
                    ALLOCATE(GOM_LOCAL%KKO_R_D(LBOUND(CPU_OM%KKO_R,1):UBOUND(CPU_OM%KKO_R,1)))
                    ALLOCATE(GOM_LOCAL%IOR_R_D(LBOUND(CPU_OM%IOR_R,1):UBOUND(CPU_OM%IOR_R,1)))
                    GOM_LOCAL%IIO_R_H = CPU_OM%IIO_R
                    GOM_LOCAL%JJO_R_H = CPU_OM%JJO_R
                    GOM_LOCAL%KKO_R_H = CPU_OM%KKO_R
                    GOM_LOCAL%IOR_R_H = CPU_OM%IOR_R
                    GOM_LOCAL%IIO_R_D = GOM_LOCAL%IIO_R_H
                    GOM_LOCAL%JJO_R_D = GOM_LOCAL%JJO_R_H
                    GOM_LOCAL%KKO_R_D = GOM_LOCAL%KKO_R_H
                    GOM_LOCAL%IOR_R_D = GOM_LOCAL%IOR_R_H
                ENDIF

                IF (ALLOCATED(CPU_OM%IIO_S)) THEN
                    ALLOCATE(GOM_LOCAL%IIO_S_H(LBOUND(CPU_OM%IIO_S,1):UBOUND(CPU_OM%IIO_S,1)))
                    ALLOCATE(GOM_LOCAL%JJO_S_H(LBOUND(CPU_OM%JJO_S,1):UBOUND(CPU_OM%JJO_S,1)))
                    ALLOCATE(GOM_LOCAL%KKO_S_H(LBOUND(CPU_OM%KKO_S,1):UBOUND(CPU_OM%KKO_S,1)))
                    ALLOCATE(GOM_LOCAL%IOR_S_H(LBOUND(CPU_OM%IOR_S,1):UBOUND(CPU_OM%IOR_S,1)))
                    ALLOCATE(GOM_LOCAL%IIO_S_D(LBOUND(CPU_OM%IIO_S,1):UBOUND(CPU_OM%IIO_S,1)))
                    ALLOCATE(GOM_LOCAL%JJO_S_D(LBOUND(CPU_OM%JJO_S,1):UBOUND(CPU_OM%JJO_S,1)))
                    ALLOCATE(GOM_LOCAL%KKO_S_D(LBOUND(CPU_OM%KKO_S,1):UBOUND(CPU_OM%KKO_S,1)))
                    ALLOCATE(GOM_LOCAL%IOR_S_D(LBOUND(CPU_OM%IOR_S,1):UBOUND(CPU_OM%IOR_S,1)))
                    GOM_LOCAL%IIO_S_H = CPU_OM%IIO_S
                    GOM_LOCAL%JJO_S_H = CPU_OM%JJO_S
                    GOM_LOCAL%KKO_S_H = CPU_OM%KKO_S
                    GOM_LOCAL%IOR_S_H = CPU_OM%IOR_S
                    GOM_LOCAL%IIO_S_D = GOM_LOCAL%IIO_S_H
                    GOM_LOCAL%JJO_S_D = GOM_LOCAL%JJO_S_H
                    GOM_LOCAL%KKO_S_D = GOM_LOCAL%KKO_S_H
                    GOM_LOCAL%IOR_S_D = GOM_LOCAL%IOR_S_H
                ENDIF

                IF (.NOT.ALLOCATED(CPU_OM%RHO)) THEN
                    GOM_LOCAL%INITIALIZED = .TRUE.
                    CYCLE
                ENDIF

                GOM_LOCAL%ACTIVE = .TRUE.
                N_ACTIVE = N_ACTIVE + 1
                I1 = LBOUND(CPU_OM%RHO,1)
                I2 = UBOUND(CPU_OM%RHO,1)
                J1 = LBOUND(CPU_OM%RHO,2)
                J2 = UBOUND(CPU_OM%RHO,2)
                K1 = LBOUND(CPU_OM%RHO,3)
                K2 = UBOUND(CPU_OM%RHO,3)

                ALLOCATE(GOM_LOCAL%RHO_D(I1:I2,J1:J2,K1:K2),GOM_LOCAL%RHOS_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%D_D(I1:I2,J1:J2,K1:K2),GOM_LOCAL%DS_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%MU_D(I1:I2,J1:J2,K1:K2),GOM_LOCAL%KRES_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%Q_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%H_D(I1:I2,J1:J2,K1:K2),GOM_LOCAL%HS_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%U_D(I1:I2,J1:J2,K1:K2),GOM_LOCAL%V_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%W_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%US_D(I1:I2,J1:J2,K1:K2),GOM_LOCAL%VS_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%WS_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%FVX_D(I1:I2,J1:J2,K1:K2),GOM_LOCAL%FVY_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%FVZ_D(I1:I2,J1:J2,K1:K2))
                ALLOCATE(GOM_LOCAL%ZZ_D(I1:I2,J1:J2,K1:K2,1:N_TOTAL_SCALARS))
                ALLOCATE(GOM_LOCAL%ZZS_D(I1:I2,J1:J2,K1:K2,1:N_TOTAL_SCALARS))

                GOM_LOCAL%RHO_D = CPU_OM%RHO
                GOM_LOCAL%RHOS_D = CPU_OM%RHOS
                GOM_LOCAL%D_D = CPU_OM%D
                GOM_LOCAL%DS_D = CPU_OM%DS
                GOM_LOCAL%MU_D = CPU_OM%MU
                GOM_LOCAL%KRES_D = CPU_OM%KRES
                GOM_LOCAL%Q_D = CPU_OM%Q
                GOM_LOCAL%H_D = CPU_OM%H
                GOM_LOCAL%HS_D = CPU_OM%HS
                GOM_LOCAL%U_D = CPU_OM%U
                GOM_LOCAL%V_D = CPU_OM%V
                GOM_LOCAL%W_D = CPU_OM%W
                GOM_LOCAL%US_D = CPU_OM%US
                GOM_LOCAL%VS_D = CPU_OM%VS
                GOM_LOCAL%WS_D = CPU_OM%WS
                GOM_LOCAL%FVX_D = CPU_OM%FVX
                GOM_LOCAL%FVY_D = CPU_OM%FVY
                GOM_LOCAL%FVZ_D = CPU_OM%FVZ
                GOM_LOCAL%ZZ_D = CPU_OM%ZZ
                GOM_LOCAL%ZZS_D = CPU_OM%ZZS

                GOM_LOCAL%INITIALIZED = .TRUE.
            ENDDO

        END SUBROUTINE INITIALIZE_GPU_OMESHES

        SUBROUTINE RELEASE_GPU_OMESHES(NM)
            IMPLICIT NONE

            INTEGER, INTENT(IN) :: NM

            GM => GPU_MESHES(NM)
            IF (ALLOCATED(GM%OMESH)) DEALLOCATE(GM%OMESH)
            NULLIFY(GOM)
            CURRENT_GPU_OMESH = 0

        END SUBROUTINE RELEASE_GPU_OMESHES

