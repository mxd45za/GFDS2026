                     GM%DUMP%MASS_RESULT_D(1+N_SPECIES+N_TRACKED_SPECIES), &
                     GM%DUMP%MASS_RESULT_H(1+N_SPECIES+N_TRACKED_SPECIES))
            ALLOCATE(GM%DUMP%DEVC_PARTIAL_D(N_CELL_BLOCKS),GM%DUMP%DEVC_RESULT_D(MAX(1,N_DEVC)), &
                     GM%DUMP%DEVC_RESULT_H(MAX(1,N_DEVC)))
            ALLOCATE(GM%DUMP%SMOKE_PACK_D(IBP1*JBP1*KBP1),GM%DUMP%SMOKE_PACK_H(IBP1*JBP1*KBP1))

            K3DTD = K3DT
            LES_FILTER_WIDTHD = LES_FILTER_WIDTH
            CELL_INDEXD = CELL_INDEX
            PRESSURE_ZONED = PRESSURE_ZONE

            RDXND = RDXN ; RDYND = RDYN ; RDZND = RDZN
            RDXD = RDX ; RDYD = RDY ; RDZD = RDZ
            RD = R ; RRND = RRN
            DXD = DX ; DYD = DY ; DZD = DZ
            HXD = HX ; HYD = HY ; HZD = HZ

            TWO_EPSILON_EBD = TWO_EPSILON_EB
            VON_KARMAN_CONSTANTD = VON_KARMAN_CONSTANT
            Y_WERNER_WENGLED     = Y_WERNER_WENGLE

            DO N=LBOUND(BXS,2),UBOUND(BXS,2)
                BXSD(:,N) = BXS(:,N)
                BXFD(:,N) = BXF(:,N)
            ENDDO
            DO N=LBOUND(BYS,2),UBOUND(BYS,2)
                BYSD(:,N) = BYS(:,N)
                BYFD(:,N) = BYF(:,N)
            ENDDO
            DO N=LBOUND(BZS,2),UBOUND(BZS,2)
                BZSD(:,N) = BZS(:,N)
                BZFD(:,N) = BZF(:,N)
            ENDDO

            IF (N_EDGE_AXIS1 > 0) EDGE_AXIS1_LIST(1:N_EDGE_AXIS1) = EDGE_AXIS1_LIST_H(1:N_EDGE_AXIS1)
            IF (N_EDGE_AXIS2 > 0) EDGE_AXIS2_LIST(1:N_EDGE_AXIS2) = EDGE_AXIS2_LIST_H(1:N_EDGE_AXIS2)
            IF (N_EDGE_AXIS3 > 0) EDGE_AXIS3_LIST(1:N_EDGE_AXIS3) = EDGE_AXIS3_LIST_H(1:N_EDGE_AXIS3)
            DO SIDE_TMP=1,4
                EDGE_SIDE_ISGN(:,SIDE_TMP) = EDGE_SIDE_ISGN_H(:,SIDE_TMP)
                EDGE_SIDE_IOR(:,SIDE_TMP)  = EDGE_SIDE_IOR_H(:,SIDE_TMP)
                EDGE_SIDE_IS2(:,SIDE_TMP)  = EDGE_SIDE_IS2_H(:,SIDE_TMP)
                EDGE_SIDE_ICD(:,SIDE_TMP)  = EDGE_SIDE_ICD_H(:,SIDE_TMP)
                EDGE_SIDE_IWM(:,SIDE_TMP)  = EDGE_SIDE_IWM_H(:,SIDE_TMP)
                EDGE_SIDE_IWMI(:,SIDE_TMP) = EDGE_SIDE_IWMI_H(:,SIDE_TMP)
                EDGE_SIDE_IWP(:,SIDE_TMP)  = EDGE_SIDE_IWP_H(:,SIDE_TMP)
                EDGE_SIDE_IWPI(:,SIDE_TMP) = EDGE_SIDE_IWPI_H(:,SIDE_TMP)
            ENDDO

            DEALLOCATE(CELL_WALL_INDEX_H, STAT=ISTAT)
            DEALLOCATE(SPECIES_ZZ0_H, SPECIES_RCON_H, STAT=ISTAT)
            DEALLOCATE(EDGE_AXIS1_LIST_H, STAT=ISTAT)
            DEALLOCATE(EDGE_AXIS2_LIST_H, STAT=ISTAT)
            DEALLOCATE(EDGE_AXIS3_LIST_H, STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_ISGN_H, STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_IOR_H,  STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_IS2_H,  STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_ICD_H,  STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_IWM_H,  STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_IWMI_H, STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_IWP_H,  STAT=ISTAT)
            DEALLOCATE(EDGE_SIDE_IWPI_H, STAT=ISTAT)

            ! Combustion-state allocation and initial transfer.
            IF (DO_COMBUSTION_GPU_ALLOC) THEN
                GPU_MAX_REACTIONS = MAX(1,N_REACTIONS)

                ALLOCATE(SPECIES_Z2Y_O2_H(1:N_TRACKED_SPECIES))
                ALLOCATE(SPECIES_H_F_H(1:N_TRACKED_SPECIES))
                ALLOCATE(REAC_NU_MW_O_MW_F_H(1:N_TRACKED_SPECIES,1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_A_PRIME_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_RHO_EXPONENT_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_HEAT_OF_COMBUSTION_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_CRITICAL_FLAME_TEMPERATURE_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_AUTO_IGNITION_TEMPERATURE_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_Y_O2_MIN_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_CHI_R_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_FUEL_SMIX_INDEX_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_AIR_SMIX_INDEX_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_PRIORITY_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_N_SMIX_R_H(1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_REACTANT_INDEX_H(1:N_TRACKED_SPECIES,1:GPU_MAX_REACTIONS))
                ALLOCATE(REAC_FAST_CHEMISTRY_H(1:GPU_MAX_REACTIONS))

                DO N = 1, N_TRACKED_SPECIES
                    SPECIES_H_F_H(N) = SPECIES_MIXTURE(N)%H_F
                ENDDO
                SPECIES_Z2Y_O2_H = 0._EB
                IF (O2_INDEX > 0) SPECIES_Z2Y_O2_H(1:N_TRACKED_SPECIES) = Z2Y(O2_INDEX,1:N_TRACKED_SPECIES)

                REAC_NU_MW_O_MW_F_H = 0._EB
                REAC_A_PRIME_H = 0._EB
                REAC_RHO_EXPONENT_H = 0._EB
                REAC_HEAT_OF_COMBUSTION_H = 0._EB
                REAC_CRITICAL_FLAME_TEMPERATURE_H = 0._EB
                REAC_AUTO_IGNITION_TEMPERATURE_H = 0._EB
                REAC_Y_O2_MIN_H = 0._EB
                REAC_CHI_R_H = 0._EB
                REAC_FUEL_SMIX_INDEX_H = -1
                REAC_AIR_SMIX_INDEX_H = -1
                REAC_PRIORITY_H = 0
                REAC_N_SMIX_R_H = 0
                REAC_REACTANT_INDEX_H = 0
                REAC_FAST_CHEMISTRY_H = .FALSE.
                DO NR = 1, N_REACTIONS
                    REAC_A_PRIME_H(NR) = REACTION(NR)%A_PRIME
                    REAC_RHO_EXPONENT_H(NR) = REACTION(NR)%RHO_EXPONENT
                    REAC_HEAT_OF_COMBUSTION_H(NR) = REACTION(NR)%HEAT_OF_COMBUSTION
                    REAC_CRITICAL_FLAME_TEMPERATURE_H(NR) = REACTION(NR)%CRITICAL_FLAME_TEMPERATURE
                    REAC_AUTO_IGNITION_TEMPERATURE_H(NR) = REACTION(NR)%AUTO_IGNITION_TEMPERATURE
                    REAC_Y_O2_MIN_H(NR) = REACTION(NR)%Y_O2_MIN
                    REAC_CHI_R_H(NR) = REACTION(NR)%CHI_R
                    REAC_FUEL_SMIX_INDEX_H(NR) = REACTION(NR)%FUEL_SMIX_INDEX
                    REAC_AIR_SMIX_INDEX_H(NR) = REACTION(NR)%AIR_SMIX_INDEX
                    REAC_PRIORITY_H(NR) = REACTION(NR)%PRIORITY
                    REAC_N_SMIX_R_H(NR) = REACTION(NR)%N_SMIX_R
                    REAC_FAST_CHEMISTRY_H(NR) = REACTION(NR)%FAST_CHEMISTRY
                    IF (ALLOCATED(REACTION(NR)%REACTANT_INDEX) .AND. REACTION(NR)%N_SMIX_R > 0) THEN
                        REAC_REACTANT_INDEX_H(1:REACTION(NR)%N_SMIX_R,NR) = REACTION(NR)%REACTANT_INDEX(1:REACTION(NR)%N_SMIX_R)
                    ENDIF
                    IF (ALLOCATED(REACTION(NR)%NU_MW_O_MW_F)) THEN
                        REAC_NU_MW_O_MW_F_H(1:N_TRACKED_SPECIES,NR) = REACTION(NR)%NU_MW_O_MW_F(1:N_TRACKED_SPECIES)
                    ENDIF
                ENDDO

                IF (.NOT.ALLOCATED(SPECIES_Z2Y_O2D)) ALLOCATE(SPECIES_Z2Y_O2D(1:N_TRACKED_SPECIES))
                IF (.NOT.ALLOCATED(SPECIES_H_FD)) ALLOCATE(SPECIES_H_FD(1:N_TRACKED_SPECIES))
                IF (.NOT.ALLOCATED(REAC_NU_MW_O_MW_FD)) ALLOCATE(REAC_NU_MW_O_MW_FD(1:N_TRACKED_SPECIES,1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_A_PRIMED)) ALLOCATE(REAC_A_PRIMED(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_RHO_EXPONENTD)) ALLOCATE(REAC_RHO_EXPONENTD(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_HEAT_OF_COMBUSTIOND)) ALLOCATE(REAC_HEAT_OF_COMBUSTIOND(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_CRITICAL_FLAME_TEMPERATURED)) ALLOCATE(REAC_CRITICAL_FLAME_TEMPERATURED(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_AUTO_IGNITION_TEMPERATURED)) ALLOCATE(REAC_AUTO_IGNITION_TEMPERATURED(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_Y_O2_MIND)) ALLOCATE(REAC_Y_O2_MIND(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_CHI_RD)) ALLOCATE(REAC_CHI_RD(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_FUEL_SMIX_INDEXD)) ALLOCATE(REAC_FUEL_SMIX_INDEXD(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_AIR_SMIX_INDEXD)) ALLOCATE(REAC_AIR_SMIX_INDEXD(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_PRIORITYD)) ALLOCATE(REAC_PRIORITYD(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_N_SMIX_RD)) ALLOCATE(REAC_N_SMIX_RD(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_REACTANT_INDEXD)) ALLOCATE(REAC_REACTANT_INDEXD(1:N_TRACKED_SPECIES,1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(REAC_FAST_CHEMISTRYD)) ALLOCATE(REAC_FAST_CHEMISTRYD(1:GPU_MAX_REACTIONS))
                IF (.NOT.ALLOCATED(GM%FIRE)) ALLOCATE(GM%FIRE)
                ALLOCATE(GM%FIRE%N_ACTIVE_CELLS_D(1),GM%FIRE%N_ACTIVE_CC_D(1))
                ALLOCATE(GM%FIRE%ACTIVE_CELLS_D(1:IBP1*JBP1*KBP1,1:3))
                SPECIES_Z2Y_O2D = SPECIES_Z2Y_O2_H
                SPECIES_H_FD = SPECIES_H_F_H
                DO NR=1,GPU_MAX_REACTIONS
                    REAC_NU_MW_O_MW_FD(:,NR) = REAC_NU_MW_O_MW_F_H(:,NR)
                ENDDO
                REAC_A_PRIMED = REAC_A_PRIME_H
                REAC_RHO_EXPONENTD = REAC_RHO_EXPONENT_H
                REAC_HEAT_OF_COMBUSTIOND = REAC_HEAT_OF_COMBUSTION_H
                REAC_CRITICAL_FLAME_TEMPERATURED = REAC_CRITICAL_FLAME_TEMPERATURE_H
                REAC_AUTO_IGNITION_TEMPERATURED = REAC_AUTO_IGNITION_TEMPERATURE_H
                REAC_Y_O2_MIND = REAC_Y_O2_MIN_H
                REAC_CHI_RD = REAC_CHI_R_H
                REAC_FUEL_SMIX_INDEXD = REAC_FUEL_SMIX_INDEX_H
                REAC_AIR_SMIX_INDEXD = REAC_AIR_SMIX_INDEX_H
                REAC_PRIORITYD = REAC_PRIORITY_H
                REAC_N_SMIX_RD = REAC_N_SMIX_R_H
                DO NR=1,GPU_MAX_REACTIONS
                    REAC_REACTANT_INDEXD(:,NR) = REAC_REACTANT_INDEX_H(:,NR)
                ENDDO
                REAC_FAST_CHEMISTRYD = REAC_FAST_CHEMISTRY_H
                GM%FIRE%N_ACTIVE_CELLS_D(1) = 0
                GM%FIRE%N_ACTIVE_CC_D(1) = 0
                GM%FIRE%ACTIVE_CELLS_D = -1

                DEALLOCATE(SPECIES_Z2Y_O2_H, SPECIES_H_F_H, STAT=ISTAT)
                DEALLOCATE(REAC_NU_MW_O_MW_F_H, REAC_A_PRIME_H, REAC_RHO_EXPONENT_H, REAC_HEAT_OF_COMBUSTION_H, STAT=ISTAT)
                DEALLOCATE(REAC_CRITICAL_FLAME_TEMPERATURE_H, REAC_AUTO_IGNITION_TEMPERATURE_H, STAT=ISTAT)
                DEALLOCATE(REAC_Y_O2_MIN_H, REAC_CHI_R_H, STAT=ISTAT)
                DEALLOCATE(REAC_FUEL_SMIX_INDEX_H, REAC_AIR_SMIX_INDEX_H, REAC_PRIORITY_H, STAT=ISTAT)
                DEALLOCATE(REAC_N_SMIX_R_H, REAC_REACTANT_INDEX_H, REAC_FAST_CHEMISTRY_H, STAT=ISTAT)
            ELSE
                GPU_MAX_REACTIONS = 0
            ENDIF

            ! Initial field transfer.
            DS_D = DS ; D_D = D
            USD = US ; UD = U
            VSD = VS ; VD = V
            WSD = WS ; WD = W
            RHOSD = RHOS ; RHOD = RHO
            ZZSD = ZZS ; ZZD = ZZ
            DEL_RHO_D_DEL_ZD = DEL_RHO_D_DEL_Z
            SWORK4D = DEL_RHO_D_DEL_Z
            TMPD = TMP
            RSUMD = RSUM
            QD = Q
            QRD = QR
            CHI_RD = CHI_R
            MIX_TIMED = MIX_TIME
            D_SOURCED = 0._EB
            M_DOT_PPPD = 0._EB
            IF (HAS_D_SOURCE) D_SOURCED = D_SOURCE
            IF (HAS_M_DOT_PPP) THEN
                DO N=1,N_TRACKED_SPECIES
                    M_DOT_PPPD(:,:,:,N) = M_DOT_PPP(:,:,:,N)
                ENDDO
            ENDIF
            MUD = MU
            MU_DNSD = MU_DNS
            KRESD = KRES
            HD = H
            HSD = HS
            DDDTD = DDDT
            FVXD = FVX
            FVYD = FVY
            FVZD = FVZ
            FVX_BD = FVX_B
            FVY_BD = FVY_B
            FVZ_BD = FVZ_B
            PRHSD = 0._EB

            CALL INITIALIZE_GPU_POISSON_SOLVER(NM,DX(1),DY(1),DZ(1),LBC,MBC,NBC,SAVE1)
            GM => GPU_MESHES(NM)
            GM%INITIALIZED = .TRUE.

        END SUBROUTINE INIT_GPU_VALUES

        !--------------------------------------------------------------------------
        ! CUDA stream lifecycle
        !--------------------------------------------------------------------------
        SUBROUTINE INIT_GPU_STREAM
            INTEGER :: NM

            DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
                CALL GPU_CREATE_STREAM(GPU_MESHES(NM)%STRM)
            ENDDO
        END SUBROUTINE INIT_GPU_STREAM

        SUBROUTINE RELEASE_GPU_STREAMS
            IMPLICIT NONE

            INTEGER :: NM,ISTAT

            IF (.NOT.ALLOCATED(GPU_MESHES)) RETURN
            DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
                GM => GPU_MESHES(NM)
                ISTAT = cudaStreamDestroy(GM%STRM)
                GM%STRM = 0
            ENDDO

        END SUBROUTINE RELEASE_GPU_STREAMS

END MODULE G_INIT
