    REAL(EB), DEVICE, ALLOCATABLE :: AIT_ZONE_DATA_D(:,:,:)
    LOGICAL, DEVICE, ALLOCATABLE :: AIT_ZONE_ACTIVE_D(:,:)
    INTEGER, ALLOCATABLE :: AIT_ZONE_DEVC_H(:,:)
    LOGICAL, ALLOCATABLE :: AIT_ZONE_ACTIVE_H(:,:),AIT_ZONE_PREVIOUS_H(:,:)
    LOGICAL :: AIT_HAS_DEVICES = .FALSE.

    CONTAINS

        SUBROUTINE UPDATE_GPU_AIT_ZONES
            INTEGER :: NR,IZ,ND,NZ
            INTEGER, ALLOCATABLE :: COUNTS_H(:)
            REAL(EB), ALLOCATABLE :: DATA_H(:,:,:)

            IF (.NOT.ALLOCATED(AIT_ZONE_COUNT_D)) THEN
                NZ = MAX(1,MAXVAL(REACTION(1:N_REACTIONS)%N_AIT_EXCLUSION_ZONES))
                ALLOCATE(COUNTS_H(N_REACTIONS),DATA_H(7,NZ,N_REACTIONS))
                ALLOCATE(AIT_ZONE_COUNT_D(N_REACTIONS),AIT_ZONE_DATA_D(7,NZ,N_REACTIONS))
                ALLOCATE(AIT_ZONE_ACTIVE_D(NZ,N_REACTIONS),AIT_ZONE_DEVC_H(NZ,N_REACTIONS))
                ALLOCATE(AIT_ZONE_ACTIVE_H(NZ,N_REACTIONS),AIT_ZONE_PREVIOUS_H(NZ,N_REACTIONS))
                DATA_H = 0._EB
                AIT_ZONE_DEVC_H = 0
                AIT_ZONE_ACTIVE_H = .TRUE.
                DO NR=1,N_REACTIONS
                    COUNTS_H(NR) = REACTION(NR)%N_AIT_EXCLUSION_ZONES
                    DO IZ=1,COUNTS_H(NR)
                        DATA_H(:,IZ,NR) = (/ REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%X1, &
                            REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%X2,REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%Y1, &
                            REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%Y2,REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%Z1, &
                            REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%Z2,REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%AIT /)
                        ND = REACTION(NR)%AIT_EXCLUSION_ZONE(IZ)%DEVC_INDEX
                        AIT_ZONE_DEVC_H(IZ,NR) = ND
                        IF (ND>0) THEN
                            AIT_HAS_DEVICES = .TRUE.
                            AIT_ZONE_ACTIVE_H(IZ,NR) = DEVICE(ND)%CURRENT_STATE
                        ENDIF
                    ENDDO
                ENDDO
                AIT_ZONE_COUNT_D = COUNTS_H
                AIT_ZONE_DATA_D = DATA_H
                AIT_ZONE_ACTIVE_D = AIT_ZONE_ACTIVE_H
                AIT_ZONE_PREVIOUS_H = AIT_ZONE_ACTIVE_H
            ENDIF

            IF (.NOT.AIT_HAS_DEVICES) RETURN
            DO NR=1,N_REACTIONS
                DO IZ=1,REACTION(NR)%N_AIT_EXCLUSION_ZONES
                    ND = AIT_ZONE_DEVC_H(IZ,NR)
                    IF (ND>0) AIT_ZONE_ACTIVE_H(IZ,NR) = DEVICE(ND)%CURRENT_STATE
                ENDDO
            ENDDO
            IF (ANY(AIT_ZONE_ACTIVE_H .NEQV. AIT_ZONE_PREVIOUS_H)) THEN
                ! Finish readers on all mesh streams before changing the shared zone states.
                CALL GPU_WAIT_ALL
                AIT_ZONE_ACTIVE_D = AIT_ZONE_ACTIVE_H
                AIT_ZONE_PREVIOUS_H = AIT_ZONE_ACTIVE_H
            ENDIF
        END SUBROUTINE UPDATE_GPU_AIT_ZONES

        !--------------------------------------------------------------------------
        ! Combustion host orchestration
        !--------------------------------------------------------------------------
        SUBROUTINE COMBUSTION_LOAD_BALANCED_GPU(T,DT)

            REAL(EB), INTENT(IN) :: T,DT
            REAL(EB) :: TNOW

            TNOW=CURRENT_TIME()
            T_CHEM_ODE = 0._EB
            T_CHEM_COMM = 0._EB

            IF (N_REACTIONS==0) RETURN

            CALL COMBUSTION_GENERAL_LOAD_BALANCED_GPU(T,DT)

            T_USED(10) = T_USED(10) + CURRENT_TIME() - TNOW - T_CHEM_ODE - T_CHEM_COMM
            T_USED(11) = T_USED(11) + T_CHEM_COMM
            T_USED(16) = T_USED(16) + T_CHEM_ODE

        END SUBROUTINE COMBUSTION_LOAD_BALANCED_GPU

        SUBROUTINE COMBUSTION_GENERAL_LOAD_BALANCED_GPU(T,DT)

            REAL(EB), INTENT(IN) :: T,DT
            INTEGER :: NM,CHEM_CELL_MAX,ACTIVE_CELL_MAX,N
            INTEGER :: CHEM_MODEL_THREADS,CHEM_MODEL_BLOCKS,SOURCE_THREADS,SOURCE_BLOCKS,ZERO_BLOCKS
            REAL(EB),DEVICE,POINTER,CONTIGUOUS,DIMENSION(:,:) :: DZZ_MODEL_D,ZZ_GET_MODEL_D,REAC_SOURCE_TERM_MODEL_D,Q_REAC_MODEL_D
            INTEGER,DEVICE,POINTER,CONTIGUOUS,DIMENSION(:) :: CHEM_SUBIT_MODEL_D

            CALL UPDATE_GPU_AIT_ZONES

            MESH_LOOP_SERIAL : DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
                CALL POINT_TO_MESH(NM)
                GM => GPU_MESHES(NM)
                CHEM_CELL_MAX = MAX(1,IBAR*JBAR*KBAR)
                ACTIVE_CELL_MAX = MAX(1,IBP1*JBP1*KBP1)

                CALL COMBUSTION_ZERO_CELL_FIELDS_GPU<<<GM%GRDD_3D_BP1,GM%BLKD_3D_BP1,0,GM%STRM>>>( &
                    GM%QD,GM%CHI_RD,IBP1,JBP1,KBP1)

                IF (GPU_DEBUG_H2D_D2H) THEN
                    GM%ZZD = ZZ
                    GM%TMPD = TMP
                    GM%RHOD = RHO
                    GM%HD = H
                    GM%KRESD = KRES
                    GM%MUD = MU
                    DO N=LBOUND(PBAR,2),UBOUND(PBAR,2)
                        GM%PBARD(:,N) = PBAR(:,N)
                    ENDDO
                    GM%D_SOURCED = D_SOURCE
                    DO N=1,N_TRACKED_SPECIES
                        GM%M_DOT_PPPD(:,:,:,N) = M_DOT_PPP(:,:,:,N)
                    ENDDO
                ENDIF

                IF (.NOT.ALLOCATED(GM%FIRE%ZZ_GET_MODEL_D)) THEN
                    ALLOCATE(GM%FIRE%ZZ_GET_MODEL_D(1:N_TRACKED_SPECIES,1:CHEM_CELL_MAX))
                    ALLOCATE(GM%FIRE%DZZ_MODEL_D(1:N_TRACKED_SPECIES,1:CHEM_CELL_MAX))
                    ALLOCATE(GM%FIRE%REAC_SOURCE_TERM_MODEL_D(1:N_TRACKED_SPECIES,1:CHEM_CELL_MAX))
                    ALLOCATE(GM%FIRE%Q_REAC_MODEL_D(1:N_REACTIONS,1:CHEM_CELL_MAX))
                    ALLOCATE(GM%FIRE%CHEM_SUBIT_MODEL_D(1:CHEM_CELL_MAX))
                ENDIF
                ZZ_GET_MODEL_D => GM%FIRE%ZZ_GET_MODEL_D
                DZZ_MODEL_D => GM%FIRE%DZZ_MODEL_D
                REAC_SOURCE_TERM_MODEL_D => GM%FIRE%REAC_SOURCE_TERM_MODEL_D
                Q_REAC_MODEL_D => GM%FIRE%Q_REAC_MODEL_D
                CHEM_SUBIT_MODEL_D => GM%FIRE%CHEM_SUBIT_MODEL_D

                CHEM_MODEL_THREADS = 128
                CHEM_MODEL_BLOCKS = (CHEM_CELL_MAX + CHEM_MODEL_THREADS - 1) / CHEM_MODEL_THREADS
                ZERO_BLOCKS = (ACTIVE_CELL_MAX + CHEM_MODEL_THREADS - 1) / CHEM_MODEL_THREADS
                CALL COMBUSTION_ZERO_MODEL_WORK_GPU<<<ZERO_BLOCKS,CHEM_MODEL_THREADS,0,GM%STRM>>>( &
                    ZZ_GET_MODEL_D,DZZ_MODEL_D,REAC_SOURCE_TERM_MODEL_D,Q_REAC_MODEL_D,CHEM_SUBIT_MODEL_D, &
                    GM%FIRE%ACTIVE_CELLS_D,GM%FIRE%N_ACTIVE_CELLS_D,GM%FIRE%N_ACTIVE_CC_D, &
                    CHEM_CELL_MAX,ACTIVE_CELL_MAX,N_TRACKED_SPECIES,N_REACTIONS)

                CALL COMBUSTION_ACTIVE_CELL_LIST_GPU<<<GM%GRDD_3D_BP1,GM%BLKD_3D_BP1,0,GM%STRM>>>( &
                    GM%ZZD,GM%CELL_INDEXD,GM%CELL_SOLID,GM%FIRE%ACTIVE_CELLS_D, &
                    GM%FIRE%N_ACTIVE_CELLS_D(1),GM%FIRE%N_ACTIVE_CC_D(1), &
                    REAC_N_SMIX_RD,REAC_REACTANT_INDEXD,IBAR,JBAR,KBAR,N_TRACKED_SPECIES,N_REACTIONS,ZZ_MIN_GLOBAL)

                CALL COMBUSTION_MODEL_GPU_KERNEL<<<CHEM_MODEL_BLOCKS,CHEM_MODEL_THREADS,0,GM%STRM>>>( &
                    GM%FIRE%N_ACTIVE_CELLS_D(1),GM%FIRE%ACTIVE_CELLS_D,GM%ZZD,ZZ_GET_MODEL_D,DZZ_MODEL_D,CHEM_SUBIT_MODEL_D, &
                    REAC_SOURCE_TERM_MODEL_D,Q_REAC_MODEL_D,GM%PBARD,GM%PRESSURE_ZONED, &
                    GM%RHOD,GM%HD,GM%KRESD,GM%TMPD,GM%MUD,GM%LES_FILTER_WIDTHD,GM%DXD,GM%DYD,GM%DZD, &
                    GM%XCD,GM%YCD,GM%ZCD, &
                    GM%QD,GM%MIX_TIMED,GM%CHI_RD, &
                    D_Z_TABLED,SPECIES_H_FD,SPECIES_Z2Y_O2D,REAC_FUEL_SMIX_INDEXD,REAC_AIR_SMIX_INDEXD, &
                    REAC_AUTO_IGNITION_TEMPERATURED,REAC_CHI_RD,REAC_NU_MW_O_MW_FD, &
                    REAC_CRITICAL_FLAME_TEMPERATURED,REAC_Y_O2_MIND, &
                    REAC_A_PRIMED,REAC_RHO_EXPONENTD,REAC_HEAT_OF_COMBUSTIOND,REAC_PRIORITYD,REAC_FAST_CHEMISTRYD, &
                    T,DT,TAU_CHEM,TAU_FLAME,C_DEARDORFF,GRAV,INITIAL_UNMIXED_FRACTION,ZZ_MIN_GLOBAL, &
                    CHI_R_MIN,CHI_R_MAX,TWO_EPSILON_EB,TINY_EB,HUGE(1._EB),FREE_BURN_TEMPERATURE,TMPA, &
                    IBAR,JBAR,KBAR,N_TRACKED_SPECIES,N_REACTIONS,I_MAX_TEMP,MAX_CHEMISTRY_SUBSTEPS, &
                    COMBUSTION_ODE_SOLVER,EXPLICIT_EULER,EXTINCT_MOD,EXTINCTION_1,MAX_PRIORITY,SUPPRESSION, &
                    OUTPUT_CHEM_IT,REAC_SOURCE_CHECK)

                SOURCE_THREADS = 128
                SOURCE_BLOCKS = (CHEM_CELL_MAX + SOURCE_THREADS - 1) / SOURCE_THREADS
                CALL SET_SPECIES_SOURCE_TERM_CELL_GPU<<<SOURCE_BLOCKS,SOURCE_THREADS,0,GM%STRM>>>( &
                    GM%FIRE%N_ACTIVE_CELLS_D(1),GM%FIRE%ACTIVE_CELLS_D,ZZ_GET_MODEL_D,DZZ_MODEL_D, &
                    GM%D_SOURCED,GM%M_DOT_PPPD,GM%TMPD,GM%RHOD,CP_ZD,H_SENS_ZD,MWR_ZD,SPECIES_RCOND, &
                    DT,DZZ_CLIP,R0,IBAR,JBAR,KBAR,N_TRACKED_SPECIES,I_MAX_TEMP)

                IF (GPU_DEBUG_H2D_D2H) THEN
                    CALL GPU_WAIT(GM%STRM)
                    Q = GM%QD
                    CHI_R = GM%CHI_RD
                    D_SOURCE = GM%D_SOURCED
                    DO N=1,N_TRACKED_SPECIES
                        M_DOT_PPP(:,:,:,N) = GM%M_DOT_PPPD(:,:,:,N)
                    ENDDO
                ENDIF

                IF (STOP_STATUS/=NO_STOP) RETURN

            ENDDO MESH_LOOP_SERIAL

        END SUBROUTINE COMBUSTION_GENERAL_LOAD_BALANCED_GPU

        !--------------------------------------------------------------------------
        ! Combustion CUDA kernels and per-cell device helpers
        !--------------------------------------------------------------------------
        ATTRIBUTES(GLOBAL) SUBROUTINE COMBUSTION_ZERO_CELL_FIELDS_GPU(QD,CHI_RD,IBP1,JBP1,KBP1)
            INTEGER, VALUE :: IBP1,JBP1,KBP1
            REAL(EB), DEVICE, DIMENSION(0:IBP1,0:JBP1,0:*) :: QD,CHI_RD
            INTEGER :: I,J,K

            I = (BLOCKIDX%X - 1)*BLOCKDIM%X + THREADIDX%X - 1
            J = (BLOCKIDX%Y - 1)*BLOCKDIM%Y + THREADIDX%Y - 1
            K = (BLOCKIDX%Z - 1)*BLOCKDIM%Z + THREADIDX%Z - 1
            IF (I<0 .OR. I>IBP1 .OR. J<0 .OR. J>JBP1 .OR. K<0 .OR. K>KBP1) RETURN
            QD(I,J,K) = 0._EB
            CHI_RD(I,J,K) = 0._EB
        END SUBROUTINE COMBUSTION_ZERO_CELL_FIELDS_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE COMBUSTION_ZERO_MODEL_WORK_GPU( &
            ZZ_GET_MODEL_D,DZZ_MODEL_D,REAC_SOURCE_TERM_MODEL_D,Q_REAC_MODEL_D,CHEM_SUBIT_MODEL_D, &
            ACTIVE_CELLS_D,N_ACTIVE_CELLS_D,N_ACTIVE_CC_D,CHEM_CELL_MAX_IN,ACTIVE_CELL_MAX_IN, &
            N_TRACKED_SPECIES_IN,N_REACTIONS_IN)
            INTEGER, VALUE :: CHEM_CELL_MAX_IN,ACTIVE_CELL_MAX_IN,N_TRACKED_SPECIES_IN,N_REACTIONS_IN
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: ZZ_GET_MODEL_D,DZZ_MODEL_D
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_SOURCE_TERM_MODEL_D
            REAL(EB), DEVICE, DIMENSION(1:N_REACTIONS_IN,1:*) :: Q_REAC_MODEL_D
            INTEGER, DEVICE, DIMENSION(1:*) :: CHEM_SUBIT_MODEL_D,N_ACTIVE_CELLS_D,N_ACTIVE_CC_D
            INTEGER, DEVICE, DIMENSION(1:ACTIVE_CELL_MAX_IN,1:*) :: ACTIVE_CELLS_D
            INTEGER :: NC,N,NR

            NC = (BLOCKIDX%X - 1)*BLOCKDIM%X + THREADIDX%X
            IF (NC==1) THEN
                N_ACTIVE_CELLS_D(1) = 0
                N_ACTIVE_CC_D(1) = 0
            ENDIF
            IF (NC<=ACTIVE_CELL_MAX_IN) THEN
                ACTIVE_CELLS_D(NC,1) = -1
                ACTIVE_CELLS_D(NC,2) = -1
                ACTIVE_CELLS_D(NC,3) = -1
            ENDIF
            IF (NC>CHEM_CELL_MAX_IN) RETURN

            CHEM_SUBIT_MODEL_D(NC) = 0
            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_GET_MODEL_D(N,NC) = 0._EB
                DZZ_MODEL_D(N,NC) = 0._EB
                REAC_SOURCE_TERM_MODEL_D(N,NC) = 0._EB
            ENDDO
            DO NR=1,N_REACTIONS_IN
                Q_REAC_MODEL_D(NR,NC) = 0._EB
            ENDDO
        END SUBROUTINE COMBUSTION_ZERO_MODEL_WORK_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE COMBUSTION_ACTIVE_CELL_LIST_GPU( &
            ZZPD,CELL_INDEXD_IN,CELL_SOLID_IN,CHEM_ACTIVE_CELLS_OUT, &
            NCHEM_ACTIVE_CELLS_OUT,NCHEM_ACTIVE_CC_OUT,REAC_N_SMIX_R_IN,REAC_REACTANT_INDEX_IN, &
            IBAR_IN,JBAR_IN,KBAR_IN,N_TRACKED_SPECIES_IN,N_REACTIONS_IN,ZZ_MIN_IN)

            INTEGER, VALUE :: IBAR_IN,JBAR_IN,KBAR_IN,N_TRACKED_SPECIES_IN,N_REACTIONS_IN
            REAL(EB), VALUE :: ZZ_MIN_IN
            REAL(EB), DEVICE, DIMENSION(0:IBAR_IN+1,0:JBAR_IN+1,0:KBAR_IN+1,1:*) :: ZZPD
            INTEGER, DEVICE, DIMENSION(0:IBAR_IN+1,0:JBAR_IN+1,0:*) :: CELL_INDEXD_IN
            LOGICAL, DEVICE, DIMENSION(0:*) :: CELL_SOLID_IN
            INTEGER, DEVICE, DIMENSION(1:(IBAR_IN+1)*(JBAR_IN+1)*(KBAR_IN+1),1:*) :: CHEM_ACTIVE_CELLS_OUT
            INTEGER, DEVICE :: NCHEM_ACTIVE_CELLS_OUT,NCHEM_ACTIVE_CC_OUT
            INTEGER, DEVICE, DIMENSION(1:*) :: REAC_N_SMIX_R_IN
            INTEGER, DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_REACTANT_INDEX_IN

            INTEGER :: I,J,K,IC,NR,NS,REACTANT_INDEX,NC,IERR
            LOGICAL :: REACTANTS_PRESENT

            I = (blockIdx%x - 1) * blockDim%x + threadIdx%x - 1
            J = (blockIdx%y - 1) * blockDim%y + threadIdx%y - 1
            K = (blockIdx%z - 1) * blockDim%z + threadIdx%z - 1

            IF (I < 1 .OR. I > IBAR_IN) RETURN
            IF (J < 1 .OR. J > JBAR_IN) RETURN
            IF (K < 1 .OR. K > KBAR_IN) RETURN

            IC = CELL_INDEXD_IN(I,J,K)
            IF (CELL_SOLID_IN(IC)) RETURN

            DO NR=1,N_REACTIONS_IN
                REACTANTS_PRESENT = .TRUE.
                DO NS=1,REAC_N_SMIX_R_IN(NR)
                    REACTANT_INDEX = REAC_REACTANT_INDEX_IN(NS,NR)
                    IF (REACTANT_INDEX < 1) THEN
                        REACTANTS_PRESENT = .FALSE.
                        EXIT
                    ENDIF
                    IF (ZZPD(I,J,K,REACTANT_INDEX) < ZZ_MIN_IN) THEN
                        REACTANTS_PRESENT = .FALSE.
                        EXIT
                    ENDIF
                ENDDO
                IF (.NOT. REACTANTS_PRESENT) CYCLE
                IERR = atomicAdd(NCHEM_ACTIVE_CELLS_OUT,1)
                NC = IERR + 1
                CHEM_ACTIVE_CELLS_OUT(NC,1) = I
                CHEM_ACTIVE_CELLS_OUT(NC,2) = J
                CHEM_ACTIVE_CELLS_OUT(NC,3) = K
                RETURN
            ENDDO

        END SUBROUTINE COMBUSTION_ACTIVE_CELL_LIST_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE COMBUSTION_MODEL_GPU_KERNEL( &
            NCHEM_ACTIVE_CELLS_IN,CHEM_ACTIVE_CELLS_IN,ZZ_D,ZZ_GET_WORKD,DZZ_WORKD,CHEM_SUBIT_WORKD, &
            REAC_SOURCE_TERM_WORKD,Q_REAC_WORKD,PBAR_D,PRESSURE_ZONE_D, &
            RHO_D,H_D,KRES_D,TMP_D,MU_D,LES_FILTER_WIDTH_D,DX_D,DY_D,DZ_D,XC_D,YC_D,ZC_D,Q_D,MIX_TIME_D,CHI_R_D, &
            D_Z_D,SPECIES_H_F_D,SPECIES_Z2Y_O2_D,REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D, &
            REAC_AUTO_IGNITION_TEMPERATURE_D,REAC_CHI_R_D,REAC_NU_MW_O_MW_F_D, &
            REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D, &
            REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D,REAC_PRIORITY_D,REAC_FAST_CHEMISTRY_D, &
            T_IN,DT_IN,TAU_CHEM_IN,TAU_FLAME_IN,C_DEARDORFF_IN,GRAV_IN,INITIAL_UNMIXED_FRACTION_IN,ZZ_MIN_IN, &
            CHI_R_MIN_IN,CHI_R_MAX_IN,TWO_EPS_IN,TINY_IN,HUGE_IN,FREE_BURN_TEMPERATURE_IN,TMPA_IN, &
            IBAR_IN,JBAR_IN,KBAR_IN,N_TRACKED_SPECIES_IN,N_REACTIONS_IN,I_MAX_TEMP_IN,MAX_CHEMISTRY_SUBSTEPS_IN, &
            COMBUSTION_ODE_SOLVER_IN,EXPLICIT_EULER_IN,EXTINCT_MOD_IN,EXTINCTION_1_IN,MAX_PRIORITY_IN,SUPPRESSION_IN, &
            OUTPUT_CHEM_IT_IN,REAC_SOURCE_CHECK_IN)

            INTEGER, VALUE :: IBAR_IN,JBAR_IN,KBAR_IN,N_TRACKED_SPECIES_IN,N_REACTIONS_IN
            INTEGER, VALUE :: I_MAX_TEMP_IN,MAX_CHEMISTRY_SUBSTEPS_IN,COMBUSTION_ODE_SOLVER_IN,EXPLICIT_EULER_IN
            INTEGER, VALUE :: EXTINCT_MOD_IN,EXTINCTION_1_IN,MAX_PRIORITY_IN
            REAL(EB), VALUE :: T_IN,DT_IN,TAU_CHEM_IN,TAU_FLAME_IN,C_DEARDORFF_IN,GRAV_IN,INITIAL_UNMIXED_FRACTION_IN
            REAL(EB), VALUE :: ZZ_MIN_IN,CHI_R_MIN_IN,CHI_R_MAX_IN,TWO_EPS_IN,TINY_IN,HUGE_IN,FREE_BURN_TEMPERATURE_IN,TMPA_IN
            LOGICAL, VALUE :: SUPPRESSION_IN,OUTPUT_CHEM_IT_IN,REAC_SOURCE_CHECK_IN
            INTEGER, DEVICE :: NCHEM_ACTIVE_CELLS_IN
            INTEGER, DEVICE, DIMENSION(1:(IBAR_IN+1)*(JBAR_IN+1)*(KBAR_IN+1),1:*) :: CHEM_ACTIVE_CELLS_IN
            INTEGER, DEVICE, DIMENSION(0:IBAR_IN+1,0:JBAR_IN+1,0:*) :: PRESSURE_ZONE_D
            REAL(EB), DEVICE, DIMENSION(0:IBAR_IN+1,0:JBAR_IN+1,0:KBAR_IN+1,1:*) :: ZZ_D
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: ZZ_GET_WORKD,DZZ_WORKD
            INTEGER, DEVICE, DIMENSION(1:*) :: CHEM_SUBIT_WORKD
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_SOURCE_TERM_WORKD
            REAL(EB), DEVICE, DIMENSION(1:N_REACTIONS_IN,1:*) :: Q_REAC_WORKD
            REAL(EB), DEVICE, DIMENSION(0:KBAR_IN+1,0:*) :: PBAR_D
            REAL(EB), DEVICE, DIMENSION(0:IBAR_IN+1,0:JBAR_IN+1,0:*) :: &
                RHO_D,H_D,KRES_D,TMP_D,MU_D,LES_FILTER_WIDTH_D,Q_D,MIX_TIME_D,CHI_R_D
            REAL(EB), DEVICE, DIMENSION(0:*) :: DX_D,DY_D,DZ_D
            REAL(EB), DEVICE, DIMENSION(0:*) :: XC_D,YC_D,ZC_D
            REAL(EB), DEVICE, DIMENSION(0:I_MAX_TEMP_IN,1:*) :: D_Z_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: SPECIES_H_F_D,SPECIES_Z2Y_O2_D,REAC_AUTO_IGNITION_TEMPERATURE_D,REAC_CHI_R_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_NU_MW_O_MW_F_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D
            INTEGER, DEVICE, DIMENSION(1:*) :: REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D
            LOGICAL, DEVICE, DIMENSION(1:*) :: REAC_FAST_CHEMISTRY_D

            INTEGER :: NC,I,J,K,N,IPZ
            REAL(EB) :: PRES,TMP_LOC,RHO_LOC,MU_LOC,DELTA_LOC,CELL_VOLUME

            NC = (blockIdx%x - 1) * blockDim%x + threadIdx%x
            IF (NC < 1 .OR. NC > NCHEM_ACTIVE_CELLS_IN) RETURN

            I = CHEM_ACTIVE_CELLS_IN(NC,1)
            J = CHEM_ACTIVE_CELLS_IN(NC,2)
            K = CHEM_ACTIVE_CELLS_IN(NC,3)
            IF (I < 1 .OR. I > IBAR_IN) RETURN
            IF (J < 1 .OR. J > JBAR_IN) RETURN
            IF (K < 1 .OR. K > KBAR_IN) RETURN

            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_GET_WORKD(N,NC) = ZZ_D(I,J,K,N)
                DZZ_WORKD(N,NC) = ZZ_GET_WORKD(N,NC)
            ENDDO

            IPZ = PRESSURE_ZONE_D(I,J,K)
            PRES = PBAR_D(K,IPZ) + RHO_D(I,J,K)*(H_D(I,J,K)-KRES_D(I,J,K))
            TMP_LOC = TMP_D(I,J,K)
            RHO_LOC = RHO_D(I,J,K)
            MU_LOC = MU_D(I,J,K)
            DELTA_LOC = LES_FILTER_WIDTH_D(I,J,K)
            CELL_VOLUME = DX_D(I)*DY_D(J)*DZ_D(K)

            CALL COMBUSTION_MODEL_DEVICE_FRAMEWORK( &
                  T_IN,DT_IN,ZZ_GET_WORKD,DZZ_WORKD,NC,Q_D(I,J,K),MIX_TIME_D(I,J,K),CHI_R_D(I,J,K), &
                  CHEM_SUBIT_WORKD,REAC_SOURCE_TERM_WORKD,Q_REAC_WORKD, &
                  TMP_LOC,RHO_LOC,PRES,MU_LOC,DELTA_LOC,CELL_VOLUME,XC_D(I),YC_D(J),ZC_D(K), &
                  D_Z_D,SPECIES_H_F_D,SPECIES_Z2Y_O2_D,REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D, &
                  REAC_AUTO_IGNITION_TEMPERATURE_D,REAC_CHI_R_D,REAC_NU_MW_O_MW_F_D, &
                  REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D, &
                  REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D,REAC_PRIORITY_D,REAC_FAST_CHEMISTRY_D, &
                  TAU_CHEM_IN,TAU_FLAME_IN,C_DEARDORFF_IN,GRAV_IN,INITIAL_UNMIXED_FRACTION_IN,ZZ_MIN_IN, &
                  CHI_R_MIN_IN,CHI_R_MAX_IN,TWO_EPS_IN,TINY_IN,HUGE_IN,FREE_BURN_TEMPERATURE_IN,TMPA_IN, &
                  N_TRACKED_SPECIES_IN,N_REACTIONS_IN,I_MAX_TEMP_IN,MAX_CHEMISTRY_SUBSTEPS_IN, &
                  COMBUSTION_ODE_SOLVER_IN,EXPLICIT_EULER_IN,EXTINCT_MOD_IN,EXTINCTION_1_IN,MAX_PRIORITY_IN,SUPPRESSION_IN, &
                  OUTPUT_CHEM_IT_IN,REAC_SOURCE_CHECK_IN)

        END SUBROUTINE COMBUSTION_MODEL_GPU_KERNEL

        ATTRIBUTES(DEVICE) SUBROUTINE COMBUSTION_MODEL_DEVICE_FRAMEWORK( &
            T_IN,DT_IN,ZZ_GET_WORKD,DZZ_WORKD,NC,Q_OUT,MIX_TIME_OUT,CHI_R_OUT, &
            CHEM_SUBIT_WORKD,REAC_SOURCE_TERM_WORKD,Q_REAC_WORKD, &
            TMP_IN,RHO_IN,PRES_IN,MU_IN,DELTA_IN,CELL_VOLUME_IN,X_IN,Y_IN,Z_IN, &
            D_Z_D,SPECIES_H_F_D,SPECIES_Z2Y_O2_D,REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D, &
            REAC_AUTO_IGNITION_TEMPERATURE_D,REAC_CHI_R_D,REAC_NU_MW_O_MW_F_D, &
            REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D, &
            REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D,REAC_PRIORITY_D,REAC_FAST_CHEMISTRY_D, &
            TAU_CHEM_IN,TAU_FLAME_IN,C_DEARDORFF_IN,GRAV_IN,INITIAL_UNMIXED_FRACTION_IN,ZZ_MIN_IN, &
            CHI_R_MIN_IN,CHI_R_MAX_IN,TWO_EPS_IN,TINY_IN,HUGE_IN,FREE_BURN_TEMPERATURE_IN,TMPA_IN, &
            N_TRACKED_SPECIES_IN,N_REACTIONS_IN,I_MAX_TEMP_IN,MAX_CHEMISTRY_SUBSTEPS_IN, &
            COMBUSTION_ODE_SOLVER_IN,EXPLICIT_EULER_IN,EXTINCT_MOD_IN,EXTINCTION_1_IN,MAX_PRIORITY_IN,SUPPRESSION_IN, &
            OUTPUT_CHEM_IT_IN,REAC_SOURCE_CHECK_IN)

            INTEGER, VALUE :: NC,N_TRACKED_SPECIES_IN,N_REACTIONS_IN,I_MAX_TEMP_IN,MAX_CHEMISTRY_SUBSTEPS_IN
            INTEGER, VALUE :: COMBUSTION_ODE_SOLVER_IN,EXPLICIT_EULER_IN,EXTINCT_MOD_IN,EXTINCTION_1_IN,MAX_PRIORITY_IN
            REAL(EB), VALUE :: T_IN,DT_IN,TMP_IN,RHO_IN,PRES_IN,MU_IN,DELTA_IN,CELL_VOLUME_IN
            REAL(EB), VALUE :: X_IN,Y_IN,Z_IN
            REAL(EB), VALUE :: TAU_CHEM_IN,TAU_FLAME_IN,C_DEARDORFF_IN,GRAV_IN,INITIAL_UNMIXED_FRACTION_IN
            REAL(EB), VALUE :: ZZ_MIN_IN,CHI_R_MIN_IN,CHI_R_MAX_IN,TWO_EPS_IN,TINY_IN,HUGE_IN,FREE_BURN_TEMPERATURE_IN,TMPA_IN
            LOGICAL, VALUE :: SUPPRESSION_IN,OUTPUT_CHEM_IT_IN,REAC_SOURCE_CHECK_IN
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: ZZ_GET_WORKD,DZZ_WORKD
            INTEGER, DEVICE, DIMENSION(1:*) :: CHEM_SUBIT_WORKD
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_SOURCE_TERM_WORKD
            REAL(EB), DEVICE, DIMENSION(1:N_REACTIONS_IN,1:*) :: Q_REAC_WORKD
            REAL(EB), DEVICE, DIMENSION(0:I_MAX_TEMP_IN,1:*) :: D_Z_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: SPECIES_H_F_D,SPECIES_Z2Y_O2_D,REAC_AUTO_IGNITION_TEMPERATURE_D,REAC_CHI_R_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_NU_MW_O_MW_F_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D
            INTEGER, DEVICE, DIMENSION(1:*) :: REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D
            LOGICAL, DEVICE, DIMENSION(1:*) :: REAC_FAST_CHEMISTRY_D
            REAL(EB) :: Q_OUT,MIX_TIME_OUT,CHI_R_OUT

            REAL(EB) :: A1(MAX_SPECIES),A2(MAX_SPECIES),A4(MAX_SPECIES)
            REAL(EB) :: ZZ_0(MAX_SPECIES),ZZ_MIXED(MAX_SPECIES),ZZ_MIXED_NEW(MAX_SPECIES)
            REAL(EB) :: ZZ_HAT_MIX(MAX_SPECIES),REACTION_DZZ(MAX_SPECIES)
            REAL(EB) :: Q_REAC_SUB(MAX_REACTIONS),Q_REAC_SUM(MAX_REACTIONS),Q_REAC_OUT(MAX_REACTIONS)
            REAL(EB) :: REAC_SOURCE_TERM_OUT(MAX_SPECIES)
            REAL(EB) :: ZETA,ZETA_0,DT_SUB,DT_SUB_NEW,DT_ITER,DT_SUB_MIN,CELL_MASS,RHO_HAT,TAU_MIX
            REAL(EB) :: D_F,TAU_D,TAU_U,TAU_G,C_U,ERR_TINY,Q_SUM_CHI_R,CHI_R_SUM,TOTAL_MIXED_MASS
            INTEGER :: NR,N,TIME_ITER,ITER,CHEM_SUBIT_OUT,RICH_ITER_MAX,ITMP_DZ
            LOGICAL :: EXTINCT,NO_REACTIONS

            IF (N_TRACKED_SPECIES_IN > MAX_SPECIES) RETURN
            IF (N_REACTIONS_IN > MAX_REACTIONS) RETURN

            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_0(N) = ZZ_GET_WORKD(N,NC)
            ENDDO
            EXTINCT = .FALSE.
            NO_REACTIONS = .FALSE.

            D_F = 0._EB
            ITMP_DZ = MAX(0,MIN(I_MAX_TEMP_IN-1,NINT(TMP_IN)))
            DO NR=1,N_REACTIONS_IN
                D_F = MAX(D_F,D_Z_D(ITMP_DZ,REAC_FUEL_SMIX_INDEX_D(NR)))
            ENDDO
            TAU_D = DELTA_IN**2/MAX(D_F,TWO_EPS_IN)

            C_U = 0.4_EB*C_DEARDORFF_IN*SQRT(1.5_EB)
            TAU_U = C_U*RHO_IN*DELTA_IN**2/MAX(MU_IN,TWO_EPS_IN)
            TAU_G = SQRT(2._EB*DELTA_IN/(GRAV_IN+1.E-10_EB))
            MIX_TIME_OUT = MAX(TAU_CHEM_IN,MIN(TAU_D,TAU_U,TAU_G,TAU_FLAME_IN))

            ZETA_0 = INITIAL_UNMIXED_FRACTION_IN
            CELL_MASS = RHO_IN*CELL_VOLUME_IN

            DT_SUB_MIN = DT_IN/REAL(MAX_CHEMISTRY_SUBSTEPS_IN,EB)

            Q_OUT = 0._EB
            ITER = 0
            DT_ITER = 0._EB
            CHI_R_OUT = 0._EB
            CHEM_SUBIT_OUT = 0
            DO N=1,N_TRACKED_SPECIES_IN
                REAC_SOURCE_TERM_OUT(N) = 0._EB
            ENDDO
            DO NR=1,N_REACTIONS_IN
                Q_REAC_OUT(NR) = 0._EB
                Q_REAC_SUM(NR) = 0._EB
                Q_REAC_SUB(NR) = 0._EB
            ENDDO

            DT_SUB = DT_IN
            DT_SUB_NEW = DT_IN
            RICH_ITER_MAX = 5

            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_MIXED(N) = ZZ_GET_WORKD(N,NC)
                A1(N) = ZZ_GET_WORKD(N,NC)
                A2(N) = ZZ_GET_WORKD(N,NC)
                A4(N) = ZZ_GET_WORKD(N,NC)
                ZZ_MIXED_NEW(N) = ZZ_GET_WORKD(N,NC)
            ENDDO

            ZETA = ZETA_0
            RHO_HAT = RHO_IN
            TAU_MIX = MIX_TIME_OUT

            ERR_TINY = TINY_IN

            INTEGRATION_LOOP_GPU: DO TIME_ITER=1,MAX_CHEMISTRY_SUBSTEPS_IN

                IF (SUPPRESSION_IN) THEN
                    DO NR=1,N_REACTIONS_IN
                        IF (ZZ_0(REAC_FUEL_SMIX_INDEX_D(NR))>ZZ_MIN_IN .AND. ZZ_0(REAC_AIR_SMIX_INDEX_D(NR))>ZZ_MIN_IN) THEN
                            CALL CHECK_AUTO_IGNITION_DEVICE(EXTINCT,TMP_IN,REAC_AUTO_IGNITION_TEMPERATURE_D(NR), &
                                                           X_IN,Y_IN,Z_IN,NR)
                            IF (.NOT. EXTINCT) EXIT
                        ENDIF
                    ENDDO
                ENDIF

                IF (EXTINCT) EXIT INTEGRATION_LOOP_GPU

                IF (COMBUSTION_ODE_SOLVER_IN == EXPLICIT_EULER_IN) THEN
                    CALL FIRE_FORWARD_EULER_DEVICE(ZZ_MIXED_NEW,ZZ_MIXED,ZZ_0,ZETA,ZETA_0,DT_SUB,TMP_IN,RHO_HAT, &
                                                             CELL_MASS,TAU_MIX,Q_REAC_SUB,TOTAL_MIXED_MASS,NO_REACTIONS, &
                                                             ZZ_HAT_MIX,REACTION_DZZ, &
                                                             REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D,REAC_FAST_CHEMISTRY_D, &
                                                             REAC_NU_MW_O_MW_F_D,REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D, &
                                                             N_TRACKED_SPECIES_IN,N_REACTIONS_IN,MAX_PRIORITY_IN,TWO_EPS_IN,HUGE_IN)
                    ZETA_0 = ZETA
                    DO N=1,N_TRACKED_SPECIES_IN
                        ZZ_MIXED(N) = ZZ_MIXED_NEW(N)
                    ENDDO
                ENDIF

                CALL GET_REALIZABLE_MF_DEVICE(ZZ_MIXED,N_TRACKED_SPECIES_IN)
                DO N=1,N_TRACKED_SPECIES_IN
                    ZZ_GET_WORKD(N,NC) = ZETA*ZZ_0(N) + (1._EB-ZETA)*ZZ_MIXED(N)
                ENDDO
                DT_ITER = DT_ITER + DT_SUB
                ITER = ITER + 1
                IF (OUTPUT_CHEM_IT_IN) CHEM_SUBIT_OUT = ITER

                DO NR=1,N_REACTIONS_IN
                    Q_REAC_SUM(NR) = Q_REAC_SUM(NR) + Q_REAC_SUB(NR)
                ENDDO

                IF (DT_ITER > (DT_IN-TWO_EPS_IN)) EXIT INTEGRATION_LOOP_GPU
            ENDDO INTEGRATION_LOOP_GPU

            Q_OUT = 0._EB
            DO N=1,N_TRACKED_SPECIES_IN
                Q_OUT = Q_OUT - RHO_IN*SPECIES_H_F_D(N)*(ZZ_GET_WORKD(N,NC)-ZZ_0(N))/DT_IN
            ENDDO

            IF (SUPPRESSION_IN .AND. .NOT. EXTINCT) THEN
                IF (EXTINCT_MOD_IN == EXTINCTION_1_IN) THEN
                    CALL EXTINCT_1_DEVICE(EXTINCT,ZZ_0,TMP_IN,SPECIES_Z2Y_O2_D, &
                                                 REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D, &
                                                 FREE_BURN_TEMPERATURE_IN,TMPA_IN,N_TRACKED_SPECIES_IN)
                ELSEIF (EXTINCT_MOD_IN == EXTINCTION_2) THEN
                    CALL EXTINCT_2_DEVICE(EXTINCT,ZZ_0,ZZ_MIXED,TMP_IN,REAC_FUEL_SMIX_INDEX_D, &
                        REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D,REAC_CRITICAL_FLAME_TEMPERATURE_D, &
                        N_TRACKED_SPECIES_IN,N_REACTIONS_IN,I_MAX_TEMP_IN,TWO_EPS_IN)
                ENDIF
            ENDIF

            IF (EXTINCT) THEN
                DO N=1,N_TRACKED_SPECIES_IN
                    ZZ_GET_WORKD(N,NC) = ZZ_0(N)
                ENDDO
                Q_OUT = 0._EB
                CHI_R_OUT = 0._EB
                CHEM_SUBIT_OUT = 0
                DO N=1,N_TRACKED_SPECIES_IN
                    REAC_SOURCE_TERM_OUT(N) = 0._EB
                ENDDO
                DO NR=1,N_REACTIONS_IN
                    Q_REAC_OUT(NR) = 0._EB
                    Q_REAC_SUM(NR) = 0._EB
                ENDDO
            ENDIF

            Q_SUM_CHI_R = 0._EB
            CHI_R_SUM = 0._EB
            DO NR=1,N_REACTIONS_IN
                IF (Q_REAC_SUM(NR) > TWO_EPS_IN) THEN
                    CHI_R_SUM = CHI_R_SUM + Q_REAC_SUM(NR)*REAC_CHI_R_D(NR)
                    Q_SUM_CHI_R = Q_SUM_CHI_R + Q_REAC_SUM(NR)
                ENDIF
            ENDDO
            IF (Q_SUM_CHI_R > TWO_EPS_IN) CHI_R_OUT = CHI_R_SUM/Q_SUM_CHI_R
            CHI_R_OUT = MAX(CHI_R_MIN_IN,MIN(CHI_R_MAX_IN,CHI_R_OUT))

            CHEM_SUBIT_WORKD(NC) = CHEM_SUBIT_OUT
            IF (REAC_SOURCE_CHECK_IN) THEN
                DO N=1,N_TRACKED_SPECIES_IN
                    REAC_SOURCE_TERM_OUT(N) = RHO_IN*(ZZ_GET_WORKD(N,NC)-ZZ_0(N))/DT_IN
                    REAC_SOURCE_TERM_WORKD(N,NC) = REAC_SOURCE_TERM_OUT(N)
                ENDDO
                DO NR=1,N_REACTIONS_IN
                    Q_REAC_OUT(NR) = Q_REAC_SUM(NR)/CELL_VOLUME_IN/DT_IN
                    Q_REAC_WORKD(NR,NC) = Q_REAC_OUT(NR)
                ENDDO
            ELSE
                DO N=1,N_TRACKED_SPECIES_IN
                    REAC_SOURCE_TERM_WORKD(N,NC) = 0._EB
                ENDDO
                DO NR=1,N_REACTIONS_IN
                    Q_REAC_WORKD(NR,NC) = 0._EB
                ENDDO
            ENDIF

        END SUBROUTINE COMBUSTION_MODEL_DEVICE_FRAMEWORK

        ATTRIBUTES(DEVICE) SUBROUTINE FIRE_FORWARD_EULER_DEVICE( &
            ZZ_OUT,ZZ_IN,ZZ_0,ZETA_OUT,ZETA_IN,DT_LOC,TMP_IN,RHO_HAT,CELL_MASS,TAU_MIX, &
            Q_REAC_LOC,TOTAL_MIXED_MASS,NO_REACTIONS,ZZ_HAT_MIX_OUT,REACTION_DZZ_OUT, &
            REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D,REAC_FAST_CHEMISTRY_D, &
            REAC_NU_MW_O_MW_F_D,REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D, &
            N_TRACKED_SPECIES_IN,N_REACTIONS_IN,MAX_PRIORITY_IN,TWO_EPS_IN,HUGE_IN)

            INTEGER, VALUE :: N_TRACKED_SPECIES_IN,N_REACTIONS_IN,MAX_PRIORITY_IN
            REAL(EB), VALUE :: DT_LOC,TMP_IN,RHO_HAT,CELL_MASS,TAU_MIX,TWO_EPS_IN,HUGE_IN
            REAL(EB) :: ZZ_OUT(MAX_SPECIES),ZZ_IN(MAX_SPECIES),ZZ_0(MAX_SPECIES)
            REAL(EB) :: ZETA_OUT,ZETA_IN,Q_REAC_LOC(MAX_REACTIONS),TOTAL_MIXED_MASS
            REAL(EB) :: ZZ_HAT_MIX_OUT(MAX_SPECIES),REACTION_DZZ_OUT(MAX_SPECIES)
            LOGICAL :: NO_REACTIONS
            INTEGER, DEVICE, DIMENSION(1:*) :: REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D
            LOGICAL, DEVICE, DIMENSION(1:*) :: REAC_FAST_CHEMISTRY_D
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_NU_MW_O_MW_F_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D

            REAL(EB) :: ZZ_HAT(MAX_SPECIES),DZZ(MAX_SPECIES),MIXED_MASS(MAX_SPECIES),MIXED_MASS_0(MAX_SPECIES)
            REAL(EB) :: Q_REAC_OUT(MAX_REACTIONS),TOTAL_MIXED_MASS_0
            INTEGER :: N,NR,PTY
            LOGICAL :: ANY_FAST

            TOTAL_MIXED_MASS_0  = (1._EB-ZETA_IN)*CELL_MASS
            DO N=1,N_TRACKED_SPECIES_IN
                MIXED_MASS_0(N) = ZZ_IN(N)*TOTAL_MIXED_MASS_0
            ENDDO

            ZETA_OUT = MAX(0._EB,ZETA_IN*EXP(-DT_LOC/TAU_MIX))
            TOTAL_MIXED_MASS = (1._EB-ZETA_OUT)*CELL_MASS
            DO N=1,N_TRACKED_SPECIES_IN
                MIXED_MASS(N) = MAX(0._EB,MIXED_MASS_0(N) - (ZETA_OUT-ZETA_IN)*ZZ_0(N)*CELL_MASS)
                ZZ_HAT(N) = MIXED_MASS(N)/MAX(TOTAL_MIXED_MASS,TWO_EPS_IN)
            ENDDO

            CALL GET_REALIZABLE_MF_DEVICE(ZZ_HAT,N_TRACKED_SPECIES_IN)
            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_HAT_MIX_OUT(N) = ZZ_HAT(N)
                REACTION_DZZ_OUT(N) = 0._EB
            ENDDO

            DO NR=1,N_REACTIONS_IN
                Q_REAC_LOC(NR) = 0._EB
            ENDDO

            ANY_FAST = .FALSE.
            DO NR=1,N_REACTIONS_IN
                IF (REAC_FAST_CHEMISTRY_D(NR)) ANY_FAST = .TRUE.
            ENDDO

            IF (ANY_FAST) THEN
                DO PTY=1,MAX_PRIORITY_IN
                    CALL REACTION_RATE_FAST_DEVICE(DZZ,ZZ_HAT,DT_LOC,RHO_HAT,TMP_IN,Q_REAC_OUT,NO_REACTIONS,PTY, &
                                                             REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D, &
                                                             REAC_FAST_CHEMISTRY_D,REAC_NU_MW_O_MW_F_D,REAC_A_PRIME_D, &
                                                             REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D, &
                                                             N_TRACKED_SPECIES_IN,N_REACTIONS_IN,TWO_EPS_IN,HUGE_IN)
                    DO N=1,N_TRACKED_SPECIES_IN
                        ZZ_HAT(N) = ZZ_HAT(N) + DZZ(N)
                        REACTION_DZZ_OUT(N) = REACTION_DZZ_OUT(N) + DZZ(N)
                    ENDDO
                    DO NR=1,N_REACTIONS_IN
                        Q_REAC_LOC(NR) = Q_REAC_LOC(NR) + Q_REAC_OUT(NR)*TOTAL_MIXED_MASS
                    ENDDO
                ENDDO
            ENDIF

            CALL GET_REALIZABLE_MF_DEVICE(ZZ_HAT,N_TRACKED_SPECIES_IN)

            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_OUT(N) = ZZ_HAT(N)
            ENDDO

        END SUBROUTINE FIRE_FORWARD_EULER_DEVICE

        ATTRIBUTES(DEVICE) SUBROUTINE REACTION_RATE_FAST_DEVICE( &
            DZZ,ZZ_OLD,DT_SUB,RHO_0,TMP_0,Q_REAC_OUT,NO_REACTIONS,PRIORITY_IN, &
            REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D,REAC_FAST_CHEMISTRY_D, &
            REAC_NU_MW_O_MW_F_D,REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D, &
            N_TRACKED_SPECIES_IN,N_REACTIONS_IN,TWO_EPS_IN,HUGE_IN)

            INTEGER, VALUE :: PRIORITY_IN,N_TRACKED_SPECIES_IN,N_REACTIONS_IN
            REAL(EB), VALUE :: DT_SUB,RHO_0,TMP_0,TWO_EPS_IN,HUGE_IN
            REAL(EB) :: DZZ(MAX_SPECIES),ZZ_OLD(MAX_SPECIES),Q_REAC_OUT(MAX_REACTIONS)
            LOGICAL :: NO_REACTIONS
            INTEGER, DEVICE, DIMENSION(1:*) :: REAC_FUEL_SMIX_INDEX_D,REAC_AIR_SMIX_INDEX_D,REAC_PRIORITY_D
            LOGICAL, DEVICE, DIMENSION(1:*) :: REAC_FAST_CHEMISTRY_D
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: REAC_NU_MW_O_MW_F_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: REAC_A_PRIME_D,REAC_RHO_EXPONENT_D,REAC_HEAT_OF_COMBUSTION_D

            REAL(EB) :: ZZ_TMP(MAX_SPECIES),ZZ_NEW(MAX_SPECIES),Q_REAC_TMP(MAX_REACTIONS),DT_MIN,DZ_F,AA
            INTEGER :: I,N,NS,OUTER_IT,FUEL_INDEX,AIR_INDEX
            LOGICAL :: REACTANTS_PRESENT

            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_NEW(N) = ZZ_OLD(N)
            ENDDO
            DO I=1,N_REACTIONS_IN
                Q_REAC_OUT(I) = 0._EB
                Q_REAC_TMP(I) = 0._EB
            ENDDO

            NO_REACTIONS = .FALSE.

            FAST_REAC_LOOP_GPU: DO OUTER_IT=1,N_REACTIONS_IN
                DO N=1,N_TRACKED_SPECIES_IN
                    ZZ_TMP(N) = ZZ_NEW(N)
                    DZZ(N) = 0._EB
                ENDDO
                REACTANTS_PRESENT = .FALSE.

                REACTION_LOOP_GPU: DO I=1,N_REACTIONS_IN
                    IF (.NOT. REAC_FAST_CHEMISTRY_D(I) .OR. REAC_PRIORITY_D(I)/=PRIORITY_IN) CYCLE REACTION_LOOP_GPU

                    FUEL_INDEX = REAC_FUEL_SMIX_INDEX_D(I)
                    AIR_INDEX  = REAC_AIR_SMIX_INDEX_D(I)
                    IF (FUEL_INDEX < 1 .OR. FUEL_INDEX > N_TRACKED_SPECIES_IN) CYCLE REACTION_LOOP_GPU

                    IF (AIR_INDEX > -1) THEN
                        IF (AIR_INDEX < 1 .OR. AIR_INDEX > N_TRACKED_SPECIES_IN) CYCLE REACTION_LOOP_GPU
                        DZ_F = ZZ_TMP(FUEL_INDEX)*ZZ_TMP(AIR_INDEX)
                    ELSE
                        DZ_F = ZZ_TMP(FUEL_INDEX)
                    ENDIF

                    IF (DZ_F > TWO_EPS_IN) REACTANTS_PRESENT = .TRUE.
                    AA = REAC_A_PRIME_D(I) * RHO_0**REAC_RHO_EXPONENT_D(I)
                    DO NS=1,N_TRACKED_SPECIES_IN
                        DZZ(NS) = DZZ(NS) + AA*REAC_NU_MW_O_MW_F_D(NS,I)*DZ_F
                    ENDDO
                    Q_REAC_TMP(I) = REAC_HEAT_OF_COMBUSTION_D(I)*AA*DZ_F
                ENDDO REACTION_LOOP_GPU

                IF (REACTANTS_PRESENT) THEN
                    DT_MIN = HUGE_IN
                    DO NS=1,N_TRACKED_SPECIES_IN
                        IF (DZZ(NS) < 0._EB) DT_MIN = MIN(DT_MIN,-ZZ_TMP(NS)/DZZ(NS))
                    ENDDO
                    DO N=1,N_TRACKED_SPECIES_IN
                        ZZ_NEW(N) = ZZ_TMP(N) + DZZ(N)*DT_MIN
                    ENDDO
                    DO I=1,N_REACTIONS_IN
                        Q_REAC_OUT(I) = Q_REAC_OUT(I) + Q_REAC_TMP(I)*DT_MIN
                    ENDDO
                ELSE
                    EXIT FAST_REAC_LOOP_GPU
                ENDIF
            ENDDO FAST_REAC_LOOP_GPU

            DO N=1,N_TRACKED_SPECIES_IN
                DZZ(N) = ZZ_NEW(N) - ZZ_OLD(N)
            ENDDO

        END SUBROUTINE REACTION_RATE_FAST_DEVICE

        ATTRIBUTES(DEVICE) SUBROUTINE GET_REALIZABLE_MF_DEVICE(ZZ_IN,N_TRACKED_SPECIES_IN)

            INTEGER, VALUE :: N_TRACKED_SPECIES_IN
            REAL(EB) :: ZZ_IN(MAX_SPECIES)
            REAL(EB) :: MAX_ZZ,SUM_ZZ,SUM_OTHER_SPECIES
            INTEGER :: N,N_ZZ_MAX

            N_ZZ_MAX = 1
            MAX_ZZ = -1._EB
            SUM_ZZ = 0._EB
            DO N=1,N_TRACKED_SPECIES_IN
                ZZ_IN(N) = MAX(0._EB,MIN(1._EB,ZZ_IN(N)))
                SUM_ZZ = SUM_ZZ + ZZ_IN(N)
                IF (ZZ_IN(N) > MAX_ZZ) THEN
                    MAX_ZZ = ZZ_IN(N)
                    N_ZZ_MAX = N
                ENDIF
            ENDDO

            SUM_OTHER_SPECIES = SUM_ZZ - ZZ_IN(N_ZZ_MAX)
            ZZ_IN(N_ZZ_MAX) = 1._EB - SUM_OTHER_SPECIES

        END SUBROUTINE GET_REALIZABLE_MF_DEVICE

        ATTRIBUTES(DEVICE) SUBROUTINE EXTINCT_1_DEVICE(EXTINCT,ZZ_0,TMP_IN,SPECIES_Z2Y_O2_D, &
                                                                      REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D, &
                                                                      FREE_BURN_TEMPERATURE_IN,TMPA_IN,N_TRACKED_SPECIES_IN)

            INTEGER, VALUE :: N_TRACKED_SPECIES_IN
            REAL(EB), VALUE :: TMP_IN,FREE_BURN_TEMPERATURE_IN,TMPA_IN
            LOGICAL :: EXTINCT
            REAL(EB) :: ZZ_0(MAX_SPECIES)
            REAL(EB), DEVICE, DIMENSION(1:*) :: SPECIES_Z2Y_O2_D,REAC_CRITICAL_FLAME_TEMPERATURE_D,REAC_Y_O2_MIN_D

            REAL(EB) :: Y_O2,Y_O2_LIM,TMP_FACTOR,CFT
            INTEGER :: N

            CFT = REAC_CRITICAL_FLAME_TEMPERATURE_D(1)

            Y_O2 = 0._EB
            DO N=1,N_TRACKED_SPECIES_IN
                Y_O2 = Y_O2 + SPECIES_Z2Y_O2_D(N)*ZZ_0(N)
            ENDDO

            IF (TMP_IN < FREE_BURN_TEMPERATURE_IN) THEN
                TMP_FACTOR = (CFT-TMP_IN)/(CFT-TMPA_IN)
            ELSE
                TMP_FACTOR = 0._EB
            ENDIF
            Y_O2_LIM = REAC_Y_O2_MIN_D(1)*TMP_FACTOR
            IF (Y_O2 < Y_O2_LIM) EXTINCT = .TRUE.

        END SUBROUTINE EXTINCT_1_DEVICE

        ATTRIBUTES(DEVICE) SUBROUTINE EXTINCT_2_DEVICE(EXTINCT,ZZ_0,ZZ_IN,TMP_IN,FUEL_INDEX_D, &
            AIR_INDEX_D,PRIORITY_D,CFT_D,N_SPEC,N_REAC,MAX_TEMP,TWO_EPS)

            INTEGER, VALUE :: N_SPEC,N_REAC,MAX_TEMP
            REAL(EB), VALUE :: TMP_IN,TWO_EPS
            LOGICAL, INTENT(INOUT) :: EXTINCT
            REAL(EB), INTENT(IN) :: ZZ_0(MAX_SPECIES),ZZ_IN(MAX_SPECIES)
            INTEGER, DEVICE :: FUEL_INDEX_D(*),AIR_INDEX_D(*),PRIORITY_D(*)
            REAL(EB), DEVICE :: CFT_D(*)
            REAL(EB) :: ZZ_HAT_0(MAX_SPECIES),ZZ_HAT(MAX_SPECIES)
            REAL(EB) :: SUM_CFT,SUM_ZZ,CFT,PHI_TILDE,SUM_0,SUM_1,H_0,H_CRIT
            INTEGER :: NR,NS

            ! FIRE:EXTINCT_2 uses the reacted mixed portion, before cell-average recombination.
            SUM_CFT = 0._EB
            SUM_ZZ = 0._EB
            DO NR=1,N_REAC
                IF (PRIORITY_D(NR)/=1) CYCLE
                SUM_CFT = SUM_CFT + ZZ_0(FUEL_INDEX_D(NR))*CFT_D(NR)
                SUM_ZZ = SUM_ZZ + ZZ_0(FUEL_INDEX_D(NR))
            ENDDO
            IF (SUM_ZZ<TWO_EPS) THEN
                EXTINCT = .TRUE.
                RETURN
            ENDIF
            CFT = SUM_CFT/SUM_ZZ
            PHI_TILDE = (ZZ_0(AIR_INDEX_D(1))-ZZ_IN(AIR_INDEX_D(1)))/ZZ_0(AIR_INDEX_D(1))
            IF (PHI_TILDE<TWO_EPS) THEN
                EXTINCT = .TRUE.
                RETURN
            ENDIF

            DO NR=1,N_REAC
                DO NS=1,N_SPEC
                    IF (NS==FUEL_INDEX_D(NR)) THEN
                        ZZ_HAT_0(NS) = ZZ_0(NS)
                        ZZ_HAT(NS) = ZZ_IN(NS)
                    ELSEIF (NS==AIR_INDEX_D(NR)) THEN
                        ZZ_HAT_0(NS) = PHI_TILDE*ZZ_0(NS)
                        ZZ_HAT(NS) = 0._EB
                    ELSE
                        ZZ_HAT_0(NS) = PHI_TILDE*ZZ_0(NS)
                        ZZ_HAT(NS) = (PHI_TILDE-1._EB)*ZZ_0(NS)+ZZ_IN(NS)
                    ENDIF
                ENDDO
            ENDDO
            SUM_0 = SUM(ZZ_HAT_0(1:N_SPEC))
            SUM_1 = SUM(ZZ_HAT(1:N_SPEC))
            ZZ_HAT_0(1:N_SPEC) = ZZ_HAT_0(1:N_SPEC)/SUM_0
            ZZ_HAT(1:N_SPEC) = ZZ_HAT(1:N_SPEC)/SUM_1
            CALL GET_ENTHALPY_FIRE_DEVICE(ZZ_HAT_0,H_0,TMP_IN,N_SPEC,MAX_TEMP)
            CALL GET_ENTHALPY_FIRE_DEVICE(ZZ_HAT,H_CRIT,CFT,N_SPEC,MAX_TEMP)
            IF (H_0<H_CRIT) EXTINCT = .TRUE.

        END SUBROUTINE EXTINCT_2_DEVICE

        ATTRIBUTES(DEVICE) SUBROUTINE GET_ENTHALPY_FIRE_DEVICE(ZZ,H_OUT,TMP_IN,N_SPEC,MAX_TEMP)
            INTEGER, VALUE :: N_SPEC,MAX_TEMP
            REAL(EB), VALUE :: TMP_IN
            REAL(EB), INTENT(IN) :: ZZ(MAX_SPECIES)
            REAL(EB), INTENT(OUT) :: H_OUT
            REAL(EB) :: H_NEXT,CP_LOC,DTMP
            INTEGER :: N,ITMP

            ! Same CPBAR_Z/CP_Z tables and interpolation as PHYSICAL_FUNCTIONS:GET_ENTHALPY.
            H_OUT = 0._EB
            IF (TMP_IN>=REAL(MAX_TEMP,EB)) THEN
                CP_LOC = 0._EB
                DO N=1,N_SPEC
                    H_OUT = H_OUT + CPBAR_ZD(MAX_TEMP,N)*ZZ(N)
                    CP_LOC = CP_LOC + CP_ZD(MAX_TEMP,N)*ZZ(N)
                ENDDO
                H_OUT = H_OUT*REAL(MAX_TEMP,EB)+CP_LOC*(TMP_IN-REAL(MAX_TEMP,EB))
            ELSE
                ITMP = INT(TMP_IN)
                DTMP = TMP_IN-REAL(ITMP)
                H_NEXT = 0._EB
                DO N=1,N_SPEC
                    H_OUT = H_OUT + CPBAR_ZD(ITMP,N)*ZZ(N)
                    H_NEXT = H_NEXT + CPBAR_ZD(ITMP+1,N)*ZZ(N)
                ENDDO
                H_OUT = (H_OUT+DTMP*(H_NEXT-H_OUT))*TMP_IN
            ENDIF
        END SUBROUTINE GET_ENTHALPY_FIRE_DEVICE

        ATTRIBUTES(DEVICE) SUBROUTINE CHECK_AUTO_IGNITION_DEVICE(EXTINCT,TMP_IN,AIT,X_IN,Y_IN,Z_IN,REAC_INDEX)

            LOGICAL :: EXTINCT
            REAL(EB), VALUE :: TMP_IN,AIT,X_IN,Y_IN,Z_IN
            INTEGER, VALUE :: REAC_INDEX
            INTEGER :: IZ

            ! Match FIRE:CHECK_AUTO_IGNITION, including first matching zone and strict comparisons.
            DO IZ=1,AIT_ZONE_COUNT_D(REAC_INDEX)
                IF (.NOT.AIT_ZONE_ACTIVE_D(IZ,REAC_INDEX)) CYCLE
                IF (X_IN>=AIT_ZONE_DATA_D(1,IZ,REAC_INDEX) .AND. X_IN<=AIT_ZONE_DATA_D(2,IZ,REAC_INDEX) .AND. &
                    Y_IN>=AIT_ZONE_DATA_D(3,IZ,REAC_INDEX) .AND. Y_IN<=AIT_ZONE_DATA_D(4,IZ,REAC_INDEX) .AND. &
                    Z_IN>=AIT_ZONE_DATA_D(5,IZ,REAC_INDEX) .AND. Z_IN<=AIT_ZONE_DATA_D(6,IZ,REAC_INDEX)) THEN
                    IF (TMP_IN<AIT_ZONE_DATA_D(7,IZ,REAC_INDEX)) EXTINCT = .TRUE.
                    RETURN
                ENDIF
            ENDDO
            EXTINCT = .TRUE.
            IF (TMP_IN > AIT) EXTINCT = .FALSE.

        END SUBROUTINE CHECK_AUTO_IGNITION_DEVICE

        ATTRIBUTES(GLOBAL) SUBROUTINE SET_SPECIES_SOURCE_TERM_CELL_GPU( &
            NCHEM_ACTIVE_CELLS_IN,CHEM_ACTIVE_CELLS_IN,ZZ_NEW_WORKD,ZZ_OLD_WORKD, &
            D_SOURCE_D,M_DOT_PPP_D,TMP_D,RHO_D,CP_Z_D,H_SENS_Z_D,MWR_Z_D,SPECIES_RCON_D, &
            DT_IN,DZZ_CLIP_IN,R0_IN,IBAR_IN,JBAR_IN,KBAR_IN,N_TRACKED_SPECIES_IN,I_MAX_TEMP_IN)

            INTEGER, VALUE :: IBAR_IN,JBAR_IN,KBAR_IN,N_TRACKED_SPECIES_IN,I_MAX_TEMP_IN
            REAL(EB), VALUE :: DT_IN,DZZ_CLIP_IN,R0_IN
            INTEGER, DEVICE :: NCHEM_ACTIVE_CELLS_IN
            INTEGER, DEVICE, DIMENSION(1:(IBAR_IN+1)*(JBAR_IN+1)*(KBAR_IN+1),1:*) :: CHEM_ACTIVE_CELLS_IN
            REAL(EB), DEVICE, DIMENSION(1:N_TRACKED_SPECIES_IN,1:*) :: ZZ_NEW_WORKD,ZZ_OLD_WORKD
            REAL(EB), DEVICE, DIMENSION(0:IBAR_IN+1,0:JBAR_IN+1,0:*) :: D_SOURCE_D,TMP_D,RHO_D
            REAL(EB), DEVICE, DIMENSION(0:IBAR_IN+1,0:JBAR_IN+1,0:KBAR_IN+1,1:*) :: M_DOT_PPP_D
            REAL(EB), DEVICE, DIMENSION(0:I_MAX_TEMP_IN,1:*) :: CP_Z_D,H_SENS_Z_D
            REAL(EB), DEVICE, DIMENSION(1:*) :: MWR_Z_D,SPECIES_RCON_D

            INTEGER :: NC,I,J,K,N,ITMP_CP,ITMP_H
            REAL(EB) :: TMP_LOC,CP_LOC,RSUM_LOC,H_S_N,DZZ_N
            LOGICAL :: DZZ_NEEDED

            NC = (blockIdx%x - 1) * blockDim%x + threadIdx%x
            IF (NC < 1 .OR. NC > NCHEM_ACTIVE_CELLS_IN) RETURN

            I = CHEM_ACTIVE_CELLS_IN(NC,1)
            J = CHEM_ACTIVE_CELLS_IN(NC,2)
            K = CHEM_ACTIVE_CELLS_IN(NC,3)
            IF (I < 1 .OR. I > IBAR_IN) RETURN
            IF (J < 1 .OR. J > JBAR_IN) RETURN
            IF (K < 1 .OR. K > KBAR_IN) RETURN

            DZZ_NEEDED = .FALSE.
            DO N=1,N_TRACKED_SPECIES_IN
                IF (ABS(ZZ_NEW_WORKD(N,NC)-ZZ_OLD_WORKD(N,NC)) > DZZ_CLIP_IN) THEN
                    DZZ_NEEDED = .TRUE.
                    EXIT
                ENDIF
            ENDDO
            IF (.NOT. DZZ_NEEDED) RETURN

            TMP_LOC = TMP_D(I,J,K)
            ITMP_CP = MAX(0,MIN(I_MAX_TEMP_IN,NINT(TMP_LOC)))
            ITMP_H  = MAX(0,MIN(I_MAX_TEMP_IN-1,INT(TMP_LOC)))

            CP_LOC = 0._EB
            RSUM_LOC = 0._EB
            DO N=1,N_TRACKED_SPECIES_IN
                CP_LOC = CP_LOC + CP_Z_D(ITMP_CP,N)*ZZ_NEW_WORKD(N,NC)
                RSUM_LOC = RSUM_LOC + MWR_Z_D(N)*ZZ_NEW_WORKD(N,NC)
            ENDDO
            RSUM_LOC = R0_IN*RSUM_LOC

            DO N=1,N_TRACKED_SPECIES_IN
                DZZ_N = ZZ_NEW_WORKD(N,NC)-ZZ_OLD_WORKD(N,NC)
                H_S_N = H_SENS_Z_D(ITMP_H,N) + (TMP_LOC-REAL(ITMP_H,EB))*(H_SENS_Z_D(ITMP_H+1,N)-H_SENS_Z_D(ITMP_H,N))
                D_SOURCE_D(I,J,K) = D_SOURCE_D(I,J,K) + &
                    (SPECIES_RCON_D(N)/RSUM_LOC - H_S_N/(CP_LOC*TMP_LOC))*DZZ_N/DT_IN
                M_DOT_PPP_D(I,J,K,N) = M_DOT_PPP_D(I,J,K,N) + RHO_D(I,J,K)*DZZ_N/DT_IN
            ENDDO

        END SUBROUTINE SET_SPECIES_SOURCE_TERM_CELL_GPU

        !--------------------------------------------------------------------------
        ! Combustion boundary-condition host orchestration
        !--------------------------------------------------------------------------
        SUBROUTINE COMBUSTION_BC_GPU(NM)
            INTEGER, INTENT(IN) :: NM
            INTEGER :: NOM
            REAL(EB) :: TNOW
            TYPE(OMESH_TYPE), POINTER :: OM
            TYPE(GPU_OMESH_TYPE), POINTER :: GOM_LOCAL

            CALL POINT_TO_MESH(NM)
            GM => GPU_MESHES(NM)
            IF (N_EXTERNAL_WALL_CELLS <= 0) RETURN

            TNOW = CURRENT_TIME()

            IF (GPU_DEBUG_H2D_D2H) GM%QD = Q

            DO NOM=1,NMESHES
                IF (.NOT.ALLOCATED(GM%OMESH)) EXIT
                GOM_LOCAL => GM%OMESH(NOM)
                IF (.NOT.GOM_LOCAL%ACTIVE) CYCLE
                OM => MESHES(NM)%OMESH(NOM)
                IF (GPU_DEBUG_H2D_D2H) GOM_LOCAL%Q_D = OM%Q

                CALL COMBUSTION_BC_INTERPOLATED_GPU<<<GM%GRDD_EXTERNAL_WALL_1D,GPU_BLKD_1D,0,GM%STRM>>>(GM%QD,GOM_LOCAL%Q_D, &
                    GM%WALL_TOPO_AOS,GM%EXTERNAL_WALL_NOMD,GM%WALL_IIO,GM%WALL_JJO,GM%WALL_KKO, &
                    GM%WALL_IIO_MAX,GM%WALL_JJO_MAX,GM%WALL_KKO_MAX, &
                    N_EXTERNAL_WALL_CELLS,NOM,IBP1,JBP1,SIZE(GOM_LOCAL%Q_D,1),SIZE(GOM_LOCAL%Q_D,2),LBOUND(GOM_LOCAL%Q_D,1), &
                    LBOUND(GOM_LOCAL%Q_D,2),LBOUND(GOM_LOCAL%Q_D,3))
            ENDDO
            IF (GPU_DEBUG_H2D_D2H) THEN
                CALL GPU_WAIT(GM%STRM)
                Q = GM%QD
            ENDIF

            T_USED(10) = T_USED(10) + CURRENT_TIME() - TNOW

        END SUBROUTINE COMBUSTION_BC_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE COMBUSTION_BC_INTERPOLATED_GPU(Q_OUT,OM_Q,WALL_TOPO,EXTERNAL_WALL_NOM, &
            WALL_IIO,WALL_JJO,WALL_KKO,WALL_IIO_MAX,WALL_JJO_MAX,WALL_KKO_MAX,N_EXTERNAL_WALL_CELLS,NOM_FILTER, &
            IBP1,JBP1,OM_NI,OM_NJ,OM_LB_I,OM_LB_J,OM_LB_K)
            TYPE(WALL_TOPO_AOS_TYPE), DEVICE :: WALL_TOPO(0:*)

            INTEGER, VALUE :: N_EXTERNAL_WALL_CELLS,NOM_FILTER,IBP1,JBP1,OM_NI,OM_NJ,OM_LB_I,OM_LB_J,OM_LB_K
            REAL(EB), DEVICE, DIMENSION(0:IBP1,0:JBP1,0:*) :: Q_OUT
            REAL(EB), DEVICE, DIMENSION(*) :: OM_Q
            INTEGER, DEVICE, DIMENSION(1:*) :: EXTERNAL_WALL_NOM,WALL_IIO,WALL_JJO,WALL_KKO
            INTEGER, DEVICE, DIMENSION(1:*) :: WALL_IIO_MAX,WALL_JJO_MAX,WALL_KKO_MAX
            INTEGER :: IW,II,JJ,KK,IIO,JJO,KKO,IIO1,IIO2,JJO1,JJO2,KKO1,KKO2,N_INT_CELLS,IDX_C
            REAL(EB) :: Q_OTHER

            IW = (BLOCKIDX%X - 1) * BLOCKDIM%X + THREADIDX%X
            IF (IW < 1 .OR. IW > N_EXTERNAL_WALL_CELLS) RETURN
            IF (EXTERNAL_WALL_NOM(IW) /= NOM_FILTER) RETURN

            IIO1 = WALL_IIO(IW)
            JJO1 = WALL_JJO(IW)
            KKO1 = WALL_KKO(IW)
            IIO2 = WALL_IIO_MAX(IW)
            JJO2 = WALL_JJO_MAX(IW)
            KKO2 = WALL_KKO_MAX(IW)
            N_INT_CELLS = (IIO2-IIO1+1)*(JJO2-JJO1+1)*(KKO2-KKO1+1)
            IF (N_INT_CELLS <= 0) RETURN

            Q_OTHER = 0._EB
            DO KKO=KKO1,KKO2
                DO JJO=JJO1,JJO2
                    DO IIO=IIO1,IIO2
                        IDX_C = 1 + (IIO-OM_LB_I) + OM_NI*((JJO-OM_LB_J) + OM_NJ*(KKO-OM_LB_K))
                        Q_OTHER = Q_OTHER + OM_Q(IDX_C)
                    ENDDO
                ENDDO
            ENDDO

            II = WALL_TOPO(IW)%II
            JJ = WALL_TOPO(IW)%JJ
            KK = WALL_TOPO(IW)%KK
            Q_OUT(II,JJ,KK) = Q_OTHER/REAL(N_INT_CELLS,EB)

        END SUBROUTINE COMBUSTION_BC_INTERPOLATED_GPU

