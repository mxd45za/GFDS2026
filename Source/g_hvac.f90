!------------------------------------------------------------------------------
! Module: G_HVAC
! Purpose: Sparse CPU/GPU staging for the CPU HVAC network in the GPU time loop.
!------------------------------------------------------------------------------
MODULE G_HVAC
    USE PRECISION_PARAMETERS, ONLY: EB
    USE GLOBAL_CONSTANTS, ONLY: N_TRACKED_SPECIES,NMESHES,HVAC_SOLVE,OBST_CREATED_OR_REMOVED,PREDICTOR, &
                                SPECIFIED_MASS_FRACTION,SPECIFIED_MASS_FLUX
    USE MESH_VARIABLES, ONLY: MESHES
    USE MESH_POINTERS, ONLY: POINT_TO_MESH,IBP1,JBP1,KBP1,N_EXTERNAL_WALL_CELLS,N_INTERNAL_WALL_CELLS, &
                             INTERNAL_CFACE_CELLS_LB,N_INTERNAL_CFACE_CELLS,WALL,CFACE,BOUNDARY_COORD,BOUNDARY_PROP1, &
                             SURFACE,RHO,TMP,KRES,H,ZZ,U,V,W,PBAR,PBAR_S,DUCTNODE
    USE TYPES, ONLY: WALL_TYPE,CFACE_TYPE,BOUNDARY_COORD_TYPE,BOUNDARY_PROP1_TYPE,SURFACE_TYPE
    USE G_MESH, ONLY: GPU_MESH_TYPE,GPU_MESHES
    USE G_CONS, ONLY: GPU_DEVICE_ON
    USE HVAC_ROUTINES, ONLY: DUCT_MF
    USE WALL_ROUTINES, ONLY: CALC_HVAC_BC,SET_WALL_PRESSURE_ARRAY
    USE CUDAFOR
    USE G_ERRO, ONLY: GPU_WAIT
    IMPLICIT NONE
    PRIVATE

    INTEGER, PARAMETER :: HVAC_COPY_BLOCK=128
    INTEGER, PARAMETER :: HVAC_CELL_FIELD_COUNT=5
    INTEGER, PARAMETER :: HVAC_WALL_FIELD_COUNT=8

    TYPE :: GPU_HVAC_MESH_TYPE
        LOGICAL :: READY=.FALSE.
        INTEGER :: N_CELL_BC=0,N_WALL_BC=0
        INTEGER, ALLOCATABLE :: I_H(:),J_H(:),K_H(:),IOR_H(:),WALL_INDEX_H(:),WALL_SPECIES_BC_H(:)
        INTEGER, DEVICE, ALLOCATABLE :: I_D(:),J_D(:),K_D(:),IOR_D(:),WALL_INDEX_D(:),WALL_SPECIES_BC_D(:)
        INTEGER, DEVICE, ALLOCATABLE :: WALL_SPECIES_BC_OVERRIDE_D(:)
        REAL(EB), ALLOCATABLE :: CELL_DATA_H(:,:),WALL_DATA_H(:,:)
        REAL(EB), DEVICE, ALLOCATABLE :: CELL_DATA_D(:,:),WALL_DATA_D(:,:)
    END TYPE GPU_HVAC_MESH_TYPE

    TYPE(GPU_HVAC_MESH_TYPE), ALLOCATABLE, TARGET :: GPU_HVAC_MESHES(:)

    PUBLIC :: SYNC_GPU_HVAC_BC_INPUT,APPLY_GPU_HVAC_BOUNDARY_BC,GET_GPU_HVAC_SPECIES_BC_OVERRIDE,FINISH_GPU_HVAC

CONTAINS

    SUBROUTINE ENSURE_GPU_HVAC_STORAGE
        IF (.NOT.ALLOCATED(GPU_HVAC_MESHES)) ALLOCATE(GPU_HVAC_MESHES(NMESHES))
    END SUBROUTINE ENSURE_GPU_HVAC_STORAGE


    SUBROUTINE BUILD_GPU_HVAC_BOUNDARY_MAP(NM)
        INTEGER, INTENT(IN) :: NM
        INTEGER :: IW,ICF,NBC,NWALL,POS
        TYPE(WALL_TYPE), POINTER :: WC
        TYPE(CFACE_TYPE), POINTER :: CFA
        TYPE(SURFACE_TYPE), POINTER :: SF
        TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
        TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1
        TYPE(GPU_MESH_TYPE), POINTER :: GM
        TYPE(GPU_HVAC_MESH_TYPE), POINTER :: HM

        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)
        HM => GPU_HVAC_MESHES(NM)
        CALL GPU_WAIT(GM%STRM)

        IF (ALLOCATED(HM%I_H)) DEALLOCATE(HM%I_H,HM%J_H,HM%K_H,HM%IOR_H)
        IF (ALLOCATED(HM%I_D)) DEALLOCATE(HM%I_D,HM%J_D,HM%K_D,HM%IOR_D)
        IF (ALLOCATED(HM%WALL_INDEX_H)) DEALLOCATE(HM%WALL_INDEX_H)
        IF (ALLOCATED(HM%WALL_INDEX_D)) DEALLOCATE(HM%WALL_INDEX_D)
        IF (ALLOCATED(HM%WALL_SPECIES_BC_H)) DEALLOCATE(HM%WALL_SPECIES_BC_H)
        IF (ALLOCATED(HM%WALL_SPECIES_BC_D)) DEALLOCATE(HM%WALL_SPECIES_BC_D)
        IF (ALLOCATED(HM%WALL_SPECIES_BC_OVERRIDE_D)) DEALLOCATE(HM%WALL_SPECIES_BC_OVERRIDE_D)
        IF (ALLOCATED(HM%CELL_DATA_H)) DEALLOCATE(HM%CELL_DATA_H)
        IF (ALLOCATED(HM%CELL_DATA_D)) DEALLOCATE(HM%CELL_DATA_D)
        IF (ALLOCATED(HM%WALL_DATA_H)) DEALLOCATE(HM%WALL_DATA_H)
        IF (ALLOCATED(HM%WALL_DATA_D)) DEALLOCATE(HM%WALL_DATA_D)

        NBC = 0
        NWALL = 0
        DO IW=1,N_EXTERNAL_WALL_CELLS+N_INTERNAL_WALL_CELLS
            WC => WALL(IW)
            IF (WC%BOUNDARY_TYPE==0) CYCLE
            B1 => BOUNDARY_PROP1(WC%B1_INDEX)
            SF => SURFACE(WC%SURF_INDEX)
            IF (B1%NODE_INDEX==0 .AND. .NOT.ANY(SF%LEAK_PATH>0)) CYCLE
            NBC = NBC + 1
            IF (B1%NODE_INDEX/=0) NWALL = NWALL + 1
        ENDDO
        DO ICF=INTERNAL_CFACE_CELLS_LB+1,INTERNAL_CFACE_CELLS_LB+N_INTERNAL_CFACE_CELLS
            CFA => CFACE(ICF)
            IF (CFA%BOUNDARY_TYPE==0) CYCLE
            B1 => BOUNDARY_PROP1(CFA%B1_INDEX)
            SF => SURFACE(CFA%SURF_INDEX)
            IF (B1%NODE_INDEX==0 .AND. .NOT.ANY(SF%LEAK_PATH>0)) CYCLE
            NBC = NBC + 1
        ENDDO

        HM%N_CELL_BC = NBC
        HM%N_WALL_BC = NWALL
        ALLOCATE(HM%WALL_SPECIES_BC_OVERRIDE_D(0:N_EXTERNAL_WALL_CELLS+N_INTERNAL_WALL_CELLS))
        HM%WALL_SPECIES_BC_OVERRIDE_D = 0
        IF (NBC>0) THEN
            ALLOCATE(HM%I_H(NBC),HM%J_H(NBC),HM%K_H(NBC),HM%IOR_H(NBC))
            ALLOCATE(HM%I_D(NBC),HM%J_D(NBC),HM%K_D(NBC),HM%IOR_D(NBC))
            ALLOCATE(HM%CELL_DATA_H(HVAC_CELL_FIELD_COUNT+N_TRACKED_SPECIES,NBC))
            ALLOCATE(HM%CELL_DATA_D(HVAC_CELL_FIELD_COUNT+N_TRACKED_SPECIES,NBC))
            HM%CELL_DATA_H = 0._EB
            POS = 0
            DO IW=1,N_EXTERNAL_WALL_CELLS+N_INTERNAL_WALL_CELLS
                WC => WALL(IW)
                IF (WC%BOUNDARY_TYPE==0) CYCLE
                B1 => BOUNDARY_PROP1(WC%B1_INDEX)
                SF => SURFACE(WC%SURF_INDEX)
                IF (B1%NODE_INDEX==0 .AND. .NOT.ANY(SF%LEAK_PATH>0)) CYCLE
                BC => BOUNDARY_COORD(WC%BC_INDEX)
                POS=POS+1
                HM%I_H(POS)=BC%IIG
                HM%J_H(POS)=BC%JJG
                HM%K_H(POS)=BC%KKG
                HM%IOR_H(POS)=BC%IOR
            ENDDO
            DO ICF=INTERNAL_CFACE_CELLS_LB+1,INTERNAL_CFACE_CELLS_LB+N_INTERNAL_CFACE_CELLS
                CFA => CFACE(ICF)
                IF (CFA%BOUNDARY_TYPE==0) CYCLE
                B1 => BOUNDARY_PROP1(CFA%B1_INDEX)
                SF => SURFACE(CFA%SURF_INDEX)
                IF (B1%NODE_INDEX==0 .AND. .NOT.ANY(SF%LEAK_PATH>0)) CYCLE
                BC => BOUNDARY_COORD(CFA%BC_INDEX)
                POS=POS+1
                HM%I_H(POS)=BC%IIG
                HM%J_H(POS)=BC%JJG
                HM%K_H(POS)=BC%KKG
                HM%IOR_H(POS)=BC%IOR
            ENDDO
            HM%I_D = HM%I_H
            HM%J_D = HM%J_H
            HM%K_D = HM%K_H
            HM%IOR_D = HM%IOR_H
        ENDIF

        IF (NWALL>0) THEN
            ALLOCATE(HM%WALL_INDEX_H(NWALL),HM%WALL_INDEX_D(NWALL))
            ALLOCATE(HM%WALL_SPECIES_BC_H(NWALL),HM%WALL_SPECIES_BC_D(NWALL))
            ALLOCATE(HM%WALL_DATA_H(HVAC_WALL_FIELD_COUNT+2*N_TRACKED_SPECIES,NWALL))
            ALLOCATE(HM%WALL_DATA_D(HVAC_WALL_FIELD_COUNT+2*N_TRACKED_SPECIES,NWALL))
            HM%WALL_DATA_H = 0._EB
            HM%WALL_SPECIES_BC_H = 0
            POS=0
            DO IW=1,N_EXTERNAL_WALL_CELLS+N_INTERNAL_WALL_CELLS
                WC => WALL(IW)
                IF (WC%BOUNDARY_TYPE==0) CYCLE
                B1 => BOUNDARY_PROP1(WC%B1_INDEX)
                IF (B1%NODE_INDEX==0) CYCLE
                POS=POS+1
                HM%WALL_INDEX_H(POS)=IW
            ENDDO
            HM%WALL_INDEX_D = HM%WALL_INDEX_H
        ENDIF

        HM%READY=.TRUE.
    END SUBROUTINE BUILD_GPU_HVAC_BOUNDARY_MAP


    SUBROUTINE ENSURE_GPU_HVAC_BOUNDARY_MAP(NM)
        INTEGER, INTENT(IN) :: NM
        IF (.NOT.GPU_HVAC_MESHES(NM)%READY .OR. OBST_CREATED_OR_REMOVED) CALL BUILD_GPU_HVAC_BOUNDARY_MAP(NM)
    END SUBROUTINE ENSURE_GPU_HVAC_BOUNDARY_MAP


    SUBROUTINE GET_GPU_HVAC_SPECIES_BC_OVERRIDE(NM,WALL_SPECIES_BC_OVERRIDE_D)
        INTEGER, INTENT(IN) :: NM
        INTEGER, DEVICE, POINTER, INTENT(OUT) :: WALL_SPECIES_BC_OVERRIDE_D(:)
        TYPE(GPU_MESH_TYPE), POINTER :: GM
        TYPE(GPU_HVAC_MESH_TYPE), POINTER :: HM

        CALL ENSURE_GPU_HVAC_STORAGE
        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)
        HM => GPU_HVAC_MESHES(NM)
        IF (.NOT.ALLOCATED(HM%WALL_SPECIES_BC_OVERRIDE_D)) THEN
            ALLOCATE(HM%WALL_SPECIES_BC_OVERRIDE_D(0:N_EXTERNAL_WALL_CELLS+N_INTERNAL_WALL_CELLS))
            HM%WALL_SPECIES_BC_OVERRIDE_D = 0
        ENDIF
        WALL_SPECIES_BC_OVERRIDE_D => HM%WALL_SPECIES_BC_OVERRIDE_D
    END SUBROUTINE GET_GPU_HVAC_SPECIES_BC_OVERRIDE


    SUBROUTINE SYNC_GPU_HVAC_BC_INPUT(NM)
        INTEGER, INTENT(IN) :: NM
        INTEGER :: N,II,JJ,KK,IOR,NS,NB,IW
        TYPE(WALL_TYPE), POINTER :: WC
        TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1
        TYPE(GPU_MESH_TYPE), POINTER :: GM
        TYPE(GPU_HVAC_MESH_TYPE), POINTER :: HM

        IF (.NOT.GPU_DEVICE_ON .OR. .NOT.HVAC_SOLVE) RETURN
        CALL ENSURE_GPU_HVAC_STORAGE
        CALL ENSURE_GPU_HVAC_BOUNDARY_MAP(NM)
        HM => GPU_HVAC_MESHES(NM)
        IF (HM%N_CELL_BC<=0) RETURN

        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)
        CALL GPU_WAIT(GM%STRM)
        NB = (HM%N_CELL_BC+HVAC_COPY_BLOCK-1)/HVAC_COPY_BLOCK
        CALL GATHER_HVAC_CELL_STATE<<<NB,HVAC_COPY_BLOCK,0,GM%STRM>>>(HM%N_CELL_BC,N_TRACKED_SPECIES, &
            HVAC_CELL_FIELD_COUNT+N_TRACKED_SPECIES,IBP1,JBP1,KBP1, &
            HM%I_D,HM%J_D,HM%K_D,HM%IOR_D,GM%RHOD,GM%TMPD,GM%KRESD,GM%HD,GM%ZZD,GM%UD,GM%VD,GM%WD,HM%CELL_DATA_D)
        CALL GPU_WAIT(GM%STRM)
        HM%CELL_DATA_H = HM%CELL_DATA_D
        PBAR = GM%PBARD

        DO N=1,HM%N_CELL_BC
            II=HM%I_H(N); JJ=HM%J_H(N); KK=HM%K_H(N); IOR=HM%IOR_H(N)
            RHO(II,JJ,KK)=HM%CELL_DATA_H(1,N)
            TMP(II,JJ,KK)=HM%CELL_DATA_H(2,N)
            KRES(II,JJ,KK)=HM%CELL_DATA_H(3,N)
            H(II,JJ,KK)=HM%CELL_DATA_H(4,N)
            SELECT CASE(IOR)
                CASE( 1); U(II-1,JJ,KK)=HM%CELL_DATA_H(5,N)
                CASE(-1); U(II,JJ,KK)=HM%CELL_DATA_H(5,N)
                CASE( 2); V(II,JJ-1,KK)=HM%CELL_DATA_H(5,N)
                CASE(-2); V(II,JJ,KK)=HM%CELL_DATA_H(5,N)
                CASE( 3); W(II,JJ,KK-1)=HM%CELL_DATA_H(5,N)
                CASE(-3); W(II,JJ,KK)=HM%CELL_DATA_H(5,N)
            END SELECT
            DO NS=1,N_TRACKED_SPECIES
                ZZ(II,JJ,KK,NS)=HM%CELL_DATA_H(HVAC_CELL_FIELD_COUNT+NS,N)
            ENDDO
        ENDDO
    END SUBROUTINE SYNC_GPU_HVAC_BC_INPUT


    SUBROUTINE APPLY_GPU_HVAC_BOUNDARY_BC(NM)
        INTEGER, INTENT(IN) :: NM
        INTEGER :: NB,N,NS,IW
        INTEGER :: DU
        TYPE(GPU_MESH_TYPE), POINTER :: GM
        TYPE(GPU_HVAC_MESH_TYPE), POINTER :: HM
        TYPE(WALL_TYPE), POINTER :: WC
        TYPE(SURFACE_TYPE), POINTER :: SF
        TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
        TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

        IF (.NOT.GPU_DEVICE_ON .OR. .NOT.HVAC_SOLVE) RETURN
        CALL ENSURE_GPU_HVAC_STORAGE
        CALL ENSURE_GPU_HVAC_BOUNDARY_MAP(NM)
        HM => GPU_HVAC_MESHES(NM)
        IF (HM%N_WALL_BC<=0) RETURN

        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)
        CALL GPU_WAIT(GM%STRM)
        IF (PREDICTOR) THEN
            PBAR_S = GM%PBAR_SD
            CALL SET_WALL_PRESSURE_ARRAY(PBAR_S)
        ELSE
            PBAR = GM%PBARD
            CALL SET_WALL_PRESSURE_ARRAY(PBAR)
        ENDIF
        NB=(HM%N_WALL_BC+HVAC_COPY_BLOCK-1)/HVAC_COPY_BLOCK
        CALL GATHER_HVAC_WALL_STATE<<<NB,HVAC_COPY_BLOCK,0,GM%STRM>>>(HM%N_WALL_BC,N_TRACKED_SPECIES, &
            HVAC_WALL_FIELD_COUNT+2*N_TRACKED_SPECIES,GM%WALL_UB,N_EXTERNAL_WALL_CELLS+N_INTERNAL_WALL_CELLS,HM%WALL_INDEX_D, &
            GM%WALL_TMP_G,GM%WALL_TMP_F,GM%WALL_U_NORMAL,GM%WALL_U_NORMAL_S,GM%WALL_HEAT_TRANS_COEF,GM%WALL_Q_CON_F, &
            GM%WALL_RHO_F,GM%WALL_Q_LEAK,GM%WALL_M_DOT_G_PP_ADJUST,GM%WALL_ZZ_G_WORKD,HM%WALL_DATA_D)
        CALL GPU_WAIT(GM%STRM)
        HM%WALL_DATA_H=HM%WALL_DATA_D

        DO N=1,HM%N_WALL_BC
            IW=HM%WALL_INDEX_H(N)
            WC => WALL(IW)
            BC => BOUNDARY_COORD(WC%BC_INDEX)
            B1 => BOUNDARY_PROP1(WC%B1_INDEX)
            SF => SURFACE(WC%SURF_INDEX)
            B1%TMP_G=HM%WALL_DATA_H(1,N)
            B1%TMP_F=HM%WALL_DATA_H(2,N)
            B1%U_NORMAL=HM%WALL_DATA_H(3,N)
            B1%U_NORMAL_S=HM%WALL_DATA_H(4,N)
            B1%HEAT_TRANS_COEF=HM%WALL_DATA_H(5,N)
            B1%Q_CON_F=HM%WALL_DATA_H(6,N)
            B1%RHO_F=HM%WALL_DATA_H(7,N)
            B1%Q_LEAK=HM%WALL_DATA_H(8,N)
            IF (ALLOCATED(B1%M_DOT_G_PP_ADJUST)) THEN
                DO NS=1,N_TRACKED_SPECIES
                    B1%M_DOT_G_PP_ADJUST(NS)=HM%WALL_DATA_H(HVAC_WALL_FIELD_COUNT+NS,N)
                ENDDO
            ENDIF
            DO NS=1,N_TRACKED_SPECIES
                B1%ZZ_G(NS)=HM%WALL_DATA_H(HVAC_WALL_FIELD_COUNT+N_TRACKED_SPECIES+NS,N)
            ENDDO
            CALL CALC_HVAC_BC(BC,B1,SF)
            DU=DUCTNODE(B1%NODE_INDEX)%DUCT_INDEX(1)
            IF (-DUCTNODE(B1%NODE_INDEX)%DIR(1)*DUCT_MF(DU)>=0._EB) THEN
                HM%WALL_SPECIES_BC_H(N)=SPECIFIED_MASS_FRACTION
            ELSE
                HM%WALL_SPECIES_BC_H(N)=SPECIFIED_MASS_FLUX
            ENDIF
            HM%WALL_DATA_H(3,N)=B1%U_NORMAL
            HM%WALL_DATA_H(4,N)=B1%U_NORMAL_S
            HM%WALL_DATA_H(2,N)=B1%TMP_F
            HM%WALL_DATA_H(5,N)=B1%HEAT_TRANS_COEF
            HM%WALL_DATA_H(6,N)=B1%Q_CON_F
            HM%WALL_DATA_H(7,N)=B1%RHO_F
            HM%WALL_DATA_H(8,N)=B1%Q_LEAK
            IF (ALLOCATED(B1%M_DOT_G_PP_ADJUST)) THEN
                DO NS=1,N_TRACKED_SPECIES
                    HM%WALL_DATA_H(HVAC_WALL_FIELD_COUNT+NS,N)=B1%M_DOT_G_PP_ADJUST(NS)
                ENDDO
            ENDIF
        ENDDO

        HM%WALL_DATA_D=HM%WALL_DATA_H
        HM%WALL_SPECIES_BC_D=HM%WALL_SPECIES_BC_H
        CALL APPLY_HVAC_WALL_STATE<<<NB,HVAC_COPY_BLOCK,0,GM%STRM>>>(HM%N_WALL_BC,N_TRACKED_SPECIES, &
            HVAC_WALL_FIELD_COUNT+2*N_TRACKED_SPECIES,GM%WALL_UB,HM%WALL_INDEX_D, &
            GM%WALL_TMP_F,GM%WALL_U_NORMAL,GM%WALL_U_NORMAL_S,GM%WALL_HEAT_TRANS_COEF,GM%WALL_Q_CON_F,GM%WALL_RHO_F, &
            GM%WALL_Q_LEAK,GM%WALL_M_DOT_G_PP_ADJUST,HM%WALL_DATA_D)
        CALL SET_GPU_HVAC_SPECIES_BC_OVERRIDE<<<NB,HVAC_COPY_BLOCK,0,GM%STRM>>>(HM%N_WALL_BC, &
            HM%WALL_INDEX_D,HM%WALL_SPECIES_BC_D,HM%WALL_SPECIES_BC_OVERRIDE_D)
        CALL GPU_WAIT(GM%STRM)
    END SUBROUTINE APPLY_GPU_HVAC_BOUNDARY_BC


    SUBROUTINE FINISH_GPU_HVAC
        INTEGER :: NM
        IF (.NOT.ALLOCATED(GPU_HVAC_MESHES)) RETURN
        DO NM=1,SIZE(GPU_HVAC_MESHES)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%I_H)) DEALLOCATE(GPU_HVAC_MESHES(NM)%I_H,GPU_HVAC_MESHES(NM)%J_H, &
                GPU_HVAC_MESHES(NM)%K_H,GPU_HVAC_MESHES(NM)%IOR_H)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%I_D)) DEALLOCATE(GPU_HVAC_MESHES(NM)%I_D,GPU_HVAC_MESHES(NM)%J_D, &
                GPU_HVAC_MESHES(NM)%K_D,GPU_HVAC_MESHES(NM)%IOR_D)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%WALL_INDEX_H)) DEALLOCATE(GPU_HVAC_MESHES(NM)%WALL_INDEX_H)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%WALL_INDEX_D)) DEALLOCATE(GPU_HVAC_MESHES(NM)%WALL_INDEX_D)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%WALL_SPECIES_BC_H)) DEALLOCATE(GPU_HVAC_MESHES(NM)%WALL_SPECIES_BC_H)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%WALL_SPECIES_BC_D)) DEALLOCATE(GPU_HVAC_MESHES(NM)%WALL_SPECIES_BC_D)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%WALL_SPECIES_BC_OVERRIDE_D)) &
                DEALLOCATE(GPU_HVAC_MESHES(NM)%WALL_SPECIES_BC_OVERRIDE_D)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%CELL_DATA_H)) DEALLOCATE(GPU_HVAC_MESHES(NM)%CELL_DATA_H)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%CELL_DATA_D)) DEALLOCATE(GPU_HVAC_MESHES(NM)%CELL_DATA_D)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%WALL_DATA_H)) DEALLOCATE(GPU_HVAC_MESHES(NM)%WALL_DATA_H)
            IF (ALLOCATED(GPU_HVAC_MESHES(NM)%WALL_DATA_D)) DEALLOCATE(GPU_HVAC_MESHES(NM)%WALL_DATA_D)
        ENDDO
        DEALLOCATE(GPU_HVAC_MESHES)
    END SUBROUTINE FINISH_GPU_HVAC


    ATTRIBUTES(GLOBAL) SUBROUTINE SET_GPU_HVAC_SPECIES_BC_OVERRIDE(N_WALL_BC,WALL_INDEX_D,WALL_SPECIES_BC_D,OVERRIDE_D)
        INTEGER, VALUE :: N_WALL_BC
        INTEGER, DEVICE :: WALL_INDEX_D(*),WALL_SPECIES_BC_D(*),OVERRIDE_D(0:*)
        INTEGER :: N,IW

        N=(BLOCKIDX%X-1)*BLOCKDIM%X+THREADIDX%X
        IF (N>N_WALL_BC) RETURN
        IW=WALL_INDEX_D(N)
        OVERRIDE_D(IW)=WALL_SPECIES_BC_D(N)
    END SUBROUTINE SET_GPU_HVAC_SPECIES_BC_OVERRIDE


    ATTRIBUTES(GLOBAL) SUBROUTINE GATHER_HVAC_CELL_STATE(NBC,NTRACKED,NDATA,IBP1_IN,JBP1_IN,KBP1_IN,I_D,J_D,K_D,IOR_D, &
        RHOD,TMPD,KRESD,HD,ZZD,UD,VD,WD,DATA_D)
        INTEGER, VALUE :: NBC,NTRACKED,NDATA,IBP1_IN,JBP1_IN,KBP1_IN
        INTEGER, DEVICE :: I_D(*),J_D(*),K_D(*),IOR_D(*)
        REAL(EB), DEVICE :: RHOD(0:IBP1_IN,0:JBP1_IN,0:*),TMPD(0:IBP1_IN,0:JBP1_IN,0:*), &
                            KRESD(0:IBP1_IN,0:JBP1_IN,0:*),HD(0:IBP1_IN,0:JBP1_IN,0:*), &
                            UD(0:IBP1_IN,0:JBP1_IN,0:*),VD(0:IBP1_IN,0:JBP1_IN,0:*),WD(0:IBP1_IN,0:JBP1_IN,0:*)
        REAL(EB), DEVICE :: ZZD(0:IBP1_IN,0:JBP1_IN,0:KBP1_IN,1:NTRACKED)
        REAL(EB), DEVICE :: DATA_D(1:NDATA,*)
        INTEGER :: N,I,J,K,NS,IOR
        N=(BLOCKIDX%X-1)*BLOCKDIM%X+THREADIDX%X
        IF (N>NBC) RETURN
        I=I_D(N); J=J_D(N); K=K_D(N); IOR=IOR_D(N)
        DATA_D(1,N)=RHOD(I,J,K)
        DATA_D(2,N)=TMPD(I,J,K)
        DATA_D(3,N)=KRESD(I,J,K)
        DATA_D(4,N)=HD(I,J,K)
        SELECT CASE(IOR)
            CASE( 1); DATA_D(5,N)=UD(I-1,J,K)
            CASE(-1); DATA_D(5,N)=UD(I,J,K)
            CASE( 2); DATA_D(5,N)=VD(I,J-1,K)
            CASE(-2); DATA_D(5,N)=VD(I,J,K)
            CASE( 3); DATA_D(5,N)=WD(I,J,K-1)
            CASE(-3); DATA_D(5,N)=WD(I,J,K)
            CASE DEFAULT; DATA_D(5,N)=0._EB
        END SELECT
        DO NS=1,NTRACKED
            DATA_D(HVAC_CELL_FIELD_COUNT+NS,N)=ZZD(I,J,K,NS)
        ENDDO
    END SUBROUTINE GATHER_HVAC_CELL_STATE


    ATTRIBUTES(GLOBAL) SUBROUTINE GATHER_HVAC_WALL_STATE(NWALL,NTRACKED,NDATA,WALL_UB,N_WALL_TOTAL,WALL_INDEX_D, &
        TMP_G,TMP_F,U_NORMAL,U_NORMAL_S, &
        HTC,Q_CON_F,RHO_F,Q_LEAK,M_DOT_ADJUST,ZZ_G,DATA_D)
        INTEGER, VALUE :: NWALL,NTRACKED,NDATA,WALL_UB,N_WALL_TOTAL
        INTEGER, DEVICE :: WALL_INDEX_D(*)
        REAL(EB), DEVICE :: TMP_G(0:*),TMP_F(0:*),U_NORMAL(0:*),U_NORMAL_S(0:*),HTC(0:*),Q_CON_F(0:*),RHO_F(0:*),Q_LEAK(0:*)
        REAL(EB), DEVICE :: M_DOT_ADJUST(0:WALL_UB,1:NTRACKED),ZZ_G(1:N_WALL_TOTAL,1:NTRACKED)
        REAL(EB), DEVICE :: DATA_D(1:NDATA,*)
        INTEGER :: N,IW,NS
        N=(BLOCKIDX%X-1)*BLOCKDIM%X+THREADIDX%X
        IF (N>NWALL) RETURN
        IW=WALL_INDEX_D(N)
        DATA_D(1,N)=TMP_G(IW)
        DATA_D(2,N)=TMP_F(IW)
        DATA_D(3,N)=U_NORMAL(IW)
        DATA_D(4,N)=U_NORMAL_S(IW)
        DATA_D(5,N)=HTC(IW)
        DATA_D(6,N)=Q_CON_F(IW)
        DATA_D(7,N)=RHO_F(IW)
        DATA_D(8,N)=Q_LEAK(IW)
        DO NS=1,NTRACKED
            DATA_D(HVAC_WALL_FIELD_COUNT+NS,N)=M_DOT_ADJUST(IW,NS)
            DATA_D(HVAC_WALL_FIELD_COUNT+NTRACKED+NS,N)=ZZ_G(IW,NS)
        ENDDO
    END SUBROUTINE GATHER_HVAC_WALL_STATE


    ATTRIBUTES(GLOBAL) SUBROUTINE APPLY_HVAC_WALL_STATE(NWALL,NTRACKED,NDATA,WALL_UB,WALL_INDEX_D,TMP_F,U_NORMAL,U_NORMAL_S,HTC,Q_CON_F, &
        RHO_F,Q_LEAK,M_DOT_ADJUST,DATA_D)
        INTEGER, VALUE :: NWALL,NTRACKED,NDATA,WALL_UB
        INTEGER, DEVICE :: WALL_INDEX_D(*)
        REAL(EB), DEVICE :: TMP_F(0:*),U_NORMAL(0:*),U_NORMAL_S(0:*),HTC(0:*),Q_CON_F(0:*),RHO_F(0:*),Q_LEAK(0:*)
        REAL(EB), DEVICE :: M_DOT_ADJUST(0:WALL_UB,1:NTRACKED)
        REAL(EB), DEVICE :: DATA_D(1:NDATA,*)
        INTEGER :: N,IW,NS
        N=(BLOCKIDX%X-1)*BLOCKDIM%X+THREADIDX%X
        IF (N>NWALL) RETURN
        IW=WALL_INDEX_D(N)
        U_NORMAL(IW)=DATA_D(3,N)
        U_NORMAL_S(IW)=DATA_D(4,N)
        TMP_F(IW)=DATA_D(2,N)
        HTC(IW)=DATA_D(5,N)
        Q_CON_F(IW)=DATA_D(6,N)
        RHO_F(IW)=DATA_D(7,N)
        Q_LEAK(IW)=DATA_D(8,N)
        DO NS=1,NTRACKED
            M_DOT_ADJUST(IW,NS)=DATA_D(HVAC_WALL_FIELD_COUNT+NS,N)
        ENDDO
    END SUBROUTINE APPLY_HVAC_WALL_STATE

