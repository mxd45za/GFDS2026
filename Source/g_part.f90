    INTEGER FUNCTION GPU_PARTICLE_COUNT(NM) RESULT(NP)
        INTEGER, INTENT(IN) :: NM

        ! Remote meshes use the diagnostic count received by MPI. Local counts
        ! are already known from exchange; the output mirror may be out of date.
        NP = MESHES(NM)%NLP
        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        IF (PROCESS(NM)==MY_RANK) NP = GPU_PARTICLES(NM)%COUNT
    END FUNCTION GPU_PARTICLE_COUNT

    SUBROUTINE INITIALIZE_GPU_PARTICLE_CLASSES
        INTEGER :: NC,IT,NCLASS,Y_INDEX,NM,IW,NN,NOM,IERR,NREQUEST
        REAL(EB), ALLOCATABLE :: BOUNDS_H(:,:),LIFETIME_H(:)
        LOGICAL, ALLOCATABLE :: STATIC_H(:)
        INTEGER, ALLOCATABLE :: ARRAY_INDEX_H(:)
        REAL(EB), ALLOCATABLE :: Y_H(:),Z_H(:),BOIL_H(:),MELT_H(:),ADJ_H(:),KILL_H(:),DENS_H(:),MW_H(:),MW_SPEC_H(:)
        REAL(EB), ALLOCATABLE :: CP_H(:,:)
        REAL(EB), ALLOCATABLE :: R50_H(:,:),WQABS_H(:,:,:),WQSCA_H(:,:,:)
        INTEGER, ALLOCATABLE :: EVAP_H(:)
        LOGICAL, ALLOCATABLE :: LIQ_H(:)
        REAL(EB), ALLOCATABLE :: HHEAT_H(:),HMASS_H(:),HV_H(:,:),DENSE_FRACTION_H(:)
        REAL(EB) :: HV,HV_EFF,T_BOIL,X_EQ
        TYPE(LAGRANGIAN_PARTICLE_CLASS_TYPE), POINTER :: LPC

        IF (GPU_PARTICLE_CLASSES_READY) RETURN

        CALL MPI_COMM_DUP(MPI_COMM_WORLD,PARTICLE_COMM,IERR)
        IF (IERR/=MPI_SUCCESS) CALL MPI_ABORT(MPI_COMM_WORLD,IERR,NN)
        ALLOCATE(MESH_BOUNDS_D(6,NMESHES),BOUNDS_H(6,NMESHES),PARTICLE_PEER(NMESHES,NMESHES))
        PARTICLE_PEER = .FALSE.
        DO NM=1,NMESHES
            BOUNDS_H(:,NM) = [MESHES(NM)%XS,MESHES(NM)%XF,MESHES(NM)%YS,MESHES(NM)%YF, &
                             MESHES(NM)%ZS,MESHES(NM)%ZF]
            DO NN=1,MESHES(NM)%N_NEIGHBORING_MESHES
                NOM = MESHES(NM)%NEIGHBORING_MESH(NN)
                IF (NOM==NM) CYCLE
                PARTICLE_PEER(NM,NOM) = .TRUE.
                PARTICLE_PEER(NOM,NM) = .TRUE.
            ENDDO
        ENDDO
        ! READ_MESH already includes the opposite-edge neighbors of a periodic domain.
        MESH_BOUNDS_D = BOUNDS_H
        NREQUEST = 4*COUNT(PARTICLE_PEER(LOWER_MESH_INDEX:UPPER_MESH_INDEX,:))
        ALLOCATE(PARTICLE_REQUEST(MAX(1,NREQUEST)))

        DO NC=1,N_LAGRANGIAN_CLASSES
            LPC => LAGRANGIAN_PARTICLE_CLASS(NC)
            IF (.NOT.LPC%LIQUID_DROPLET) CYCLE
            DO NM=1,NMESHES
                DO IW=1,MESHES(NM)%N_WALL_CELLS
                    IF (MESHES(NM)%WALL(IW)%BOUNDARY_TYPE==SOLID_BOUNDARY) &
                        ERROR STOP 'GPU liquid droplets with solid walls are not supported; use --c/--gc'
                ENDDO
            ENDDO
        ENDDO

        NCLASS = MAX(1,N_LAGRANGIAN_CLASSES)
        ALLOCATE(Y_H(NCLASS),Z_H(NCLASS),EVAP_H(NCLASS),LIQ_H(NCLASS),BOIL_H(NCLASS),MELT_H(NCLASS),ADJ_H(NCLASS),KILL_H(NCLASS))
        ALLOCATE(DENS_H(NCLASS),CP_H(0:I_MAX_TEMP,NCLASS),MW_H(NCLASS),MW_SPEC_H(N_SPECIES))
        ALLOCATE(DENSE_FRACTION_H(NCLASS))
        ALLOCATE(HHEAT_H(NCLASS),HMASS_H(NCLASS))
        ALLOCATE(HV_H(0:I_MAX_TEMP,NCLASS))

        IF (RADIATION .AND. N_LP_ARRAY_INDICES>0) THEN
            ALLOCATE(R50_H(0:MIE_NDG,N_LP_ARRAY_INDICES))
            ALLOCATE(WQABS_H(0:MIE_NDG,N_LP_ARRAY_INDICES,NUMBER_SPECTRAL_BANDS), &
                     WQSCA_H(0:MIE_NDG,N_LP_ARRAY_INDICES,NUMBER_SPECTRAL_BANDS))
            R50_H = 0._EB
            WQABS_H = 0._EB
            WQSCA_H = 0._EB
        ENDIF

        Y_H = 0._EB
        Z_H = 0._EB
        EVAP_H = 0
        LIQ_H = .FALSE.
        BOIL_H = 373.15_EB
        MELT_H = 0._EB
        ADJ_H = 1._EB
        KILL_H = 0._EB
        DENS_H = 1000._EB
        DENSE_FRACTION_H = 1.E-5_EB
        CP_H = 4180._EB
        MW_H = 18.01528_EB
        DO IT=1,N_SPECIES
            MW_SPEC_H(IT) = MAX(TWO_EPSILON_EB,SPECIES(IT)%MW)
        ENDDO
        HHEAT_H = -1._EB
        HMASS_H = -1._EB
        HV_H = 0._EB

        DO NC=1,N_LAGRANGIAN_CLASSES
            LPC => LAGRANGIAN_PARTICLE_CLASS(NC)
            Y_INDEX = LPC%Y_INDEX
            IF (RADIATION .AND. N_LP_ARRAY_INDICES>0) THEN
                IF (LPC%LIQUID_DROPLET .AND. LPC%ARRAY_INDEX>0 .AND. LPC%ARRAY_INDEX<=N_LP_ARRAY_INDICES) THEN
                    IF (ALLOCATED(LPC%R50)) R50_H(:,LPC%ARRAY_INDEX) = LPC%R50
                    IF (ALLOCATED(LPC%WQABS)) WQABS_H(:,LPC%ARRAY_INDEX,:) = LPC%WQABS
                    IF (ALLOCATED(LPC%WQSCA)) WQSCA_H(:,LPC%ARRAY_INDEX,:) = LPC%WQSCA
                ENDIF
            ENDIF
            IF (.NOT.LPC%LIQUID_DROPLET .OR. Y_INDEX<1 .OR. Y_INDEX>SIZE(SPECIES)) CYCLE

            Y_H(NC) = Y_INDEX
            Z_H(NC) = MAX(1,LPC%Z_INDEX)
            EVAP_H(NC) = LPC%EVAP_MODEL
            LIQ_H(NC) = LPC%LIQUID_DROPLET
            BOIL_H(NC) = MAX(1._EB,SPECIES(Y_INDEX)%TMP_V)
            MELT_H(NC) = MAX(0._EB,SPECIES(Y_INDEX)%TMP_MELT)
            ADJ_H(NC) = MAX(TWO_EPSILON_EB,LPC%ADJUST_EVAPORATION)
            KILL_H(NC) = MAX(0._EB,LPC%KILL_RADIUS)
            DENSE_FRACTION_H(NC) = LPC%DENSE_VOLUME_FRACTION
            DENS_H(NC) = MAX(TWO_EPSILON_EB,MAX(LPC%DENSITY,SPECIES(Y_INDEX)%DENSITY_LIQUID))
            IF (ALLOCATED(SPECIES(Y_INDEX)%C_P_L)) THEN
                CP_H(:,NC) = SPECIES(Y_INDEX)%C_P_L
            ELSE
                CP_H(:,NC) = MAX(1._EB,SPECIES(Y_INDEX)%SPECIFIC_HEAT_LIQUID)
            ENDIF
            MW_H(NC) = MAX(TWO_EPSILON_EB,SPECIES(Y_INDEX)%MW)
            HHEAT_H(NC) = LPC%HEAT_TRANSFER_COEFFICIENT_GAS
            HMASS_H(NC) = LPC%MASS_TRANSFER_COEFFICIENT

            IF (.NOT.ALLOCATED(SPECIES(Y_INDEX)%H_V)) CYCLE
            DO IT=0,I_MAX_TEMP
                HV_EFF = 0._EB
                T_BOIL = BOIL_H(NC)
                X_EQ = 0._EB
                IF (IT>0) THEN
                    CALL GET_EQUIL_DATA(MW_H(NC),REAL(IT,EB),P_INF,HV,HV_EFF,T_BOIL,X_EQ,SPECIES(Y_INDEX)%H_V)
                    HV_H(IT,NC) = MAX(0._EB,HV)
                ELSE
                    HV_H(IT,NC) = SPECIES(Y_INDEX)%H_V(1)
                ENDIF
            ENDDO
        ENDDO

        ALLOCATE(CLASS_Y_INDEX_D(NCLASS),CLASS_Z_INDEX_D(NCLASS),CLASS_ARRAY_INDEX_D(NCLASS),CLASS_EVAP_MODEL_D(NCLASS))
        ALLOCATE(CLASS_LIQUID_D(NCLASS),CLASS_STATIC_D(NCLASS))
        ALLOCATE(CLASS_LIFETIME_D(NCLASS))
        ALLOCATE(STATIC_H(NCLASS),ARRAY_INDEX_H(NCLASS),LIFETIME_H(NCLASS))
        STATIC_H = .TRUE.
        ARRAY_INDEX_H = 0
        LIFETIME_H = HUGE(1._EB)
        ALLOCATE(CLASS_DENSITY_D(NCLASS),CLASS_CP_L_D(0:I_MAX_TEMP,NCLASS),CLASS_MW_D(NCLASS))
        ALLOCATE(CLASS_DENSE_VOLUME_FRACTION_D(NCLASS))
        ALLOCATE(CLASS_T_BOIL_D(NCLASS),CLASS_T_MELT_D(NCLASS),CLASS_ADJUST_D(NCLASS),CLASS_KILL_RADIUS_D(NCLASS))
        ALLOCATE(CLASS_H_HEAT_D(NCLASS),CLASS_H_MASS_D(NCLASS))
        ALLOCATE(CLASS_H_V_D(0:I_MAX_TEMP,NCLASS))
        ALLOCATE(SPECIES_MW_D(N_SPECIES))
        IF (RADIATION .AND. N_LP_ARRAY_INDICES>0) THEN
            ALLOCATE(CLASS_R50_D(0:MIE_NDG,N_LP_ARRAY_INDICES))
            ALLOCATE(CLASS_WQABS_D(0:MIE_NDG,N_LP_ARRAY_INDICES,NUMBER_SPECTRAL_BANDS), &
                     CLASS_WQSCA_D(0:MIE_NDG,N_LP_ARRAY_INDICES,NUMBER_SPECTRAL_BANDS))
            CLASS_R50_D = R50_H
            CLASS_WQABS_D = WQABS_H
            CLASS_WQSCA_D = WQSCA_H
            DEALLOCATE(R50_H,WQABS_H,WQSCA_H)
        ENDIF

        CLASS_Y_INDEX_D = Y_H
        CLASS_Z_INDEX_D = Z_H
        CLASS_ARRAY_INDEX_D = 0
        CLASS_EVAP_MODEL_D = EVAP_H
        CLASS_LIQUID_D = LIQ_H
        CLASS_DENSITY_D = DENS_H
        CLASS_DENSE_VOLUME_FRACTION_D = DENSE_FRACTION_H
        CLASS_CP_L_D = CP_H
        CLASS_MW_D = MW_H
        CLASS_T_BOIL_D = BOIL_H
        CLASS_T_MELT_D = MELT_H
        CLASS_ADJUST_D = ADJ_H
        CLASS_KILL_RADIUS_D = KILL_H
        CLASS_H_HEAT_D = HHEAT_H
        CLASS_H_MASS_D = HMASS_H
        CLASS_H_V_D = HV_H
        SPECIES_MW_D = MW_SPEC_H

        DO NC=1,N_LAGRANGIAN_CLASSES
            LPC => LAGRANGIAN_PARTICLE_CLASS(NC)
            STATIC_H(NC) = LPC%STATIC
            ARRAY_INDEX_H(NC) = LPC%ARRAY_INDEX
            LIFETIME_H(NC) = LPC%LIFETIME
        ENDDO
        CLASS_STATIC_D = STATIC_H
        CLASS_ARRAY_INDEX_D = ARRAY_INDEX_H
        CLASS_LIFETIME_D = LIFETIME_H

        DEALLOCATE(Y_H,Z_H,EVAP_H,LIQ_H,BOIL_H,MELT_H,ADJ_H,KILL_H,DENS_H,DENSE_FRACTION_H,CP_H,MW_H,MW_SPEC_H, &
                   HHEAT_H,HMASS_H,HV_H)
        IF (ALLOCATED(R50_H)) DEALLOCATE(R50_H,WQABS_H,WQSCA_H)
        GPU_PARTICLE_CLASSES_READY = .TRUE.
    END SUBROUTINE INITIALIZE_GPU_PARTICLE_CLASSES

    SUBROUTINE INITIALIZE_GPU_PARTICLES(NM)
        INTEGER, INTENT(IN) :: NM
        INTEGER :: NP,CAP,NOM

        IF (N_LAGRANGIAN_CLASSES==0) RETURN
        IF (.NOT.ALLOCATED(GPU_PARTICLES)) ALLOCATE(GPU_PARTICLES(NMESHES))
        CALL INITIALIZE_GPU_PARTICLE_CLASSES
        CALL RELEASE_PARTICLE_MESH(NM)

        NP = MESHES(NM)%NLP
        GPU_PARTICLES(NM)%HOST_COUNT = NP
        IF (NP>0) MESHES(NM)%PARTICLES_EXISTED = .TRUE.

        CAP = MAX(NP,16)
        GPU_PARTICLES(NM)%COUNT = NP
        GPU_PARTICLES(NM)%CAPACITY = CAP

        CALL CHECK_GPU_PARTICLE_RANGE(NM,1,NP)

        ALLOCATE(GPU_PARTICLES(NM)%TAG(CAP),GPU_PARTICLES(NM)%CLASS_INDEX(CAP))
        ALLOCATE(GPU_PARTICLES(NM)%CELL_I(CAP),GPU_PARTICLES(NM)%CELL_J(CAP),GPU_PARTICLES(NM)%CELL_K(CAP))
        ALLOCATE(GPU_PARTICLES(NM)%META(4,CAP),GPU_PARTICLES(NM)%DESTINATION(CAP),GPU_PARTICLES(NM)%SLOT(CAP))
        ALLOCATE(GPU_PARTICLES(NM)%COUNTS(0:NMESHES+1),GPU_PARTICLES(NM)%OFFSETS(NMESHES))
        ALLOCATE(GPU_PARTICLES(NM)%SEND_COUNT(0:NMESHES+1),GPU_PARTICLES(NM)%RECV_COUNT(NMESHES), &
                 GPU_PARTICLES(NM)%SEND_OFFSET(NMESHES),GPU_PARTICLES(NM)%RECV_OFFSET(NMESHES))
        ! A trailing sentinel also avoids zero-sized device allocation on single-mesh cases.
        ALLOCATE(GPU_PARTICLES(NM)%NEIGHBORS(COUNT(PARTICLE_PEER(NM,:))+1))
        GPU_PARTICLES(NM)%NEIGHBORS = [PACK([(NOM,NOM=1,NMESHES)],PARTICLE_PEER(NM,:)),0]
        ALLOCATE(GPU_PARTICLES(NM)%X(CAP),GPU_PARTICLES(NM)%Y(CAP),GPU_PARTICLES(NM)%Z(CAP))
        ALLOCATE(GPU_PARTICLES(NM)%U(CAP),GPU_PARTICLES(NM)%V(CAP),GPU_PARTICLES(NM)%W(CAP))
        ALLOCATE(GPU_PARTICLES(NM)%MASS(CAP),GPU_PARTICLES(NM)%RADIUS(CAP),GPU_PARTICLES(NM)%TEMPERATURE(CAP))
        ALLOCATE(GPU_PARTICLES(NM)%WEIGHT(CAP),GPU_PARTICLES(NM)%RVC(CAP),GPU_PARTICLES(NM)%INSERT_TIME(CAP), &
                 GPU_PARTICLES(NM)%MASS_RATE(CAP))
        ALLOCATE(GPU_PARTICLES(NM)%DRAG_X(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1), &
                 GPU_PARTICLES(NM)%DRAG_Y(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1), &
                 GPU_PARTICLES(NM)%DRAG_Z(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1))
        ALLOCATE(GPU_PARTICLES(NM)%MVAP_TOT(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1))
        GPU_PARTICLES(NM)%DRAG_X = 0._EB
        GPU_PARTICLES(NM)%DRAG_Y = 0._EB
        GPU_PARTICLES(NM)%DRAG_Z = 0._EB
        GPU_PARTICLES(NM)%MVAP_TOT = 0._EB

        IF (N_LP_ARRAY_INDICES>0) THEN
            ALLOCATE(GPU_PARTICLES(NM)%DROP_DEN(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)), &
                     GPU_PARTICLES(NM)%DROP_TMP(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)), &
                     GPU_PARTICLES(NM)%DROP_RAD(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)), &
                     GPU_PARTICLES(NM)%DROP_AREA(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)), &
                     GPU_PARTICLES(NM)%AVG_DROP_DEN(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)), &
                     GPU_PARTICLES(NM)%AVG_DROP_TMP(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)), &
                     GPU_PARTICLES(NM)%AVG_DROP_RAD(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)), &
                     GPU_PARTICLES(NM)%AVG_DROP_AREA(0:MESHES(NM)%IBP1,0:MESHES(NM)%JBP1,0:MESHES(NM)%KBP1,MAX(1,N_LP_ARRAY_INDICES)))
            GPU_PARTICLES(NM)%DROP_DEN = 0._EB
            GPU_PARTICLES(NM)%DROP_TMP = 0._EB
            GPU_PARTICLES(NM)%DROP_RAD = 0._EB
            GPU_PARTICLES(NM)%DROP_AREA = 0._EB
            GPU_PARTICLES(NM)%AVG_DROP_DEN = MESHES(NM)%AVG_DROP_DEN
            GPU_PARTICLES(NM)%AVG_DROP_TMP = MESHES(NM)%AVG_DROP_TMP
            GPU_PARTICLES(NM)%AVG_DROP_RAD = MESHES(NM)%AVG_DROP_RAD
            GPU_PARTICLES(NM)%AVG_DROP_AREA = MESHES(NM)%AVG_DROP_AREA
        ENDIF

        CALL COPY_PARTICLE_RANGE(NM,1,NP)
    END SUBROUTINE INITIALIZE_GPU_PARTICLES

    SUBROUTINE SYNC_GPU_PARTICLE_INSERTIONS(NM)
        INTEGER, INTENT(IN) :: NM
        INTEGER :: NP,IP,FIRST,NEW_COUNT

        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        NP = MESHES(NM)%NLP
        FIRST = GPU_PARTICLES(NM)%HOST_COUNT+1
        IF (NP<FIRST-1) ERROR STOP 'GPU particle output mirror changed during insertion'
        IF (NP<FIRST) RETURN
        NEW_COUNT = GPU_PARTICLES(NM)%COUNT+NP-FIRST+1
        IF (NEW_COUNT>MAXIMUM_PARTICLES) ERROR STOP 'GPU replacement at MAXIMUM_PARTICLES is not supported'
        MESHES(NM)%PARTICLES_EXISTED = .TRUE.
        CALL GPU_WAIT(GPU_MESHES(NM)%STRM)
        IF (NEW_COUNT>GPU_PARTICLES(NM)%CAPACITY) CALL GROW_GPU_PARTICLE_ARRAYS(NM,NEW_COUNT)
        CALL CHECK_GPU_PARTICLE_RANGE(NM,FIRST,NP)
        CALL COPY_PARTICLE_RANGE(NM,FIRST,NP,GPU_PARTICLES(NM)%COUNT+1)
        GPU_PARTICLES(NM)%COUNT = NEW_COUNT
        ! Only the newly generated batch is staged. Existing device particles are never read here.
        DO IP=FIRST,NP
            CALL NULLIFY_PARTICLE(NM,IP)
        ENDDO
        MESHES(NM)%NLP = FIRST-1
    END SUBROUTINE SYNC_GPU_PARTICLE_INSERTIONS


    SUBROUTINE GROW_GPU_PARTICLE_ARRAYS(NM,NEEDED)
        INTEGER, INTENT(IN) :: NM,NEEDED
        INTEGER :: NEW_CAP,OLD_COUNT,NTHREADS,NBLOCKS
        TYPE(GPU_MESH_TYPE), POINTER :: GM_LOCAL
        TYPE(GPU_PARTICLE_MESH_TYPE) :: NEW_PARTICLES

        OLD_COUNT = GPU_PARTICLES(NM)%COUNT
        NEW_CAP = MAX(NEEDED,MAX(16,2*GPU_PARTICLES(NM)%CAPACITY))

        ALLOCATE(NEW_PARTICLES%META(4,NEW_CAP))

        ALLOCATE(NEW_PARTICLES%TAG(NEW_CAP),NEW_PARTICLES%CLASS_INDEX(NEW_CAP))
        ALLOCATE(NEW_PARTICLES%CELL_I(NEW_CAP),NEW_PARTICLES%CELL_J(NEW_CAP),NEW_PARTICLES%CELL_K(NEW_CAP))
        ALLOCATE(NEW_PARTICLES%X(NEW_CAP),NEW_PARTICLES%Y(NEW_CAP),NEW_PARTICLES%Z(NEW_CAP))
        ALLOCATE(NEW_PARTICLES%U(NEW_CAP),NEW_PARTICLES%V(NEW_CAP),NEW_PARTICLES%W(NEW_CAP))
        ALLOCATE(NEW_PARTICLES%MASS(NEW_CAP),NEW_PARTICLES%RADIUS(NEW_CAP),NEW_PARTICLES%TEMPERATURE(NEW_CAP))
        ALLOCATE(NEW_PARTICLES%WEIGHT(NEW_CAP),NEW_PARTICLES%RVC(NEW_CAP),NEW_PARTICLES%INSERT_TIME(NEW_CAP))
        ALLOCATE(NEW_PARTICLES%MASS_RATE(NEW_CAP))

        IF (OLD_COUNT>0) THEN
            NTHREADS = 128
            NBLOCKS = (OLD_COUNT+NTHREADS-1)/NTHREADS
            GM_LOCAL => GPU_MESHES(NM)
            CALL COPY_GPU_PARTICLE_ARRAYS_KERNEL<<<NBLOCKS,NTHREADS,0,GM_LOCAL%STRM>>>(OLD_COUNT, &
                GPU_PARTICLES(NM)%TAG,NEW_PARTICLES%TAG,GPU_PARTICLES(NM)%CLASS_INDEX,NEW_PARTICLES%CLASS_INDEX, &
                GPU_PARTICLES(NM)%CELL_I,NEW_PARTICLES%CELL_I,GPU_PARTICLES(NM)%CELL_J,NEW_PARTICLES%CELL_J, &
                GPU_PARTICLES(NM)%CELL_K,NEW_PARTICLES%CELL_K,GPU_PARTICLES(NM)%X,NEW_PARTICLES%X, &
                GPU_PARTICLES(NM)%Y,NEW_PARTICLES%Y,GPU_PARTICLES(NM)%Z,NEW_PARTICLES%Z, &
                GPU_PARTICLES(NM)%U,NEW_PARTICLES%U,GPU_PARTICLES(NM)%V,NEW_PARTICLES%V, &
                GPU_PARTICLES(NM)%W,NEW_PARTICLES%W,GPU_PARTICLES(NM)%MASS,NEW_PARTICLES%MASS, &
                GPU_PARTICLES(NM)%RADIUS,NEW_PARTICLES%RADIUS,GPU_PARTICLES(NM)%TEMPERATURE,NEW_PARTICLES%TEMPERATURE, &
                GPU_PARTICLES(NM)%WEIGHT,NEW_PARTICLES%WEIGHT,GPU_PARTICLES(NM)%RVC,NEW_PARTICLES%RVC, &
                GPU_PARTICLES(NM)%INSERT_TIME,NEW_PARTICLES%INSERT_TIME,GPU_PARTICLES(NM)%MASS_RATE,NEW_PARTICLES%MASS_RATE, &
                GPU_PARTICLES(NM)%META,NEW_PARTICLES%META)
            CALL GPU_WAIT(GM_LOCAL%STRM)
        ENDIF

        IF (ASSOCIATED(GPU_PARTICLES(NM)%TAG)) DEALLOCATE(GPU_PARTICLES(NM)%TAG)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%CLASS_INDEX)) DEALLOCATE(GPU_PARTICLES(NM)%CLASS_INDEX)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%CELL_I)) DEALLOCATE(GPU_PARTICLES(NM)%CELL_I)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%CELL_J)) DEALLOCATE(GPU_PARTICLES(NM)%CELL_J)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%CELL_K)) DEALLOCATE(GPU_PARTICLES(NM)%CELL_K)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%X)) DEALLOCATE(GPU_PARTICLES(NM)%X)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%Y)) DEALLOCATE(GPU_PARTICLES(NM)%Y)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%Z)) DEALLOCATE(GPU_PARTICLES(NM)%Z)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%U)) DEALLOCATE(GPU_PARTICLES(NM)%U)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%V)) DEALLOCATE(GPU_PARTICLES(NM)%V)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%W)) DEALLOCATE(GPU_PARTICLES(NM)%W)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%MASS)) DEALLOCATE(GPU_PARTICLES(NM)%MASS)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%RADIUS)) DEALLOCATE(GPU_PARTICLES(NM)%RADIUS)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%TEMPERATURE)) DEALLOCATE(GPU_PARTICLES(NM)%TEMPERATURE)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%WEIGHT)) DEALLOCATE(GPU_PARTICLES(NM)%WEIGHT)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%RVC)) DEALLOCATE(GPU_PARTICLES(NM)%RVC)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%INSERT_TIME)) DEALLOCATE(GPU_PARTICLES(NM)%INSERT_TIME)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%MASS_RATE)) DEALLOCATE(GPU_PARTICLES(NM)%MASS_RATE)
        GPU_PARTICLES(NM)%TAG => NEW_PARTICLES%TAG
        GPU_PARTICLES(NM)%CLASS_INDEX => NEW_PARTICLES%CLASS_INDEX
        GPU_PARTICLES(NM)%CELL_I => NEW_PARTICLES%CELL_I
        GPU_PARTICLES(NM)%CELL_J => NEW_PARTICLES%CELL_J
        GPU_PARTICLES(NM)%CELL_K => NEW_PARTICLES%CELL_K
        GPU_PARTICLES(NM)%X => NEW_PARTICLES%X
        GPU_PARTICLES(NM)%Y => NEW_PARTICLES%Y
        GPU_PARTICLES(NM)%Z => NEW_PARTICLES%Z
        GPU_PARTICLES(NM)%U => NEW_PARTICLES%U
        GPU_PARTICLES(NM)%V => NEW_PARTICLES%V
        GPU_PARTICLES(NM)%W => NEW_PARTICLES%W
        GPU_PARTICLES(NM)%MASS => NEW_PARTICLES%MASS
        GPU_PARTICLES(NM)%RADIUS => NEW_PARTICLES%RADIUS
        GPU_PARTICLES(NM)%TEMPERATURE => NEW_PARTICLES%TEMPERATURE
        GPU_PARTICLES(NM)%WEIGHT => NEW_PARTICLES%WEIGHT
        GPU_PARTICLES(NM)%RVC => NEW_PARTICLES%RVC
        GPU_PARTICLES(NM)%INSERT_TIME => NEW_PARTICLES%INSERT_TIME
        GPU_PARTICLES(NM)%MASS_RATE => NEW_PARTICLES%MASS_RATE
        DEALLOCATE(GPU_PARTICLES(NM)%META)
        GPU_PARTICLES(NM)%META => NEW_PARTICLES%META
        DEALLOCATE(GPU_PARTICLES(NM)%DESTINATION,GPU_PARTICLES(NM)%SLOT)
        ALLOCATE(GPU_PARTICLES(NM)%DESTINATION(NEW_CAP),GPU_PARTICLES(NM)%SLOT(NEW_CAP))
        GPU_PARTICLES(NM)%CAPACITY = NEW_CAP
    END SUBROUTINE GROW_GPU_PARTICLE_ARRAYS


