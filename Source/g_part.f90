        IF (ALLOCATED(GPU_PARTICLES(NM)%AVG_DROP_RAD)) DEALLOCATE(GPU_PARTICLES(NM)%AVG_DROP_RAD)
        IF (ALLOCATED(GPU_PARTICLES(NM)%AVG_DROP_AREA)) DEALLOCATE(GPU_PARTICLES(NM)%AVG_DROP_AREA)
        GPU_PARTICLES(NM)%COUNT = 0
        GPU_PARTICLES(NM)%CAPACITY = 0
        GPU_PARTICLES(NM)%HOST_COUNT = 0
        GPU_PARTICLES(NM)%SEND_CAPACITY = 0
        GPU_PARTICLES(NM)%RECV_CAPACITY = 0
    END SUBROUTINE RELEASE_PARTICLE_MESH

