    SUBROUTINE CHECK_GPU_PARTICLE_RANGE(NM,FIRST_PARTICLE,LAST_PARTICLE)
        INTEGER, INTENT(IN) :: NM,FIRST_PARTICLE,LAST_PARTICLE
        INTEGER :: IP,C
        TYPE(LAGRANGIAN_PARTICLE_TYPE), POINTER :: LP
        TYPE(LAGRANGIAN_PARTICLE_CLASS_TYPE), POINTER :: LPC

        IF (LAST_PARTICLE<FIRST_PARTICLE) RETURN

        IF (CYLINDRICAL) ERROR STOP 'GPU particles do not support cylindrical coordinates'
        IF (PARTICLE_CFL) ERROR STOP 'GPU particles do not support PARTICLE_CFL'
        IF (NEAR_WALL_PARTICLE_INTERPOLATION) &
            ERROR STOP 'GPU particles do not support NEAR_WALL_PARTICLE_INTERPOLATION'

        DO IP=FIRST_PARTICLE,LAST_PARTICLE
            LP => MESHES(NM)%LAGRANGIAN_PARTICLE(IP)
            C = LP%CLASS_INDEX
            IF (C<1 .OR. C>N_LAGRANGIAN_CLASSES) ERROR STOP 'GPU particle class index is invalid'
            LPC => LAGRANGIAN_PARTICLE_CLASS(C)
            IF (.NOT.LPC%LIQUID_DROPLET) ERROR STOP 'GPU particles currently support liquid droplets only'
            IF (LPC%DRAG_LAW/=SPHERE_DRAG) ERROR STOP 'GPU particles currently support spherical drag only'
            IF (LPC%BREAKUP .OR. LPC%TURBULENT_DISPERSION .OR. LP%PATH_PARTICLE) &
                ERROR STOP 'GPU particle breakup, dispersion, and path models are not supported'
            IF (LP%WALL_INDEX>0 .OR. LP%CFACE_INDEX>0) ERROR STOP 'GPU particles on walls are not supported'
            IF (LP%DUCT_INDEX>0 .OR. LPC%DUCT_PARTICLE) ERROR STOP 'GPU duct particles are not supported'
        ENDDO
    END SUBROUTINE CHECK_GPU_PARTICLE_RANGE


    SUBROUTINE ADVANCE_GPU_PARTICLES(T,DT,NM)
        REAL(EB), INTENT(IN) :: T,DT
        INTEGER, INTENT(IN) :: NM
        INTEGER :: IBP1,JBP1,KBP1
        INTEGER :: NTHREADS,NBLOCKS

        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        IF (.NOT.ASSOCIATED(GPU_PARTICLES(NM)%CLASS_INDEX)) RETURN

        IBP1 = MESHES(NM)%IBP1
        JBP1 = MESHES(NM)%JBP1
        KBP1 = MESHES(NM)%KBP1
        NTHREADS = 128
        NBLOCKS = (GPU_PARTICLES(NM)%COUNT+NTHREADS-1)/NTHREADS
        GM => GPU_MESHES(NM)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DROP_DEN)) THEN
            GPU_PARTICLES(NM)%DROP_DEN = 0._EB
            GPU_PARTICLES(NM)%DROP_TMP = 0._EB
            GPU_PARTICLES(NM)%DROP_RAD = 0._EB
            GPU_PARTICLES(NM)%DROP_AREA = 0._EB
        ENDIF
        GPU_PARTICLES(NM)%MVAP_TOT = 0._EB
        ! Replace the held predictor force with the force from this particle update.
        GPU_PARTICLES(NM)%DRAG_X = 0._EB
        GPU_PARTICLES(NM)%DRAG_Y = 0._EB
        GPU_PARTICLES(NM)%DRAG_Z = 0._EB
        IF (GPU_PARTICLES(NM)%COUNT==0) THEN
            CALL UPDATE_GPU_PARTICLE_AVERAGES(NM)
            RETURN
        ENDIF
        IF (RADIATION) THEN
            CALL GPU_PARTICLE_STEP_KERNEL<<<NBLOCKS,NTHREADS,0,GM%STRM>>>( &
                GPU_PARTICLES(NM)%COUNT,DT,IBP1,JBP1,KBP1,N_TRACKED_SPECIES,N_SPECIES,I_MAX_TEMP, &
                GPU_PARTICLES(NM)%CLASS_INDEX,GPU_PARTICLES(NM)%CELL_I,GPU_PARTICLES(NM)%CELL_J,GPU_PARTICLES(NM)%CELL_K, &
                GPU_PARTICLES(NM)%U,GPU_PARTICLES(NM)%V,GPU_PARTICLES(NM)%W,GPU_PARTICLES(NM)%MASS, &
                GPU_PARTICLES(NM)%RADIUS,GPU_PARTICLES(NM)%TEMPERATURE,GPU_PARTICLES(NM)%WEIGHT,GPU_PARTICLES(NM)%RVC, &
                GPU_PARTICLES(NM)%MASS_RATE,GM%RADI%QR_W_D,GPU_PARTICLES(NM)%MVAP_TOT,.TRUE.,N_LP_ARRAY_INDICES, &
                GPU_PARTICLES(NM)%AVG_DROP_AREA, &
                GM%UD,GM%VD,GM%WD,GM%RHOD,GM%TMPD,GM%RSUMD,GM%ZZD,GM%PBARD,GM%PRESSURE_ZONED, &
                GM%D_SOURCED,GM%M_DOT_PPPD, &
                CP_ZD,H_SENS_ZD,SPECIES_Z2YD,CLASS_Y_INDEX_D,CLASS_Z_INDEX_D,CLASS_ARRAY_INDEX_D,CLASS_LIQUID_D,CLASS_STATIC_D, &
                CLASS_DENSITY_D,CLASS_CP_L_D,CLASS_MW_D,CLASS_T_BOIL_D,CLASS_T_MELT_D,CLASS_ADJUST_D,CLASS_KILL_RADIUS_D, &
                CLASS_H_HEAT_D,CLASS_H_MASS_D,CLASS_H_V_D,SPECIES_MW_D, &
                MU_RSQMW_ZD,K_RSQMW_ZD,RSQ_MW_ZD,MWR_ZD,D_Z_TABLED,P_STP,DY_MIN_BLOWING,R0, &
                GPU_PARTICLES(NM)%DROP_DEN,GPU_PARTICLES(NM)%DROP_TMP,GPU_PARTICLES(NM)%DROP_RAD,GPU_PARTICLES(NM)%DROP_AREA)
        ELSE
            CALL GPU_PARTICLE_STEP_KERNEL<<<NBLOCKS,NTHREADS,0,GM%STRM>>>( &
                GPU_PARTICLES(NM)%COUNT,DT,IBP1,JBP1,KBP1,N_TRACKED_SPECIES,N_SPECIES,I_MAX_TEMP, &
                GPU_PARTICLES(NM)%CLASS_INDEX,GPU_PARTICLES(NM)%CELL_I,GPU_PARTICLES(NM)%CELL_J,GPU_PARTICLES(NM)%CELL_K, &
                GPU_PARTICLES(NM)%U,GPU_PARTICLES(NM)%V,GPU_PARTICLES(NM)%W,GPU_PARTICLES(NM)%MASS, &
                GPU_PARTICLES(NM)%RADIUS,GPU_PARTICLES(NM)%TEMPERATURE,GPU_PARTICLES(NM)%WEIGHT,GPU_PARTICLES(NM)%RVC, &
                GPU_PARTICLES(NM)%MASS_RATE,GM%QRD,GPU_PARTICLES(NM)%MVAP_TOT,.FALSE.,N_LP_ARRAY_INDICES, &
                GPU_PARTICLES(NM)%AVG_DROP_AREA, &
                GM%UD,GM%VD,GM%WD,GM%RHOD,GM%TMPD,GM%RSUMD,GM%ZZD,GM%PBARD,GM%PRESSURE_ZONED, &
                GM%D_SOURCED,GM%M_DOT_PPPD, &
                CP_ZD,H_SENS_ZD,SPECIES_Z2YD,CLASS_Y_INDEX_D,CLASS_Z_INDEX_D,CLASS_ARRAY_INDEX_D,CLASS_LIQUID_D,CLASS_STATIC_D, &
                CLASS_DENSITY_D,CLASS_CP_L_D,CLASS_MW_D,CLASS_T_BOIL_D,CLASS_T_MELT_D,CLASS_ADJUST_D,CLASS_KILL_RADIUS_D, &
                CLASS_H_HEAT_D,CLASS_H_MASS_D,CLASS_H_V_D,SPECIES_MW_D, &
                MU_RSQMW_ZD,K_RSQMW_ZD,RSQ_MW_ZD,MWR_ZD,D_Z_TABLED,P_STP,DY_MIN_BLOWING,R0, &
                GPU_PARTICLES(NM)%DROP_DEN,GPU_PARTICLES(NM)%DROP_TMP,GPU_PARTICLES(NM)%DROP_RAD,GPU_PARTICLES(NM)%DROP_AREA)
        ENDIF
        CALL UPDATE_GPU_PARTICLE_AVERAGES(NM)
        CALL MOVE_GPU_PARTICLES(NM,DT)
        IF (PARTICLE_DRAG) CALL APPLY_GPU_PARTICLE_DRAG(NM,DT,.FALSE.)
    END SUBROUTINE ADVANCE_GPU_PARTICLES


    SUBROUTINE ADD_GPU_PARTICLE_RADIATION(NM,IBND,BBF,FOUR_SIGMA_IN)
        INTEGER, INTENT(IN) :: NM,IBND
        REAL(EB), INTENT(IN) :: BBF,FOUR_SIGMA_IN
        INTEGER :: IBP1,JBP1,KBP1,NPOINTS,NTHREADS,NBLOCKS

        IF (N_LP_ARRAY_INDICES<=0 .OR. .NOT.ALLOCATED(CLASS_R50_D)) RETURN
        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        IF (.NOT.ALLOCATED(GPU_PARTICLES(NM)%AVG_DROP_AREA)) RETURN

        IBP1 = MESHES(NM)%IBP1
        JBP1 = MESHES(NM)%JBP1
        KBP1 = MESHES(NM)%KBP1
        NPOINTS = (IBP1+1)*(JBP1+1)*(KBP1+1)
        NTHREADS = 128
        NBLOCKS = (NPOINTS+NTHREADS-1)/NTHREADS
        GM => GPU_MESHES(NM)
        CALL GPU_WAIT(GM%STRM)

        CALL GPU_PARTICLE_RADIATION_KERNEL<<<NBLOCKS,NTHREADS>>>( &
            NPOINTS,IBP1,JBP1,KBP1,N_LAGRANGIAN_CLASSES,N_LP_ARRAY_INDICES,MIE_NDG,IBND,BBF,FOUR_SIGMA_IN, &
            GPU_PARTICLES(NM)%AVG_DROP_AREA,GPU_PARTICLES(NM)%AVG_DROP_RAD,GPU_PARTICLES(NM)%AVG_DROP_TMP, &
            CLASS_ARRAY_INDEX_D,CLASS_LIQUID_D,CLASS_R50_D,CLASS_WQABS_D,CLASS_WQSCA_D, &
            GM%WORK5D,GM%WORK7D,GM%WORK6D)

    END SUBROUTINE ADD_GPU_PARTICLE_RADIATION


    ATTRIBUTES(GLOBAL) SUBROUTINE GPU_PARTICLE_RADIATION_KERNEL(NPOINTS,IBP1,JBP1,KBP1,NCLASS,NARRAY,NDG,IBND,BBF,FOUR_SIGMA_IN, &
        AVG_DROP_AREA,AVG_DROP_RAD,AVG_DROP_TMP,CLASS_ARRAY_INDEX,CLASS_LIQUID,CLASS_R50,CLASS_WQABS,CLASS_WQSCA, &
        KAPPA_PART,KFST4_PART,SCAEFF)
        INTEGER, VALUE :: NPOINTS,IBP1,JBP1,KBP1,NCLASS,NARRAY,NDG,IBND
        REAL(EB), VALUE :: BBF,FOUR_SIGMA_IN
        REAL(EB), DEVICE :: AVG_DROP_AREA(0:IBP1,0:JBP1,0:KBP1,*),AVG_DROP_RAD(0:IBP1,0:JBP1,0:KBP1,*)
        REAL(EB), DEVICE :: AVG_DROP_TMP(0:IBP1,0:JBP1,0:KBP1,*)
        INTEGER, DEVICE :: CLASS_ARRAY_INDEX(*)
        LOGICAL, DEVICE :: CLASS_LIQUID(*)
        REAL(EB), DEVICE :: CLASS_R50(0:NDG,1:NARRAY),CLASS_WQABS(0:NDG,1:NARRAY,1:*),CLASS_WQSCA(0:NDG,1:NARRAY,1:*)
        REAL(EB), DEVICE :: KAPPA_PART(0:IBP1,0:JBP1,0:KBP1),KFST4_PART(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: SCAEFF(0:IBP1,0:JBP1,0:KBP1)
        INTEGER :: N,I,J,K,C,A,M
        REAL(EB) :: AREA,RADIUS,TEMP,QABS,QSCA,FRACTION

        N = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X - 1
        IF (N<0 .OR. N>=NPOINTS) RETURN
        I = MOD(N,IBP1+1)
        J = MOD(N/(IBP1+1),JBP1+1)
        K = N/((IBP1+1)*(JBP1+1))

        DO C=1,NCLASS
            IF (.NOT.CLASS_LIQUID(C)) CYCLE
            A = CLASS_ARRAY_INDEX(C)
            IF (A<1 .OR. A>NARRAY) CYCLE
            AREA = AVG_DROP_AREA(I,J,K,A)
            IF (AREA<=TWO_EPSILON_EB) CYCLE
            RADIUS = AVG_DROP_RAD(I,J,K,A)
            TEMP = MAX(0._EB,AVG_DROP_TMP(I,J,K,A))

            IF (RADIUS<=CLASS_R50(0,A)) THEN
                QABS = CLASS_WQABS(0,A,IBND)
                QSCA = CLASS_WQSCA(0,A,IBND)
            ELSEIF (RADIUS>=CLASS_R50(NDG,A)) THEN
                QABS = CLASS_WQABS(NDG,A,IBND)
                QSCA = CLASS_WQSCA(NDG,A,IBND)
            ELSE
                QABS = CLASS_WQABS(NDG,A,IBND)
                QSCA = CLASS_WQSCA(NDG,A,IBND)
                DO M=0,NDG-1
                    IF (RADIUS<=CLASS_R50(M+1,A)) THEN
                        FRACTION = (RADIUS-CLASS_R50(M,A))/MAX(TWO_EPSILON_EB,CLASS_R50(M+1,A)-CLASS_R50(M,A))
                        QABS = CLASS_WQABS(M,A,IBND)+FRACTION*(CLASS_WQABS(M+1,A,IBND)-CLASS_WQABS(M,A,IBND))
                        QSCA = CLASS_WQSCA(M,A,IBND)+FRACTION*(CLASS_WQSCA(M+1,A,IBND)-CLASS_WQSCA(M,A,IBND))
                        EXIT
                    ENDIF
                ENDDO
            ENDIF

            KAPPA_PART(I,J,K) = KAPPA_PART(I,J,K)+AREA*QABS
            KFST4_PART(I,J,K) = KFST4_PART(I,J,K)+BBF*AREA*QABS*FOUR_SIGMA_IN*TEMP*TEMP*TEMP*TEMP
            SCAEFF(I,J,K) = SCAEFF(I,J,K)+AREA*QSCA
        ENDDO
    END SUBROUTINE GPU_PARTICLE_RADIATION_KERNEL


    SUBROUTINE MOVE_GPU_PARTICLES(NM,DT)
        INTEGER, INTENT(IN) :: NM
        REAL(EB), INTENT(IN) :: DT
        INTEGER :: NTHREADS,NBLOCKS,IBP1,JBP1,KBP1

        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        IF (.NOT.ASSOCIATED(GPU_PARTICLES(NM)%CLASS_INDEX)) RETURN
        IF (GPU_PARTICLES(NM)%COUNT<=0) RETURN

        IBP1 = MESHES(NM)%IBP1
        JBP1 = MESHES(NM)%JBP1
        KBP1 = MESHES(NM)%KBP1
        NTHREADS = 128
        NBLOCKS = (GPU_PARTICLES(NM)%COUNT+NTHREADS-1)/NTHREADS
        GM => GPU_MESHES(NM)
        CALL MOVE_GPU_PARTICLES_KERNEL<<<NBLOCKS,NTHREADS,0,GM%STRM>>>( &
            GPU_PARTICLES(NM)%COUNT,DT,MESHES(NM)%IBAR,MESHES(NM)%JBAR,MESHES(NM)%KBAR,IBP1,JBP1,KBP1, &
            GPU_PARTICLES(NM)%CLASS_INDEX,GPU_PARTICLES(NM)%CELL_I,GPU_PARTICLES(NM)%CELL_J,GPU_PARTICLES(NM)%CELL_K, &
            GPU_PARTICLES(NM)%X,GPU_PARTICLES(NM)%Y,GPU_PARTICLES(NM)%Z,GPU_PARTICLES(NM)%U,GPU_PARTICLES(NM)%V,GPU_PARTICLES(NM)%W, &
            GPU_PARTICLES(NM)%RADIUS,GPU_PARTICLES(NM)%MASS,GPU_PARTICLES(NM)%WEIGHT,GPU_PARTICLES(NM)%RVC, &
            GPU_PARTICLES(NM)%MASS_RATE,CLASS_STATIC_D,CLASS_KILL_RADIUS_D,CLASS_LIQUID_D,CLASS_ARRAY_INDEX_D, &
            CLASS_DENSITY_D,CLASS_DENSE_VOLUME_FRACTION_D,GPU_PARTICLES(NM)%AVG_DROP_DEN, &
            GPU_PARTICLES(NM)%DRAG_X,GPU_PARTICLES(NM)%DRAG_Y,GPU_PARTICLES(NM)%DRAG_Z, &
            GM%UD,GM%VD,GM%WD,GM%RHOD,GM%MU_DNSD,GM%PBARD,GM%PRESSURE_ZONED, &
            GM%DXD,GM%DYD,GM%DZD,GM%XCD,GM%YCD,GM%ZCD, &
            GM%RDXND,GM%RDYND,GM%RDZND,GM%CELL_INDEXD,GM%CELL_WALL_INDEX,GM%CELL_LB,GM%CELL_UB, &
            GVEC(1),GVEC(2),GVEC(3))
    END SUBROUTINE MOVE_GPU_PARTICLES


    SUBROUTINE GPU_PARTICLE_MESH_EXCHANGE(T)
        REAL(EB), INTENT(IN) :: T
        INTEGER :: NM,NOM,NR,IERR,ABORT_ERR,N,OFFSET,BASE,NEEDED
        TYPE(GPU_PARTICLE_MESH_TYPE), POINTER :: P,S

        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN

        DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
            P => GPU_PARTICLES(NM)
            CALL GPU_WAIT(GPU_MESHES(NM)%STRM)
            P%COUNTS = 0
            P%SEND_COUNT = 0
            P%RECV_COUNT = 0
            IF (P%COUNT==0) CYCLE
            CALL CLASSIFY_PARTICLES_KERNEL<<<(P%COUNT+PARTICLE_THREADS-1)/PARTICLE_THREADS, &
                PARTICLE_THREADS,0,GPU_MESHES(NM)%STRM>>>(P%COUNT,NM,NMESHES,SIZE(P%NEIGHBORS),T, &
                P%X,P%Y,P%Z,P%RADIUS,P%INSERT_TIME,P%CLASS_INDEX,CLASS_KILL_RADIUS_D,CLASS_LIFETIME_D, &
                MESH_BOUNDS_D,P%NEIGHBORS,P%DESTINATION,P%SLOT,P%COUNTS, &
                PERIODIC_DOMAIN_X,PERIODIC_DOMAIN_Y,PERIODIC_DOMAIN_Z,XS_MIN,XF_MAX,YS_MIN,YF_MAX,ZS_MIN,ZF_MAX)
            CALL GPU_WAIT(GPU_MESHES(NM)%STRM)
            ! Communication sizes only; no particle fields are staged through the host.
            P%SEND_COUNT = P%COUNTS
            IF (P%SEND_COUNT(NMESHES+1)==0) CYCLE
            OFFSET = 0
            DO NOM=1,NMESHES
                P%SEND_OFFSET(NOM) = OFFSET
                OFFSET = OFFSET+P%SEND_COUNT(NOM)
            ENDDO
            P%OFFSETS = P%SEND_OFFSET
            CALL RESERVE_PARTICLE_BUFFER(NM,OFFSET,.TRUE.)
            CALL PACK_GPU_PARTICLES(NM)
        ENDDO

        ! Post all count receives first, including peers with no outgoing particles.
        NR = 0
        DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
            DO NOM=1,NMESHES
                IF (.NOT.PARTICLE_PEER(NM,NOM) .OR. PROCESS(NOM)==MY_RANK) CYCLE
                NR = NR+1
                CALL MPI_IRECV(GPU_PARTICLES(NM)%RECV_COUNT(NOM),1,MPI_INTEGER,PROCESS(NOM),NOM, &
                               PARTICLE_COMM,PARTICLE_REQUEST(NR),IERR)
                IF (IERR/=MPI_SUCCESS) CALL MPI_ABORT(PARTICLE_COMM,IERR,ABORT_ERR)
            ENDDO
        ENDDO
        DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
            DO NOM=1,NMESHES
                IF (.NOT.PARTICLE_PEER(NM,NOM)) CYCLE
                IF (PROCESS(NOM)==MY_RANK) THEN
                    GPU_PARTICLES(NOM)%RECV_COUNT(NM) = GPU_PARTICLES(NM)%SEND_COUNT(NOM)
                ELSE
                    NR = NR+1
                    CALL MPI_ISEND(GPU_PARTICLES(NM)%SEND_COUNT(NOM),1,MPI_INTEGER,PROCESS(NOM),NM, &
                                   PARTICLE_COMM,PARTICLE_REQUEST(NR),IERR)
                    IF (IERR/=MPI_SUCCESS) CALL MPI_ABORT(PARTICLE_COMM,IERR,ABORT_ERR)
                ENDIF
            ENDDO
        ENDDO
        IF (NR>0) CALL GPU_MPI_WAITALL(PARTICLE_REQUEST(1:NR))

        NR = 0
        DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
            P => GPU_PARTICLES(NM)
            OFFSET = 0
            DO NOM=1,NMESHES
                P%RECV_OFFSET(NOM) = OFFSET
                IF (PROCESS(NOM)/=MY_RANK) OFFSET = OFFSET+P%RECV_COUNT(NOM)
            ENDDO
            CALL RESERVE_PARTICLE_BUFFER(NM,OFFSET,.FALSE.)
            DO NOM=1,NMESHES
                N = P%RECV_COUNT(NOM)
                IF (N==0 .OR. PROCESS(NOM)==MY_RANK) CYCLE
                BASE = PARTICLE_REALS*P%RECV_OFFSET(NOM)+1
                NR = NR+1
                CALL GPU_MPI_IRECV(P%RECV_REAL(BASE:BASE+PARTICLE_REALS*N-1),PARTICLE_REALS*N, &
                                   PROCESS(NOM),NOM,PARTICLE_REQUEST(NR),PARTICLE_COMM)
                BASE = PARTICLE_INTS*P%RECV_OFFSET(NOM)+1
                NR = NR+1
                CALL GPU_MPI_IRECV(P%RECV_INT(BASE:BASE+PARTICLE_INTS*N-1),PARTICLE_INTS*N, &
                                   PROCESS(NOM),NOM,PARTICLE_REQUEST(NR),PARTICLE_COMM)
            ENDDO
        ENDDO
        DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
            P => GPU_PARTICLES(NM)
            CALL GPU_WAIT(GPU_MESHES(NM)%STRM) ! Pack must complete before MPI reads device buffers.
            DO NOM=1,NMESHES
                N = P%SEND_COUNT(NOM)
                IF (N==0 .OR. PROCESS(NOM)==MY_RANK) CYCLE
                BASE = PARTICLE_REALS*P%SEND_OFFSET(NOM)+1
                NR = NR+1
                CALL GPU_MPI_ISEND(P%SEND_REAL(BASE:BASE+PARTICLE_REALS*N-1),PARTICLE_REALS*N, &
                                   PROCESS(NOM),NM,PARTICLE_REQUEST(NR),PARTICLE_COMM)
                BASE = PARTICLE_INTS*P%SEND_OFFSET(NOM)+1
                NR = NR+1
                CALL GPU_MPI_ISEND(P%SEND_INT(BASE:BASE+PARTICLE_INTS*N-1),PARTICLE_INTS*N, &
                                   PROCESS(NOM),NM,PARTICLE_REQUEST(NR),PARTICLE_COMM)
            ENDDO
        ENDDO
        IF (NR>0) CALL GPU_MPI_WAITALL(PARTICLE_REQUEST(1:NR))

        DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
            P => GPU_PARTICLES(NM)
            NEEDED = P%SEND_COUNT(NM)+SUM(P%RECV_COUNT)
            IF (NEEDED>MAXIMUM_PARTICLES) ERROR STOP 'GPU particle receive exceeds MAXIMUM_PARTICLES'
            IF (NEEDED>P%CAPACITY) CALL GROW_GPU_PARTICLE_ARRAYS(NM,NEEDED)
            N = P%SEND_COUNT(NM)
            IF (P%SEND_COUNT(NMESHES+1)>0 .AND. N>0) &
                CALL UNPACK_GPU_PARTICLES(NM,N,0,P%SEND_OFFSET(NM),P%SEND_INT,P%SEND_REAL)
            OFFSET = N
            DO NOM=1,NMESHES
                N = P%RECV_COUNT(NOM)
                IF (N==0) CYCLE
                IF (PROCESS(NOM)==MY_RANK) THEN
                    S => GPU_PARTICLES(NOM)
                    CALL UNPACK_GPU_PARTICLES(NM,N,OFFSET,S%SEND_OFFSET(NM),S%SEND_INT,S%SEND_REAL)
                ELSE
                    CALL UNPACK_GPU_PARTICLES(NM,N,OFFSET,P%RECV_OFFSET(NOM),P%RECV_INT,P%RECV_REAL)
                ENDIF
                OFFSET = OFFSET+N
            ENDDO
            P%COUNT = NEEDED
            IF (NEEDED>0) MESHES(NM)%PARTICLES_EXISTED = .TRUE.
        ENDDO
        ! Same-rank kernels may still read another mesh's send buffer.
        DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
            CALL GPU_WAIT(GPU_MESHES(NM)%STRM)
        ENDDO
    END SUBROUTINE GPU_PARTICLE_MESH_EXCHANGE


    SUBROUTINE RESERVE_PARTICLE_BUFFER(NM,NEEDED,SENDING)
        INTEGER, INTENT(IN) :: NM,NEEDED
        LOGICAL, INTENT(IN) :: SENDING
        INTEGER :: CAP
        TYPE(GPU_PARTICLE_MESH_TYPE), POINTER :: P

        P => GPU_PARTICLES(NM)
        IF (SENDING) THEN
            IF (NEEDED<=P%SEND_CAPACITY) RETURN
            CAP = MAX(NEEDED,MAX(16,2*P%SEND_CAPACITY))
            IF (ALLOCATED(P%SEND_INT)) DEALLOCATE(P%SEND_INT,P%SEND_REAL)
            ALLOCATE(P%SEND_INT(PARTICLE_INTS*CAP),P%SEND_REAL(PARTICLE_REALS*CAP))
            P%SEND_CAPACITY = CAP
        ELSE
            IF (NEEDED<=P%RECV_CAPACITY) RETURN
            CAP = MAX(NEEDED,MAX(16,2*P%RECV_CAPACITY))
            IF (ALLOCATED(P%RECV_INT)) DEALLOCATE(P%RECV_INT,P%RECV_REAL)
            ALLOCATE(P%RECV_INT(PARTICLE_INTS*CAP),P%RECV_REAL(PARTICLE_REALS*CAP))
            P%RECV_CAPACITY = CAP
        ENDIF
    END SUBROUTINE RESERVE_PARTICLE_BUFFER


    ATTRIBUTES(GLOBAL) SUBROUTINE CLASSIFY_PARTICLES_KERNEL(NP,NM,NMESH,NNEIGHBORS,T,X,Y,Z,RADIUS,INSERT_TIME,CLASS_INDEX, &
        KILL_RADIUS,LIFETIME,BOUNDS,NEIGHBORS,DESTINATION,SLOT,COUNTS,PERIODIC_X,PERIODIC_Y,PERIODIC_Z, &
        XMIN,XMAX,YMIN,YMAX,ZMIN,ZMAX)
        INTEGER, VALUE :: NP,NM,NMESH,NNEIGHBORS
        REAL(EB), VALUE :: T,XMIN,XMAX,YMIN,YMAX,ZMIN,ZMAX
        LOGICAL, VALUE :: PERIODIC_X,PERIODIC_Y,PERIODIC_Z
        INTEGER, DEVICE :: CLASS_INDEX(*),NEIGHBORS(*),DESTINATION(*),SLOT(*),COUNTS(0:*)
        REAL(EB), DEVICE :: X(*),Y(*),Z(*),RADIUS(*),INSERT_TIME(*),KILL_RADIUS(*),LIFETIME(*),BOUNDS(6,*)
        INTEGER :: IP,C,DEST,NN,MM,OLD
        LOGICAL :: WRAPPED

        IP = (BLOCKIDX%X-1)*BLOCKDIM%X+THREADIDX%X
        IF (IP>NP) RETURN
        C = CLASS_INDEX(IP)
        DEST = 0
        WRAPPED = .FALSE.
        IF (RADIUS(IP)>KILL_RADIUS(C) .AND. T-INSERT_TIME(IP)<=LIFETIME(C)) THEN
            IF (PERIODIC_X .AND. (X(IP)<=XMIN .OR. X(IP)>=XMAX)) THEN
                X(IP) = XMIN+MODULO(X(IP)-XMIN,XMAX-XMIN)
                WRAPPED = .TRUE.
            ENDIF
            IF (PERIODIC_Y .AND. (Y(IP)<=YMIN .OR. Y(IP)>=YMAX)) THEN
                Y(IP) = YMIN+MODULO(Y(IP)-YMIN,YMAX-YMIN)
                WRAPPED = .TRUE.
            ENDIF
            IF (PERIODIC_Z .AND. (Z(IP)<=ZMIN .OR. Z(IP)>=ZMAX)) THEN
                Z(IP) = ZMIN+MODULO(Z(IP)-ZMIN,ZMAX-ZMIN)
                WRAPPED = .TRUE.
            ENDIF
            IF (X(IP)>BOUNDS(1,NM) .AND. X(IP)<BOUNDS(2,NM) .AND. &
                Y(IP)>BOUNDS(3,NM) .AND. Y(IP)<BOUNDS(4,NM) .AND. &
                Z(IP)>BOUNDS(5,NM) .AND. Z(IP)<BOUNDS(6,NM)) THEN
                DEST = NM
            ELSE
                DO NN=1,NNEIGHBORS
                    MM = NEIGHBORS(NN)
                    IF (MM==0) CYCLE
                    IF (X(IP)<BOUNDS(1,MM) .OR. X(IP)>BOUNDS(2,MM) .OR. &
                        Y(IP)<BOUNDS(3,MM) .OR. Y(IP)>BOUNDS(4,MM) .OR. &
                        Z(IP)<BOUNDS(5,MM) .OR. Z(IP)>BOUNDS(6,MM)) CYCLE
                    DEST = MM
                    EXIT
                ENDDO
                IF (WRAPPED .AND. DEST==0) THEN
                    IF (X(IP)>=BOUNDS(1,NM) .AND. X(IP)<=BOUNDS(2,NM) .AND. &
                        Y(IP)>=BOUNDS(3,NM) .AND. Y(IP)<=BOUNDS(4,NM) .AND. &
                        Z(IP)>=BOUNDS(5,NM) .AND. Z(IP)<=BOUNDS(6,NM)) DEST = NM
                ENDIF
            ENDIF
        ENDIF
        DESTINATION(IP) = DEST
        SLOT(IP) = atomicAdd(COUNTS(DEST),1)+1
        IF (DEST/=NM .OR. WRAPPED) OLD = atomicAdd(COUNTS(NMESH+1),1)
    END SUBROUTINE CLASSIFY_PARTICLES_KERNEL


    SUBROUTINE PACK_GPU_PARTICLES(NM)
        INTEGER, INTENT(IN) :: NM
        TYPE(GPU_PARTICLE_MESH_TYPE), POINTER :: P

        P => GPU_PARTICLES(NM)
        IF (SUM(P%SEND_COUNT(1:NMESHES))==0) RETURN
        CALL PACK_PARTICLES_KERNEL<<<(P%COUNT+PARTICLE_THREADS-1)/PARTICLE_THREADS, &
            PARTICLE_THREADS,0,GPU_MESHES(NM)%STRM>>>(P%COUNT,P%DESTINATION,P%SLOT,P%OFFSETS, &
            P%TAG,P%CLASS_INDEX,P%META,P%X,P%Y,P%Z,P%U,P%V,P%W,P%MASS,P%RADIUS,P%TEMPERATURE, &
            P%WEIGHT,P%RVC,P%INSERT_TIME,P%MASS_RATE,P%SEND_INT,P%SEND_REAL)
    END SUBROUTINE PACK_GPU_PARTICLES


    ATTRIBUTES(GLOBAL) SUBROUTINE PACK_PARTICLES_KERNEL(NP,DESTINATION,SLOT,OFFSETS,TAG,CLASS_INDEX,META, &
        X,Y,Z,U,V,W,MASS,RADIUS,TEMPERATURE,WEIGHT,RVC,INSERT_TIME,MASS_RATE,INTS,REALS)
        INTEGER, VALUE :: NP
        INTEGER, DEVICE :: DESTINATION(*),SLOT(*),OFFSETS(*),TAG(*),CLASS_INDEX(*),META(4,*),INTS(*)
        REAL(EB), DEVICE :: X(*),Y(*),Z(*),U(*),V(*),W(*),MASS(*),RADIUS(*),TEMPERATURE(*),WEIGHT(*), &
                            RVC(*),INSERT_TIME(*),MASS_RATE(*),REALS(*)
        INTEGER :: IP,DEST,P,IB,RB

        IP = (BLOCKIDX%X-1)*BLOCKDIM%X+THREADIDX%X
        IF (IP>NP) RETURN
        DEST = DESTINATION(IP)
        IF (DEST==0) RETURN
        P = OFFSETS(DEST)+SLOT(IP)-1
        IB = PARTICLE_INTS*P
        RB = PARTICLE_REALS*P
        INTS(IB+1) = TAG(IP)
        INTS(IB+2) = CLASS_INDEX(IP)
        INTS(IB+3:IB+6) = META(:,IP)
        REALS(RB+1) = X(IP)
        REALS(RB+2) = Y(IP)
        REALS(RB+3) = Z(IP)
        REALS(RB+4) = U(IP)
        REALS(RB+5) = V(IP)
        REALS(RB+6) = W(IP)
        REALS(RB+7) = MASS(IP)
        REALS(RB+8) = RADIUS(IP)
        REALS(RB+9) = TEMPERATURE(IP)
        REALS(RB+10) = WEIGHT(IP)
        REALS(RB+11) = RVC(IP)
        REALS(RB+12) = INSERT_TIME(IP)
        REALS(RB+13) = MASS_RATE(IP)
    END SUBROUTINE PACK_PARTICLES_KERNEL


    SUBROUTINE UNPACK_GPU_PARTICLES(NM,NP,DEST_OFFSET,SOURCE_OFFSET,INTS,REALS)
        INTEGER, INTENT(IN) :: NM,NP,DEST_OFFSET,SOURCE_OFFSET
        INTEGER, DEVICE :: INTS(:)
        REAL(EB), DEVICE :: REALS(:)
        TYPE(GPU_PARTICLE_MESH_TYPE), POINTER :: P

        P => GPU_PARTICLES(NM)
        GM => GPU_MESHES(NM)
        CALL UNPACK_PARTICLES_KERNEL<<<(NP+PARTICLE_THREADS-1)/PARTICLE_THREADS,PARTICLE_THREADS,0,GM%STRM>>>( &
            NP,DEST_OFFSET,SOURCE_OFFSET,INTS,REALS,P%TAG,P%CLASS_INDEX,P%META,P%X,P%Y,P%Z,P%U,P%V,P%W, &
            P%MASS,P%RADIUS,P%TEMPERATURE,P%WEIGHT,P%RVC,P%INSERT_TIME,P%MASS_RATE,P%CELL_I,P%CELL_J,P%CELL_K, &
            MESHES(NM)%IBAR,MESHES(NM)%JBAR,MESHES(NM)%KBAR,GM%XCD,GM%YCD,GM%ZCD,GM%DXD,GM%DYD,GM%DZD)
    END SUBROUTINE UNPACK_GPU_PARTICLES


    ATTRIBUTES(GLOBAL) SUBROUTINE UNPACK_PARTICLES_KERNEL(NP,DEST_OFFSET,SOURCE_OFFSET,INTS,REALS, &
        TAG,CLASS_INDEX,META,X,Y,Z,U,V,W,MASS,RADIUS,TEMPERATURE,WEIGHT,RVC,INSERT_TIME,MASS_RATE, &
        CELL_I,CELL_J,CELL_K,IBAR,JBAR,KBAR,XC,YC,ZC,DX,DY,DZ)
        INTEGER, VALUE :: NP,DEST_OFFSET,SOURCE_OFFSET,IBAR,JBAR,KBAR
        INTEGER, DEVICE :: INTS(*),TAG(*),CLASS_INDEX(*),META(4,*),CELL_I(*),CELL_J(*),CELL_K(*)
        REAL(EB), DEVICE :: REALS(*),X(*),Y(*),Z(*),U(*),V(*),W(*),MASS(*),RADIUS(*),TEMPERATURE(*), &
                            WEIGHT(*),RVC(*),INSERT_TIME(*),MASS_RATE(*)
        REAL(EB), DEVICE :: XC(0:*),YC(0:*),ZC(0:*),DX(0:*),DY(0:*),DZ(0:*)
        INTEGER :: N,IP,IB,RB,I,J,K

        N = (BLOCKIDX%X-1)*BLOCKDIM%X+THREADIDX%X
        IF (N>NP) RETURN
        IP = DEST_OFFSET+N
        IB = PARTICLE_INTS*(SOURCE_OFFSET+N-1)
        RB = PARTICLE_REALS*(SOURCE_OFFSET+N-1)
        TAG(IP) = INTS(IB+1)
        CLASS_INDEX(IP) = INTS(IB+2)
        META(:,IP) = INTS(IB+3:IB+6)
        X(IP) = REALS(RB+1)
        Y(IP) = REALS(RB+2)
        Z(IP) = REALS(RB+3)
        U(IP) = REALS(RB+4)
        V(IP) = REALS(RB+5)
        W(IP) = REALS(RB+6)
        MASS(IP) = REALS(RB+7)
        RADIUS(IP) = REALS(RB+8)
        TEMPERATURE(IP) = REALS(RB+9)
        WEIGHT(IP) = REALS(RB+10)
        INSERT_TIME(IP) = REALS(RB+12)
        MASS_RATE(IP) = REALS(RB+13)
        I = PARTICLE_CELL(X(IP),IBAR,XC,DX)
        J = PARTICLE_CELL(Y(IP),JBAR,YC,DY)
        K = PARTICLE_CELL(Z(IP),KBAR,ZC,DZ)
        CELL_I(IP) = I
        CELL_J(IP) = J
        CELL_K(IP) = K
        RVC(IP) = 1._EB/(DX(I)*DY(J)*DZ(K))
    END SUBROUTINE UNPACK_PARTICLES_KERNEL


    ATTRIBUTES(DEVICE) INTEGER FUNCTION PARTICLE_CELL(X,N,XC,DX) RESULT(I)
        REAL(EB), VALUE :: X
        INTEGER, VALUE :: N
        REAL(EB), DEVICE :: XC(0:*),DX(0:*)
        INTEGER :: LO,HI,MID

        LO = 1
        HI = N
        DO WHILE (LO<HI)
            MID = (LO+HI)/2
            IF (X<XC(MID)+0.5_EB*DX(MID)) THEN
                HI = MID
            ELSE
                LO = MID+1
            ENDIF
        ENDDO
        I = LO
    END FUNCTION PARTICLE_CELL


    ATTRIBUTES(GLOBAL) SUBROUTINE MOVE_GPU_PARTICLES_KERNEL(NP,DT,IBAR,JBAR,KBAR,IBP1,JBP1,KBP1, &
        CLASS_INDEX,CELL_I,CELL_J,CELL_K,X,Y,Z,U,V,W,RADIUS,MASS,WEIGHT,RVC,MASS_RATE,CLASS_STATIC,CLASS_KILL_RADIUS, &
        CLASS_LIQUID,CLASS_ARRAY_INDEX,CLASS_DENSITY,CLASS_DENSE_VOLUME_FRACTION,AVG_DROP_DEN, &
        DRAG_X,DRAG_Y,DRAG_Z,UD,VD,WD,RHOD,MUD,PBARD_IN,PRESSURE_ZONED_IN,DXD,DYD,DZD,XCD,YCD,ZCD, &
        RDXND,RDYND,RDZND,CELL_INDEX,CELL_WALL_INDEX,CELL_LB,CELL_UB,GX_GLOBAL,GY_GLOBAL,GZ_GLOBAL)
        INTEGER, VALUE :: NP,IBAR,JBAR,KBAR,IBP1,JBP1,KBP1,CELL_LB,CELL_UB
        REAL(EB), VALUE :: DT
        INTEGER, DEVICE :: CLASS_INDEX(:),CELL_I(:),CELL_J(:),CELL_K(:),CLASS_ARRAY_INDEX(:)
        REAL(EB), DEVICE :: X(:),Y(:),Z(:),U(:),V(:),W(:),RADIUS(:),MASS(:),WEIGHT(:),RVC(:),MASS_RATE(:)
        LOGICAL, DEVICE :: CLASS_STATIC(:),CLASS_LIQUID(:)
        REAL(EB), DEVICE :: CLASS_KILL_RADIUS(:),CLASS_DENSITY(:),CLASS_DENSE_VOLUME_FRACTION(:)
        REAL(EB), DEVICE :: AVG_DROP_DEN(0:IBP1,0:JBP1,0:KBP1,*)
        REAL(EB), DEVICE :: DRAG_X(0:IBP1,0:JBP1,0:KBP1),DRAG_Y(0:IBP1,0:JBP1,0:KBP1),DRAG_Z(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: UD(0:IBP1,0:JBP1,0:KBP1),VD(0:IBP1,0:JBP1,0:KBP1),WD(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: RHOD(0:IBP1,0:JBP1,0:KBP1),MUD(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE, DIMENSION(0:KBP1,0:*) :: PBARD_IN
        INTEGER, DEVICE :: PRESSURE_ZONED_IN(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: DXD(0:IBP1),DYD(0:JBP1),DZD(0:KBP1)
        REAL(EB), DEVICE :: XCD(0:IBP1),YCD(0:JBP1),ZCD(0:KBP1)
        REAL(EB), DEVICE :: RDXND(0:IBP1),RDYND(0:JBP1),RDZND(0:KBP1)
        INTEGER, DEVICE :: CELL_INDEX(0:IBP1,0:JBP1,0:KBP1),CELL_WALL_INDEX(CELL_LB:CELL_UB,-3:3)
        REAL(EB), VALUE :: GX_GLOBAL,GY_GLOBAL,GZ_GLOBAL

        INTEGER :: IP,C,I,J,K,NSTEP,IT,IC,AXIS,IL,JL,KL,II,JJ,KK,A,B,D
        REAL(EB) :: DT_P,DX_LOC,DY_LOC,DZ_LOC,DT_CFL
        REAL(EB) :: R,M,RHO,MU,UBAR,VBAR,WBAR,UREL,VREL,WREL,QREL,RE,CD,A_DRAG,BETA,KN,SLIP_CORRECTION
        REAL(EB) :: DROP_VOL_FRAC,LODM,RELOD,WAKE_VEL
        REAL(EB) :: U_OLD,V_OLD,W_OLD,GX,GY,GZ,X_NEW,Y_NEW,Z_NEW
        REAL(EB) :: MPOM,M_DOT,ACCEL_X,ACCEL_Y,ACCEL_Z,RVC_LOC,WGT
        REAL(EB) :: POS(3),CENTER(3),LOWER(3),UPPER(3),FRAC(3),WT(0:1,0:1,0:1,3),VOL(0:1,0:1,0:1,3)
        REAL(EB) :: GAS(3),VOLSUM,FORCE(3)
        INTEGER :: CELL(3),BASE(3,3),LIMITS(3)
        INTEGER :: IERR

        IP = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
        IF (IP<1 .OR. IP>NP) RETURN
        C = CLASS_INDEX(IP)
        IF (C<1 .OR. CLASS_STATIC(C)) RETURN
        R = RADIUS(IP)
        IF (R<=CLASS_KILL_RADIUS(C)) RETURN
        M = MAX(TWO_EPSILON_EB, MASS(IP))
        I = MAX(1,MIN(IBAR,CELL_I(IP)))
        J = MAX(1,MIN(JBAR,CELL_J(IP)))
        K = MAX(1,MIN(KBAR,CELL_K(IP)))
        CELL_I(IP) = I
        CELL_J(IP) = J
        CELL_K(IP) = K

        DX_LOC = MAX(TWO_EPSILON_EB,DXD(I))
        DY_LOC = MAX(TWO_EPSILON_EB,DYD(J))
        DZ_LOC = MAX(TWO_EPSILON_EB,DZD(K))
        DT_CFL = MIN(DX_LOC/(ABS(U(IP))+TWO_EPSILON_EB), &
                     MIN(DY_LOC/(ABS(V(IP))+TWO_EPSILON_EB),DZ_LOC/(ABS(W(IP))+TWO_EPSILON_EB)))
        NSTEP = MAX(1,MIN(64,CEILING(DT/MAX(TWO_EPSILON_EB,0.9_EB*DT_CFL))))
        DT_P = DT/REAL(NSTEP,EB)

        DO IT=1,NSTEP
            POS = (/X(IP),Y(IP),Z(IP)/)
            CELL = (/I,J,K/)
            CENTER = (/XCD(I),YCD(J),ZCD(K)/)
            LIMITS = (/IBAR,JBAR,KBAR/)
            IC = CELL_INDEX(I,J,K)
            GAS = 0._EB
            DO AXIS=1,3
                DO A=1,3
                    IF (A==AXIS) THEN
                        BASE(A,AXIS) = CELL(A)-1
                    ELSE
                        BASE(A,AXIS) = CELL(A)
                        IF (POS(A)<CENTER(A)) BASE(A,AXIS) = CELL(A)-1
                    ENDIF
                    BASE(A,AXIS) = MAX(0,MIN(LIMITS(A),BASE(A,AXIS)))
                ENDDO
                IL=BASE(1,AXIS); JL=BASE(2,AXIS); KL=BASE(3,AXIS)
                LOWER=(/XCD(IL),YCD(JL),ZCD(KL)/)
                UPPER=(/XCD(IL+1),YCD(JL+1),ZCD(KL+1)/)
                SELECT CASE(AXIS)
                CASE(1)
                    LOWER(1)=XCD(IL)+0.5_EB*DXD(IL)
                    UPPER(1)=XCD(IL+1)+0.5_EB*DXD(IL+1)
                CASE(2)
                    LOWER(2)=YCD(JL)+0.5_EB*DYD(JL)
                    UPPER(2)=YCD(JL+1)+0.5_EB*DYD(JL+1)
                CASE(3)
                    LOWER(3)=ZCD(KL)+0.5_EB*DZD(KL)
                    UPPER(3)=ZCD(KL+1)+0.5_EB*DZD(KL+1)
                END SELECT
                DO A=1,3
                    FRAC(A)=(POS(A)-LOWER(A))/MAX(TWO_EPSILON_EB,UPPER(A)-LOWER(A))
                    IF (A/=AXIS) THEN
                        IF (CELL(A)>BASE(A,AXIS) .AND. CELL_WALL_INDEX(IC,-A)>0) FRAC(A)=1._EB
                        IF (CELL(A)==BASE(A,AXIS) .AND. CELL_WALL_INDEX(IC,A)>0) FRAC(A)=0._EB
                    ENDIF
                ENDDO
                VOLSUM=0._EB
                DO D=0,1
                    DO B=0,1
                        DO A=0,1
                            II=IL+A; JJ=JL+B; KK=KL+D
                            WT(A,B,D,AXIS)=MERGE(FRAC(1),1._EB-FRAC(1),A==1)* &
                                              MERGE(FRAC(2),1._EB-FRAC(2),B==1)* &
                                              MERGE(FRAC(3),1._EB-FRAC(3),D==1)
                            SELECT CASE(AXIS)
                            CASE(1)
                                GAS(1)=GAS(1)+WT(A,B,D,1)*UD(II,JJ,KK)
                                VOL(A,B,D,1)=DYD(JJ)*DZD(KK)/RDXND(II)
                            CASE(2)
                                GAS(2)=GAS(2)+WT(A,B,D,2)*VD(II,JJ,KK)
                                VOL(A,B,D,2)=DXD(II)*DZD(KK)/RDYND(JJ)
                            CASE(3)
                                GAS(3)=GAS(3)+WT(A,B,D,3)*WD(II,JJ,KK)
                                VOL(A,B,D,3)=DXD(II)*DYD(JJ)/RDZND(KK)
                            END SELECT
                            VOLSUM=VOLSUM+WT(A,B,D,AXIS)*VOL(A,B,D,AXIS)
                        ENDDO
                    ENDDO
                ENDDO
                IF (VOLSUM>TWO_EPSILON_EB) WT(:,:,:,AXIS)=WT(:,:,:,AXIS)/VOLSUM
            ENDDO
            UBAR=GAS(1); VBAR=GAS(2); WBAR=GAS(3)
            RHO = MAX(TWO_EPSILON_EB,RHOD(I,J,K))
            MU = MAX(TWO_EPSILON_EB,MUD(I,J,K))
            U_OLD = U(IP)
            V_OLD = V(IP)
            W_OLD = W(IP)
            UREL = U_OLD-UBAR
            VREL = V_OLD-VBAR
            WREL = W_OLD-WBAR
            QREL = SQRT(UREL*UREL+VREL*VREL+WREL*WREL)
            RE = RHO*QREL*2._EB*R/MU
            IF (RE<=TWO_EPSILON_EB) THEN
                CD = 0._EB
            ELSEIF (RE<1._EB) THEN
                KN = MU*SQRT(0.5_EB*PI/MAX(TWO_EPSILON_EB, &
                     PBARD_IN(K,PRESSURE_ZONED_IN(I,J,K))*RHO))/(2._EB*R)
                SLIP_CORRECTION = 1._EB + 1.257_EB*KN + 0.4_EB*KN*EXP(-1.1_EB/KN)
                CD = 24._EB/(RE*SLIP_CORRECTION)
            ELSEIF (RE<1000._EB) THEN
                CD = 24._EB*(0.85_EB+0.15_EB*RE**0.687_EB)/RE
            ELSE
                CD = 0.44_EB
            ENDIF
            IF (CLASS_LIQUID(C)) THEN
                A = CLASS_ARRAY_INDEX(C)
                IF (A>0) THEN
                    DROP_VOL_FRAC = MIN(1._EB,AVG_DROP_DEN(I,J,K,A)/MAX(TWO_EPSILON_EB,CLASS_DENSITY(C)))
                    IF (DROP_VOL_FRAC>CLASS_DENSE_VOLUME_FRACTION(C)) THEN
                        LODM = MAX(TWO_EPSILON_EB,(PI/(6._EB*DROP_VOL_FRAC))**ONTH-0.5_EB)
                        RELOD = RE/(16._EB*LODM)
                        WAKE_VEL = 1._EB-0.5_EB*CD*(1._EB-EXP(-RELOD))
                        WAKE_VEL = MAX(WAKE_VEL,0.15_EB)
                        CD = CD*WAKE_VEL*(1._EB+(RELOD/LODM)*EXP(-RELOD))
                    ENDIF
                ENDIF
            ENDIF
            A_DRAG = PI*R*R
            BETA = 0.5_EB*RHO*CD*A_DRAG*QREL/M
            GX = GX_GLOBAL
            GY = GY_GLOBAL
            GZ = GZ_GLOBAL
            IF (BETA>TWO_EPSILON_EB) THEN
                U(IP) = UBAR+(UREL-GX/BETA)*EXP(-BETA*DT_P)+GX/BETA
                V(IP) = VBAR+(VREL-GY/BETA)*EXP(-BETA*DT_P)+GY/BETA
                W(IP) = WBAR+(WREL-GZ/BETA)*EXP(-BETA*DT_P)+GZ/BETA
            ELSE
                U(IP) = U_OLD+DT_P*GX
                V(IP) = V_OLD+DT_P*GY
                W(IP) = W_OLD+DT_P*GZ
            ENDIF

            IF (BETA>TWO_EPSILON_EB) THEN
                WGT = MAX(TWO_EPSILON_EB,WEIGHT(IP))
                RVC_LOC = MAX(TWO_EPSILON_EB,RVC(IP))
                M_DOT = MAX(0._EB,MASS_RATE(IP))
                MPOM = WGT*RVC_LOC/MAX(TWO_EPSILON_EB,RHO)
                ACCEL_X = MPOM*(M*((U_OLD-U(IP))/DT_P+GX)+M_DOT*UREL)
                ACCEL_Y = MPOM*(M*((V_OLD-V(IP))/DT_P+GY)+M_DOT*VREL)
                ACCEL_Z = MPOM*(M*((W_OLD-W(IP))/DT_P+GZ)+M_DOT*WREL)
                FORCE=(/ACCEL_X,ACCEL_Y,ACCEL_Z/)/RVC_LOC
                DO AXIS=1,3
                    DO D=0,1
                        DO B=0,1
                            DO A=0,1
                                II=BASE(1,AXIS)+A; JJ=BASE(2,AXIS)+B; KK=BASE(3,AXIS)+D
                                SELECT CASE(AXIS)
                                CASE(1)
                                    IERR=atomicAdd(DRAG_X(II,JJ,KK),-FORCE(1)*WT(A,B,D,1))
                                CASE(2)
                                    IERR=atomicAdd(DRAG_Y(II,JJ,KK),-FORCE(2)*WT(A,B,D,2))
                                CASE(3)
                                    IERR=atomicAdd(DRAG_Z(II,JJ,KK),-FORCE(3)*WT(A,B,D,3))
                                END SELECT
                            ENDDO
                        ENDDO
                    ENDDO
                ENDDO
            ENDIF
            X_NEW = X(IP)+0.5_EB*DT_P*(U_OLD+U(IP))
            Y_NEW = Y(IP)+0.5_EB*DT_P*(V_OLD+V(IP))
            Z_NEW = Z(IP)+0.5_EB*DT_P*(W_OLD+W(IP))
            X(IP) = X_NEW
            Y(IP) = Y_NEW
            Z(IP) = Z_NEW

            DO WHILE (I>1 .AND. X_NEW<(XCD(I-1)+0.5_EB*DXD(I-1)))
                I = I-1
            ENDDO
            DO WHILE (I<IBAR .AND. X_NEW>=(XCD(I)+0.5_EB*DXD(I)))
                I = I+1
            ENDDO
            DO WHILE (J>1 .AND. Y_NEW<(YCD(J-1)+0.5_EB*DYD(J-1)))
                J = J-1
            ENDDO
            DO WHILE (J<JBAR .AND. Y_NEW>=(YCD(J)+0.5_EB*DYD(J)))
                J = J+1
            ENDDO
            DO WHILE (K>1 .AND. Z_NEW<(ZCD(K-1)+0.5_EB*DZD(K-1)))
                K = K-1
            ENDDO
            DO WHILE (K<KBAR .AND. Z_NEW>=(ZCD(K)+0.5_EB*DZD(K)))
                K = K+1
            ENDDO
            IF (X_NEW<(XCD(0)+0.5_EB*DXD(0)) .OR. X_NEW>=(XCD(IBAR)+0.5_EB*DXD(IBAR)) .OR. &
                Y_NEW<(YCD(0)+0.5_EB*DYD(0)) .OR. Y_NEW>=(YCD(JBAR)+0.5_EB*DYD(JBAR)) .OR. &
                Z_NEW<(ZCD(0)+0.5_EB*DZD(0)) .OR. Z_NEW>=(ZCD(KBAR)+0.5_EB*DZD(KBAR))) THEN
                EXIT
            ENDIF
            RVC(IP) = 1._EB/(DXD(I)*DYD(J)*DZD(K))
        ENDDO
        CELL_I(IP) = I
        CELL_J(IP) = J
        CELL_K(IP) = K
    END SUBROUTINE MOVE_GPU_PARTICLES_KERNEL


    SUBROUTINE APPLY_GPU_PARTICLE_DRAG(NM,DT,IS_PREDICTOR)
        INTEGER, INTENT(IN) :: NM
        REAL(EB), INTENT(IN) :: DT
        LOGICAL, INTENT(IN) :: IS_PREDICTOR
        INTEGER :: NTHREADS,NBLOCKS,NPOINTS,IBP1,JBP1,KBP1

        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        IF (.NOT.ALLOCATED(GPU_PARTICLES(NM)%DRAG_X)) RETURN

        IBP1 = MESHES(NM)%IBP1
        JBP1 = MESHES(NM)%JBP1
        KBP1 = MESHES(NM)%KBP1
        NPOINTS = (IBP1+1)*(JBP1+1)*(KBP1+1)
        NTHREADS = 128
        NBLOCKS = (NPOINTS+NTHREADS-1)/NTHREADS
        GM => GPU_MESHES(NM)
        IF (IS_PREDICTOR) THEN
            CALL APPLY_GPU_PARTICLE_DRAG_KERNEL<<<NBLOCKS,NTHREADS,0,GM%STRM>>>( &
                NPOINTS,IBP1,JBP1,KBP1,DT,GM%UD,GM%VD,GM%WD,GM%FVXD,GM%FVYD,GM%FVZD, &
                GPU_PARTICLES(NM)%DRAG_X,GPU_PARTICLES(NM)%DRAG_Y,GPU_PARTICLES(NM)%DRAG_Z)
        ELSE
            CALL APPLY_GPU_PARTICLE_DRAG_KERNEL<<<NBLOCKS,NTHREADS,0,GM%STRM>>>( &
                NPOINTS,IBP1,JBP1,KBP1,DT,GM%USD,GM%VSD,GM%WSD,GM%FVXD,GM%FVYD,GM%FVZD, &
                GPU_PARTICLES(NM)%DRAG_X,GPU_PARTICLES(NM)%DRAG_Y,GPU_PARTICLES(NM)%DRAG_Z)
        ENDIF
    END SUBROUTINE APPLY_GPU_PARTICLE_DRAG


    ATTRIBUTES(GLOBAL) SUBROUTINE APPLY_GPU_PARTICLE_DRAG_KERNEL(NPOINTS,IBP1,JBP1,KBP1,DT,UD,VD,WD,FVX,FVY,FVZ,DRAG_X,DRAG_Y,DRAG_Z)
        INTEGER, VALUE :: NPOINTS,IBP1,JBP1,KBP1
        REAL(EB), VALUE :: DT
        REAL(EB), DEVICE :: UD(0:IBP1,0:JBP1,0:KBP1),VD(0:IBP1,0:JBP1,0:KBP1),WD(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: FVX(0:IBP1,0:JBP1,0:KBP1),FVY(0:IBP1,0:JBP1,0:KBP1),FVZ(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: DRAG_X(0:IBP1,0:JBP1,0:KBP1),DRAG_Y(0:IBP1,0:JBP1,0:KBP1),DRAG_Z(0:IBP1,0:JBP1,0:KBP1)
        INTEGER :: N,I,J,K
        REAL(EB) :: UODT,VODT,WODT

        N = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X - 1
        IF (N<0 .OR. N>=NPOINTS) RETURN
        I = MOD(N,IBP1+1)
        J = MOD(N/(IBP1+1),JBP1+1)
        K = N/((IBP1+1)*(JBP1+1))

        UODT = ABS(UD(I,J,K)/MAX(TWO_EPSILON_EB,DT))
        VODT = ABS(VD(I,J,K)/MAX(TWO_EPSILON_EB,DT))
        WODT = ABS(WD(I,J,K)/MAX(TWO_EPSILON_EB,DT))
        FVX(I,J,K) = FVX(I,J,K) + MIN(UODT,MAX(-UODT,DRAG_X(I,J,K)))
        FVY(I,J,K) = FVY(I,J,K) + MIN(VODT,MAX(-VODT,DRAG_Y(I,J,K)))
        FVZ(I,J,K) = FVZ(I,J,K) + MIN(WODT,MAX(-WODT,DRAG_Z(I,J,K)))
    END SUBROUTINE APPLY_GPU_PARTICLE_DRAG_KERNEL


    SUBROUTINE SYNC_GPU_PARTICLES_TO_CPU(NM)
        INTEGER, INTENT(IN) :: NM
        INTEGER :: IP,NP,BC_INDEX,B1_INDEX,C,ND,INIT_INDEX
        INTEGER, ALLOCATABLE :: I_H(:),J_H(:),K_H(:),TAG_H(:),CLASS_H(:),META_H(:,:)
        REAL(EB), ALLOCATABLE :: X_H(:),Y_H(:),Z_H(:),U_H(:),V_H(:),W_H(:),MASS_H(:),RADIUS_H(:),TEMP_H(:),RVC_H(:)
        REAL(EB), ALLOCATABLE :: WEIGHT_H(:),INSERT_H(:)

        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        IF (.NOT.ASSOCIATED(GPU_PARTICLES(NM)%CLASS_INDEX)) RETURN
        NP = GPU_PARTICLES(NM)%COUNT

        GM => GPU_MESHES(NM)
        CALL GPU_WAIT(GM%STRM)
        IF (ALLOCATED(GPU_PARTICLES(NM)%AVG_DROP_DEN)) THEN
            MESHES(NM)%AVG_DROP_DEN = GPU_PARTICLES(NM)%AVG_DROP_DEN
            MESHES(NM)%AVG_DROP_TMP = GPU_PARTICLES(NM)%AVG_DROP_TMP
            MESHES(NM)%AVG_DROP_RAD = GPU_PARTICLES(NM)%AVG_DROP_RAD
            MESHES(NM)%AVG_DROP_AREA = GPU_PARTICLES(NM)%AVG_DROP_AREA
        ENDIF
        ! This is an output mirror, not the owner of the simulated particles.
        DO IP=NP+1,GPU_PARTICLES(NM)%HOST_COUNT
            CALL NULLIFY_PARTICLE(NM,IP)
        ENDDO
        MESHES(NM)%NLP = NP
        IF (NP==0) THEN
            GPU_PARTICLES(NM)%HOST_COUNT = 0
            RETURN
        ENDIF
        ALLOCATE(I_H(NP),J_H(NP),K_H(NP),X_H(NP),Y_H(NP),Z_H(NP),U_H(NP),V_H(NP),W_H(NP), &
                 MASS_H(NP),RADIUS_H(NP),TEMP_H(NP),RVC_H(NP),TAG_H(NP),CLASS_H(NP),META_H(4,NP), &
                 WEIGHT_H(NP),INSERT_H(NP))
        TAG_H = GPU_PARTICLES(NM)%TAG(1:NP)
        CLASS_H = GPU_PARTICLES(NM)%CLASS_INDEX(1:NP)
        META_H = GPU_PARTICLES(NM)%META(:,1:NP)
        WEIGHT_H = GPU_PARTICLES(NM)%WEIGHT(1:NP)
        INSERT_H = GPU_PARTICLES(NM)%INSERT_TIME(1:NP)
        I_H = GPU_PARTICLES(NM)%CELL_I(1:NP)
        J_H = GPU_PARTICLES(NM)%CELL_J(1:NP)
        K_H = GPU_PARTICLES(NM)%CELL_K(1:NP)
        X_H = GPU_PARTICLES(NM)%X(1:NP)
        Y_H = GPU_PARTICLES(NM)%Y(1:NP)
        Z_H = GPU_PARTICLES(NM)%Z(1:NP)
        U_H = GPU_PARTICLES(NM)%U(1:NP)
        V_H = GPU_PARTICLES(NM)%V(1:NP)
        W_H = GPU_PARTICLES(NM)%W(1:NP)
        MASS_H = GPU_PARTICLES(NM)%MASS(1:NP)
        RADIUS_H = GPU_PARTICLES(NM)%RADIUS(1:NP)
        TEMP_H = GPU_PARTICLES(NM)%TEMPERATURE(1:NP)
        RVC_H = GPU_PARTICLES(NM)%RVC(1:NP)

        DO IP=1,NP
            C = CLASS_H(IP)
            IF (IP<=GPU_PARTICLES(NM)%HOST_COUNT) THEN
                IF (MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%CLASS_INDEX/=C) CALL NULLIFY_PARTICLE(NM,IP)
            ENDIF
            IF (IP>GPU_PARTICLES(NM)%HOST_COUNT) THEN
                CALL ALLOCATE_STORAGE(NM,LP_INDEX=IP,LPC_INDEX=C,SURF_INDEX=LAGRANGIAN_PARTICLE_CLASS(C)%SURF_INDEX)
            ELSEIF (MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%BC_INDEX==0) THEN
                CALL ALLOCATE_STORAGE(NM,LP_INDEX=IP,LPC_INDEX=C,SURF_INDEX=LAGRANGIAN_PARTICLE_CLASS(C)%SURF_INDEX)
            ENDIF
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%TAG = TAG_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%CLASS_INDEX = C
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%INIT_INDEX = META_H(1,IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%PROP_INDEX = META_H(2,IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%SHOW = META_H(3,IP)/=0
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%PWT = WEIGHT_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%T_INSERT = INSERT_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%U = U_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%V = V_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%W = W_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%MASS = MASS_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%RADIUS = RADIUS_H(IP)
            MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%RVC = RVC_H(IP)
            BC_INDEX = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%BC_INDEX
            B1_INDEX = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%B1_INDEX
            IF (BC_INDEX>0) THEN
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%X = X_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%Y = Y_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%Z = Z_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%IIG = I_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%JJG = J_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%KKG = K_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%II = I_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%JJ = J_H(IP)
                MESHES(NM)%BOUNDARY_COORD(BC_INDEX)%KK = K_H(IP)
            ENDIF
            IF (B1_INDEX>0) MESHES(NM)%BOUNDARY_PROP1(B1_INDEX)%TMP_F = TEMP_H(IP)
        ENDDO
        GPU_PARTICLES(NM)%HOST_COUNT = NP

        ! Restore INIT-linked device identity on a receiving rank, as in the CPU exchange.
        DO ND=1,N_DEVC
            IF (DEVICE(ND)%INIT_ID=='null' .OR. DEVICE(ND)%LP_TAG>0) CYCLE
            DO IP=1,NP
                INIT_INDEX = META_H(1,IP)
                IF (INIT_INDEX<=0) CYCLE
                IF (META_H(4,IP)/=DEVICE(ND)%POINT) CYCLE
                IF (INITIALIZATION(INIT_INDEX)%ID/=DEVICE(ND)%INIT_ID) CYCLE
                DEVICE(ND)%LP_TAG = TAG_H(IP)
                DEVICE(ND)%PART_CLASS_INDEX = CLASS_H(IP)
            ENDDO
        ENDDO

        DEALLOCATE(I_H,J_H,K_H,X_H,Y_H,Z_H,U_H,V_H,W_H,MASS_H,RADIUS_H,TEMP_H,RVC_H)
    END SUBROUTINE SYNC_GPU_PARTICLES_TO_CPU


    ATTRIBUTES(GLOBAL) SUBROUTINE GPU_PARTICLE_STEP_KERNEL(NP,DT,IBP1,JBP1,KBP1,NTRACKED,NSPECIES,ITMAX, &
        CLASS_INDEX,CELL_I,CELL_J,CELL_K,U,V,W,MASS,RADIUS,TEMPERATURE,WEIGHT,RVC,MASS_RATE,QR_WD,MVAP_TOT_D,RADIATION_IN, &
        NARRAY,AVG_DROP_AREA, &
        UD,VD,WD,RHOD,TMPD,RSUMD,ZZD,PBARD_IN,PRESSURE_ZONED_IN,D_SOURCED,M_DOT_PPPD, &
        CP_ZD_IN,H_SENS_ZD_IN,SPECIES_Z2YD_IN, &
        CLASS_Y_INDEX,CLASS_Z_INDEX,CLASS_ARRAY_INDEX,CLASS_LIQUID,CLASS_STATIC,CLASS_DENSITY,CLASS_CP_L,CLASS_MW,CLASS_T_BOIL, &
        CLASS_T_MELT,CLASS_ADJUST,CLASS_KILL_RADIUS,CLASS_H_HEAT,CLASS_H_MASS,CLASS_H_V, &
        SPECIES_MW, &
        MU_RSQMW_ZD_IN,K_RSQMW_ZD_IN,RSQ_MW_ZD_IN,MWR_ZD_IN,D_Z_TABLED_IN,P_STP_IN,DY_MIN_BLOWING_IN,R0_IN, &
        DROP_DEN,DROP_TMP,DROP_RAD,DROP_AREA)
        INTEGER, VALUE :: NP,IBP1,JBP1,KBP1,NTRACKED,NSPECIES,ITMAX
        REAL(EB), VALUE :: DT,P_STP_IN,DY_MIN_BLOWING_IN,R0_IN
        LOGICAL, VALUE :: RADIATION_IN
        INTEGER, VALUE :: NARRAY
        INTEGER, DEVICE :: CLASS_INDEX(:),CELL_I(:),CELL_J(:),CELL_K(:)
        REAL(EB), DEVICE :: U(:),V(:),W(:),MASS(:),RADIUS(:),TEMPERATURE(:),WEIGHT(:),RVC(:),MASS_RATE(:)
        REAL(EB), DEVICE :: QR_WD(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: MVAP_TOT_D(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: AVG_DROP_AREA(0:IBP1,0:JBP1,0:KBP1,*)
        REAL(EB), DEVICE :: UD(0:IBP1,0:JBP1,0:KBP1),VD(0:IBP1,0:JBP1,0:KBP1),WD(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: RHOD(0:IBP1,0:JBP1,0:KBP1),TMPD(0:IBP1,0:JBP1,0:KBP1)
        REAL(EB), DEVICE :: RSUMD(0:IBP1,0:JBP1,0:KBP1),ZZD(0:IBP1,0:JBP1,0:KBP1,1:NTRACKED)
        REAL(EB), DEVICE, DIMENSION(0:KBP1,0:*) :: PBARD_IN
        REAL(EB), DEVICE, DIMENSION(0:IBP1,0:JBP1,0:KBP1) :: D_SOURCED
        INTEGER, DEVICE, DIMENSION(0:IBP1,0:JBP1,0:KBP1) :: PRESSURE_ZONED_IN
        REAL(EB), DEVICE, DIMENSION(0:IBP1,0:JBP1,0:KBP1,1:NTRACKED) :: M_DOT_PPPD
        REAL(EB), DEVICE, DIMENSION(0:ITMAX,1:NTRACKED) :: CP_ZD_IN,H_SENS_ZD_IN
        REAL(EB), DEVICE, DIMENSION(1:NSPECIES,1:NTRACKED) :: SPECIES_Z2YD_IN
        INTEGER, DEVICE, DIMENSION(*) :: CLASS_Y_INDEX,CLASS_Z_INDEX,CLASS_ARRAY_INDEX
        LOGICAL, DEVICE, DIMENSION(*) :: CLASS_LIQUID,CLASS_STATIC
        REAL(EB), DEVICE, DIMENSION(*) :: CLASS_DENSITY,CLASS_MW,CLASS_T_BOIL,CLASS_T_MELT,CLASS_ADJUST,CLASS_KILL_RADIUS
        REAL(EB), DEVICE, DIMENSION(0:ITMAX,1:*) :: CLASS_CP_L
        REAL(EB), DEVICE, DIMENSION(*) :: CLASS_H_HEAT,CLASS_H_MASS
        REAL(EB), DEVICE, DIMENSION(0:ITMAX,1:*) :: CLASS_H_V
        REAL(EB), DEVICE, DIMENSION(*) :: SPECIES_MW
        REAL(EB), DEVICE, DIMENSION(0:ITMAX,1:*) :: MU_RSQMW_ZD_IN,K_RSQMW_ZD_IN,D_Z_TABLED_IN
        REAL(EB), DEVICE, DIMENSION(*) :: RSQ_MW_ZD_IN,MWR_ZD_IN
        REAL(EB), DEVICE :: DROP_DEN(0:IBP1,0:JBP1,0:KBP1,*),DROP_TMP(0:IBP1,0:JBP1,0:KBP1,*)
        REAL(EB), DEVICE :: DROP_RAD(0:IBP1,0:JBP1,0:KBP1,*),DROP_AREA(0:IBP1,0:JBP1,0:KBP1,*)

        INTEGER :: IP,C,YI,ZI,I,J,K,N,NS,ITP,ITG,ITF,ITB,ITMP,ITMP2,IZONE,IERR
        REAL(EB) :: R,RNEW,M,MNEW,WGT,RVC_LOC,T_DROP,T_GAS,T_DROP_NEW,T_GAS_NEW
        REAL(EB) :: RHO_G,MU_G,VEL,RE_L,PR,SC,K_GAS,D_G,NU,SH,H_HEAT,H_MASS
        REAL(EB) :: M_GAS,MW_GAS,MW_RATIO,Y_GAS,Y_DROP,H_V,CP_L,CP_G,H1,H2
        REAL(EB) :: AREA,AGHRHO,DTOG,DTGOG,DTOP,DTGOP,DAHVHLDY,DADYHV,DADYDTHVHL,DADYDTHV
        REAL(EB) :: A1,A2,B1,B2,D1,D2,DENOM,M_VAP,M_VAP_MAX,Q_CON,Q_RAD,H_S_G_OLD
        REAL(EB) :: TMP_LIMIT,PI4_3,MW_DEN,PBAR,H_V_EFF,T_BOIL_EFF,X_EQ,DHOR,DH_V_A_DT,DYDT
        REAL(EB) :: Y_FILM,SUM_GAS,SUM_FILM,OM_SUM_FILM,ZZF,SUM_ZZF,MU_FILM,K_FILM,CP_FILM,D_FILM,RHO_FILM,R_FILM
        REAL(EB) :: NU_FAC,SH_FAC,B_NUMBER,LOG_B,LEWIS,THETA,C_DROP_FILM,BASE_NU,BASE_SH
        REAL(EB) :: MWR_SUM,Y_PRIM,Q_FRAC,X_SUM,C_DROP,C_DROP2,Q_TOT,T_MELT,M_VAP_CAND,M_VAP_OLD,M_VAP_LIMIT
        REAL(EB) :: ZZ_FILM(1:NTRACKED)

        IP = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
        IF (IP<1 .OR. IP>NP) RETURN
        C = CLASS_INDEX(IP)
        IF (C<1) RETURN
        IF (.NOT.CLASS_LIQUID(C)) RETURN

        I = MAX(0,MIN(IBP1,CELL_I(IP)))
        J = MAX(0,MIN(JBP1,CELL_J(IP)))
        K = MAX(0,MIN(KBP1,CELL_K(IP)))
        MASS_RATE(IP) = 0._EB
        IF (RADIUS(IP)<=CLASS_KILL_RADIUS(C)) RETURN
        R = RADIUS(IP)
        WGT = MAX(TWO_EPSILON_EB,WEIGHT(IP))
        RVC_LOC = MAX(TWO_EPSILON_EB,RVC(IP))
        M = MAX(TWO_EPSILON_EB,CLASS_DENSITY(C)*FOTHPI*R*R*R)
        T_DROP = MAX(1._EB,TEMPERATURE(IP))
        T_GAS = MAX(1._EB,TMPD(I,J,K))
        RHO_G = MAX(TWO_EPSILON_EB,RHOD(I,J,K))
        CP_G = 0._EB
        DO N=1,NTRACKED
            CP_G = CP_G + MAX(0._EB,CP_ZD_IN(MAX(0,MIN(ITMAX,NINT(T_GAS))),N))*MAX(0._EB,ZZD(I,J,K,N))
        ENDDO
        CP_G = MAX(1._EB,CP_G)
        ITF = MAX(0,MIN(ITMAX-1,INT(T_DROP)))
        CP_L = CLASS_CP_L(ITF,C)+(T_DROP-REAL(ITF,EB))*(CLASS_CP_L(ITF+1,C)-CLASS_CP_L(ITF,C))
        CP_L = MAX(1._EB,CP_L)
        MW_GAS = R0_IN/MAX(TWO_EPSILON_EB,RSUMD(I,J,K))

        YI = CLASS_Y_INDEX(C)
        ZI = CLASS_Z_INDEX(C)
        T_MELT = CLASS_T_MELT(C)
        Y_GAS = 0._EB
        IF (YI>0) THEN
            DO N=1,NTRACKED
                Y_GAS = Y_GAS + SPECIES_Z2YD_IN(YI,N)*ZZD(I,J,K,N)
            ENDDO
        ENDIF
        ITP = MAX(1,MIN(ITMAX,NINT(T_DROP)))
        ITG = MAX(1,MIN(ITMAX,NINT(T_GAS)))
        H_V = MAX(1._EB,CLASS_H_V(ITP,C))

        ! Match the CPU gas-film calculation using the FDS species property tables.
        MWR_SUM = 0._EB
        DO NS=1,NSPECIES
            IF (NS==YI) CYCLE
            Y_PRIM = 0._EB
            DO N=1,NTRACKED
                Y_PRIM = Y_PRIM + SPECIES_Z2YD_IN(NS,N)*ZZD(I,J,K,N)
            ENDDO
            MWR_SUM = MWR_SUM + MAX(0._EB,Y_PRIM)/MAX(TWO_EPSILON_EB,SPECIES_MW(NS))
        ENDDO
        Y_PRIM = MAX(0._EB,MIN(1._EB,Y_GAS))
        IF (MWR_SUM>TWO_EPSILON_EB) THEN
            MW_RATIO = (1._EB-Y_PRIM)/(MWR_SUM*MAX(TWO_EPSILON_EB,CLASS_MW(C)))
        ELSE
            MW_RATIO = 1._EB/(MAX(TWO_EPSILON_EB,MWR_ZD_IN(1))*MAX(TWO_EPSILON_EB,CLASS_MW(C)))
        ENDIF

        IZONE = MAX(0,PRESSURE_ZONED_IN(I,J,K))
        PBAR = MAX(TWO_EPSILON_EB,PBARD_IN(K,IZONE))
        T_BOIL_EFF = CLASS_T_BOIL(C)
        ITB = MAX(1,MIN(ITMAX,NINT(T_BOIL_EFF)))
        H_V_EFF = CLASS_H_V(ITB,C)*CLASS_MW(C)/R0_IN
        T_BOIL_EFF = MAX(1._EB,H_V_EFF*T_BOIL_EFF / &
            MAX(TWO_EPSILON_EB,H_V_EFF-T_BOIL_EFF*LOG(PBAR/P_STP_IN)))
        ITB = MAX(1,MIN(ITMAX,NINT(T_BOIL_EFF)))
        H_V_EFF = 0.5_EB*(H_V+CLASS_H_V(ITB,C))
        X_EQ = MIN(1._EB,EXP(H_V_EFF*CLASS_MW(C)/R0_IN*(1._EB/T_BOIL_EFF-1._EB/T_DROP)))
        Y_DROP = X_EQ/(MW_RATIO+(1._EB-MW_RATIO)*X_EQ+TWO_EPSILON_EB)

        ITB = MAX(1,MIN(ITMAX,INT(T_BOIL_EFF)))
        IF (INT(T_DROP)<INT(T_BOIL_EFF)) THEN
            ITF = MAX(1,MIN(ITMAX-1,INT(T_DROP)))
            DH_V_A_DT = 0.5_EB*(CLASS_H_V(ITF+1,C)-CLASS_H_V(ITF,C))
        ELSE
            ITF = MAX(2,MIN(ITMAX,ITB))
            DH_V_A_DT = 0.5_EB*(CLASS_H_V(ITF,C)-CLASS_H_V(ITF-1,C))
        ENDIF
        DHOR = H_V_EFF*CLASS_MW(C)/R0_IN
        DYDT = (MW_RATIO/MAX(TWO_EPSILON_EB,(X_EQ*(1._EB-MW_RATIO)+MW_RATIO)**2))* &
            (DHOR*X_EQ/(T_DROP*T_DROP)+(1._EB/T_BOIL_EFF-1._EB/T_DROP)*DH_V_A_DT*CLASS_MW(C)/R0_IN)

        VEL = SQRT((0.5_EB*(UD(I,J,K)+UD(MAX(0,I-1),J,K))-U(IP))**2 + &
                   (0.5_EB*(VD(I,J,K)+VD(I,MAX(0,J-1),K))-V(IP))**2 + &
                   (0.5_EB*(WD(I,J,K)+WD(I,J,MAX(0,K-1)))-W(IP))**2)
        ! The CPU path evaluates properties at the film state, not the gas-cell state.
        SUM_GAS = Y_GAS
        Y_FILM = Y_DROP+ONTH*(Y_GAS-Y_DROP)
        SUM_FILM = Y_FILM
        OM_SUM_FILM = 1._EB-SUM_FILM
        IF (OM_SUM_FILM<TWO_EPSILON_EB) THEN
            ZZ_FILM = 0._EB
            ZZ_FILM(ZI) = Y_FILM
        ELSEIF (ABS(SUM_GAS-1._EB)<TWO_EPSILON_EB) THEN
            ZZ_FILM = 0._EB
            ZZ_FILM(ZI) = Y_FILM
            ZZ_FILM(1) = 1._EB-SUM_FILM
        ELSE
            ZZ_FILM = ZZD(I,J,K,1:NTRACKED)
            ZZ_FILM(ZI) = ZZD(I,J,K,ZI) + &
                (Y_FILM*(1._EB-SUM_GAS+Y_GAS)+Y_GAS*(SUM_FILM-Y_FILM-1._EB))/ &
                MAX(TWO_EPSILON_EB,OM_SUM_FILM)
            ZZ_FILM = ZZ_FILM/MAX(TWO_EPSILON_EB,SUM(ZZ_FILM))
        ENDIF

        T_FILM_BLOCK: BLOCK
            REAL(EB) :: T_FILM
            T_FILM = T_DROP+ONTH*(T_GAS-T_DROP)
            ITF = MAX(0,MIN(ITMAX,NINT(T_FILM)))
            SUM_ZZF = 0._EB
            MU_FILM = 0._EB
            K_FILM = 0._EB
            CP_FILM = 0._EB
            R_FILM = 0._EB
            DO N=1,NTRACKED
                SUM_ZZF = SUM_ZZF + ZZ_FILM(N)*RSQ_MW_ZD_IN(N)
                MU_FILM = MU_FILM + MU_RSQMW_ZD_IN(ITF,N)*ZZ_FILM(N)
                K_FILM = K_FILM + K_RSQMW_ZD_IN(ITF,N)*ZZ_FILM(N)
                CP_FILM = CP_FILM + CP_ZD_IN(ITF,N)*ZZ_FILM(N)
                R_FILM = R_FILM + MWR_ZD_IN(N)*ZZ_FILM(N)
            ENDDO
            MU_FILM = MU_FILM/MAX(TWO_EPSILON_EB,SUM_ZZF)
            K_FILM = K_FILM/MAX(TWO_EPSILON_EB,SUM_ZZF)
            CP_FILM = MAX(1._EB,CP_FILM)
            R_FILM = R0_IN*R_FILM
            RHO_FILM = PBAR/MAX(TWO_EPSILON_EB,R_FILM*T_FILM)
            X_SUM = MAX(0._EB,ZZ_FILM(ZI))*MAX(TWO_EPSILON_EB,MWR_ZD_IN(ZI))
            D_FILM = D_Z_TABLED_IN(ITF,ZI)*X_SUM
            IF (X_SUM>TWO_EPSILON_EB) D_FILM = D_FILM/X_SUM
            D_FILM = MAX(TWO_EPSILON_EB,D_FILM)
            PR = MU_FILM*CP_FILM/MAX(TWO_EPSILON_EB,K_FILM)
            SC = MU_FILM/MAX(TWO_EPSILON_EB,RHO_FILM*D_FILM)
            RE_L = RHO_FILM*VEL*(2._EB*R)/MAX(TWO_EPSILON_EB,MU_FILM)
        END BLOCK T_FILM_BLOCK

        NU_FAC = 0.6_EB*PR**ONTH
        SH_FAC = 0.6_EB*SC**ONTH
        BASE_NU = 2._EB+NU_FAC*SQRT(MAX(0._EB,RE_L))
        BASE_SH = 2._EB+SH_FAC*SQRT(MAX(0._EB,RE_L))
        H_HEAT = BASE_NU*K_FILM/(2._EB*R)
        H_MASS = 0._EB
        IF (Y_DROP>Y_GAS) THEN
            B_NUMBER = (Y_DROP-Y_GAS)/MAX(DY_MIN_BLOWING_IN,1._EB-Y_DROP)
            LOG_B = LOG(1._EB+B_NUMBER)
            SELECT CASE(CLASS_EVAP_MODEL_D(C))
            CASE(RM_NO_B)
                H_MASS = BASE_SH*D_FILM/(2._EB*R)
            CASE(RM_B)
                H_HEAT = BASE_NU*K_FILM/(2._EB*R)*LOG_B/MAX(TWO_EPSILON_EB,B_NUMBER)
                H_MASS = BASE_SH*D_FILM/(2._EB*R)*LOG_B/MAX(TWO_EPSILON_EB,Y_DROP-Y_GAS)
            CASE(RM_LEWIS_B,RM_FL_LEWIS_B)
                H_MASS = BASE_SH*D_FILM/(2._EB*R)*LOG_B/MAX(TWO_EPSILON_EB,Y_DROP-Y_GAS)
                LEWIS = K_FILM/MAX(TWO_EPSILON_EB,RHO_FILM*D_FILM*CP_FILM)
                C_DROP_FILM = CP_ZD_IN(ITF,ZI)
                THETA = C_DROP_FILM/MAX(TWO_EPSILON_EB,CP_FILM*LEWIS)
                B_NUMBER = (1._EB+B_NUMBER)**THETA-1._EB
                LOG_B = LOG(1._EB+B_NUMBER)
                IF (CLASS_EVAP_MODEL_D(C)==RM_LEWIS_B) THEN
                    H_HEAT = BASE_NU*K_FILM/(2._EB*R)*LOG_B/MAX(TWO_EPSILON_EB,B_NUMBER)
                ELSE
                    Q_FRAC = (1._EB+B_NUMBER)**0.7_EB*LOG_B/MAX(TWO_EPSILON_EB,B_NUMBER)
                    H_MASS = BASE_SH*D_FILM/(2._EB*R)*LOG_B / &
                        (MAX(TWO_EPSILON_EB,Y_DROP-Y_GAS)*MAX(TWO_EPSILON_EB,Q_FRAC))
                    H_HEAT = BASE_NU*K_FILM/(2._EB*R)*LOG_B / &
                        (MAX(TWO_EPSILON_EB,B_NUMBER)*MAX(TWO_EPSILON_EB,Q_FRAC))
                ENDIF
            END SELECT
        ENDIF
        IF (CLASS_H_HEAT(C)>=0._EB) H_HEAT = CLASS_H_HEAT(C)
        IF (CLASS_H_MASS(C)>=0._EB) H_MASS = CLASS_H_MASS(C)

        AREA = 4._EB*PI*R*R
        M_GAS = RHO_G/RVC_LOC
        AGHRHO = AREA*H_MASS*RHO_FILM/(1._EB+0.5_EB*RVC_LOC*DT*AREA*WGT*H_MASS*RHO_FILM*(1._EB-Y_GAS)/RHO_G)
        DTOG = DT*WGT/(M_GAS*CP_G)
        DTGOG = 0.5_EB*DTOG*AREA*H_HEAT
        DTOP = DT/(M*CP_L)
        DTGOP = 0.5_EB*DTOP*AREA*H_HEAT
        ITF = MAX(0,MIN(ITMAX-1,INT(T_DROP)))
        H1 = H_SENS_ZD_IN(ITF,ZI)+(T_DROP-REAL(ITF,EB))* &
            (H_SENS_ZD_IN(ITF+1,ZI)-H_SENS_ZD_IN(ITF,ZI))
        ITF = MAX(0,MIN(ITMAX-1,INT(T_GAS)))
        H2 = H_SENS_ZD_IN(ITF,ZI)+(T_GAS-REAL(ITF,EB))* &
            (H_SENS_ZD_IN(ITF+1,ZI)-H_SENS_ZD_IN(ITF,ZI))
        Q_RAD = 0._EB
        IF (RADIATION_IN .AND. NARRAY>0) THEN
            SUM_FILM = 0._EB
            DO N=1,NARRAY
                SUM_FILM = SUM_FILM + MAX(0._EB,AVG_DROP_AREA(I,J,K,N))
            ENDDO
            IF (SUM_FILM>TWO_EPSILON_EB) Q_RAD = DT*QR_WD(I,J,K)*(AREA*0.25_EB)/SUM_FILM
        ENDIF
        DAHVHLDY = DTOG*AGHRHO*(H1-H2)*(Y_DROP-Y_GAS)
        DADYDTHVHL = 0.5_EB*DTOG*AGHRHO*(H1-H2)*DYDT
        DADYHV = DTOP*AGHRHO*H_V*(Y_DROP-Y_GAS)
        DADYDTHV = 0.5_EB*DTOP*AGHRHO*DYDT*H_V

        A1 = 1._EB+DTGOG
        B1 = -(DTGOG+DADYDTHVHL)
        A2 = -DTGOP
        B2 = 1._EB+DTGOP+DADYDTHV
        D1 = (1._EB-DTGOG)*T_GAS+(DTGOG-DADYDTHVHL)*T_DROP+DAHVHLDY
        D2 = DTGOP*T_GAS+(1._EB-DTGOP+DADYDTHV)*T_DROP-DADYHV+Q_RAD/(M*CP_L)
        DENOM = A1*B2-B1*A2
        IF (ABS(DENOM)<=TWO_EPSILON_EB) RETURN
        T_DROP_NEW = -(A2*D1-A1*D2)/DENOM
        T_GAS_NEW = (D1-B1*T_DROP_NEW)/A1
        Q_CON = DT*AREA*H_HEAT*0.5_EB*(T_GAS+T_GAS_NEW-T_DROP-T_DROP_NEW)
        M_VAP = MAX(0._EB,MIN(M,DT*AGHRHO*(Y_DROP-Y_GAS+0.5_EB*DYDT*(T_DROP_NEW-T_DROP))))
        M_VAP_MAX = MAX(0._EB,(0.33_EB*M_GAS)/WGT)
        M_VAP = MIN(M_VAP,M_VAP_MAX)
        Q_TOT = Q_CON+Q_RAD
        IF (Q_TOT>=M*H_V) M_VAP = M
        IF (M_VAP<M) THEN
            T_DROP_NEW = T_DROP+(Q_TOT-M_VAP*H_V)/(CP_L*MAX(TWO_EPSILON_EB,M-M_VAP))
            ITMP = MAX(0,MIN(ITMAX,NINT(T_DROP)))
            ITB = MAX(0,MIN(ITMAX,NINT(T_BOIL_EFF)))
            ITMP2 = MIN(ITB,MAX(0,MIN(ITMAX,NINT(T_DROP_NEW))))
            IF (T_MELT>0._EB) ITMP2 = MAX(NINT(T_MELT),ITMP2)
            IF (ITMP/=ITMP2) THEN
                C_DROP2 = 0._EB
                DO ITF=MIN(ITMP,ITMP2),MAX(ITMP,ITMP2)
                    C_DROP2 = C_DROP2+CLASS_CP_L(ITF,C)
                ENDDO
                C_DROP2 = C_DROP2/REAL(ABS(ITMP2-ITMP)+1,EB)
                T_DROP_NEW = T_DROP+(Q_TOT-M_VAP*H_V)/(MAX(TWO_EPSILON_EB,C_DROP2)*MAX(TWO_EPSILON_EB,M-M_VAP))
            ENDIF
            IF (T_MELT>0._EB .AND. T_DROP_NEW<T_MELT) THEN
                T_DROP_NEW = T_MELT
            ELSEIF (T_DROP_NEW>T_BOIL_EFF) THEN
                C_DROP2 = 0._EB
                DO ITF=MIN(ITMP,ITB),MAX(ITMP,ITMP2)
                    C_DROP2 = C_DROP2+CLASS_CP_L(ITF,C)
                ENDDO
                C_DROP2 = C_DROP2/REAL(ABS(ITB-ITMP)+1,EB)
                DENOM = H_V-C_DROP2*(T_BOIL_EFF-T_DROP)
                IF (ABS(DENOM)>TWO_EPSILON_EB) M_VAP = MIN(M,(Q_TOT-M*C_DROP2*(T_BOIL_EFF-T_DROP))/DENOM)
                IF (M_VAP>=M .AND. Q_TOT>TWO_EPSILON_EB) THEN
                    Q_FRAC = M_VAP*H_V/Q_TOT
                    Q_CON = Q_CON*Q_FRAC
                    Q_RAD = Q_RAD*Q_FRAC
                ENDIF
                T_DROP_NEW = T_BOIL_EFF
            ENDIF
        ELSE
            IF (Q_TOT>TWO_EPSILON_EB) THEN
                Q_FRAC = M_VAP*H_V/Q_TOT
                Q_CON = Q_CON*Q_FRAC
                Q_RAD = Q_RAD*Q_FRAC
            ENDIF
            T_DROP_NEW = T_BOIL_EFF
        ENDIF

        IF (M_VAP>TWO_EPSILON_EB) THEN
            M_VAP_CAND = M_VAP
            M_VAP_OLD = atomicAdd(MVAP_TOT_D(I,J,K),WGT*M_VAP_CAND)
            M_VAP_LIMIT = MAX(0._EB,(0.33_EB*M_GAS-M_VAP_OLD)/WGT)
            IF (M_VAP>M_VAP_LIMIT) THEN
                M_VAP = M_VAP_LIMIT
                IERR = atomicAdd(MVAP_TOT_D(I,J,K),WGT*(M_VAP-M_VAP_CAND))
                IF (M_VAP<M .AND. T_DROP_NEW>=T_BOIL_EFF) THEN
                    T_DROP_NEW = MIN(T_BOIL_EFF,T_DROP+(Q_TOT-M_VAP*H_V)/ &
                        (CP_L*MAX(TWO_EPSILON_EB,M-M_VAP)))
                ENDIF
            ENDIF
        ENDIF

        MNEW = MAX(0._EB,M-M_VAP)
        PI4_3 = FOTHPI*CLASS_DENSITY(C)
        RNEW = (MAX(0._EB,MNEW)/MAX(TWO_EPSILON_EB,PI4_3))**(1._EB/3._EB)
        RADIUS(IP) = RNEW
        MASS(IP) = MNEW
        TEMPERATURE(IP) = T_DROP_NEW

        MASS_RATE(IP) = M_VAP/MAX(TWO_EPSILON_EB,DT)
        IF (ZI>0 .AND. ZI<=NTRACKED .AND. M_VAP>0._EB) THEN
            H_S_G_OLD = MAX(TWO_EPSILON_EB,CP_G*T_GAS*M_GAS)
            MW_DEN = MAX(TWO_EPSILON_EB,CLASS_MW(C))
            MNEW = CLASS_ADJUST(C)*M_VAP
            IERR = atomicAdd(D_SOURCED(I,J,K),WGT/DT*(MW_GAS/MW_DEN*MNEW/M_GAS + &
                (MNEW*(H1-H2)-Q_CON)/H_S_G_OLD))
            IERR = atomicAdd(M_DOT_PPPD(I,J,K,ZI),MNEW*RVC_LOC*WGT/DT)
        ENDIF

        IF (CLASS_ARRAY_INDEX(C)>0) THEN
            DENOM = WGT*MASS(IP)*RVC_LOC
            AREA = WGT*PI*RADIUS(IP)*RADIUS(IP)*RVC_LOC
            IERR = atomicAdd(DROP_DEN(I,J,K,CLASS_ARRAY_INDEX(C)),DENOM)
            IERR = atomicAdd(DROP_TMP(I,J,K,CLASS_ARRAY_INDEX(C)),DENOM*T_DROP_NEW)
            IERR = atomicAdd(DROP_RAD(I,J,K,CLASS_ARRAY_INDEX(C)),AREA*RADIUS(IP))
            IERR = atomicAdd(DROP_AREA(I,J,K,CLASS_ARRAY_INDEX(C)),AREA)
        ENDIF
    END SUBROUTINE GPU_PARTICLE_STEP_KERNEL


    SUBROUTINE UPDATE_GPU_PARTICLE_AVERAGES(NM)
        INTEGER, INTENT(IN) :: NM
        INTEGER :: NC,NTHREADS,NBLOCKS,NPOINTS,IBP1,JBP1,KBP1,ARRAY_INDEX,Y_INDEX
        REAL(EB) :: FACTOR,TMP_MIN

        IF (N_LP_ARRAY_INDICES<=0) RETURN
        IF (.NOT.ALLOCATED(GPU_PARTICLES(NM)%AVG_DROP_DEN)) RETURN

        IBP1 = MESHES(NM)%IBP1
        JBP1 = MESHES(NM)%JBP1
        KBP1 = MESHES(NM)%KBP1
        NPOINTS = (IBP1+1)*(JBP1+1)*(KBP1+1)
        NTHREADS = 128
        NBLOCKS = (NPOINTS+NTHREADS-1)/NTHREADS
        GM => GPU_MESHES(NM)

        DO NC=1,N_LAGRANGIAN_CLASSES
            ARRAY_INDEX = LAGRANGIAN_PARTICLE_CLASS(NC)%ARRAY_INDEX
            IF (ARRAY_INDEX<1 .OR. ARRAY_INDEX>N_LP_ARRAY_INDICES) CYCLE
            FACTOR = LAGRANGIAN_PARTICLE_CLASS(NC)%RUNNING_AVERAGE_FACTOR
            Y_INDEX = LAGRANGIAN_PARTICLE_CLASS(NC)%Y_INDEX
            TMP_MIN = TMPM
            IF (Y_INDEX>0 .AND. Y_INDEX<=SIZE(SPECIES)) TMP_MIN = SPECIES(Y_INDEX)%TMP_MELT
            CALL UPDATE_GPU_PARTICLE_AVERAGES_KERNEL<<<NBLOCKS,NTHREADS,0,GM%STRM>>>( &
                NPOINTS,IBP1,JBP1,KBP1,ARRAY_INDEX,FACTOR,TMP_MIN, &
                GPU_PARTICLES(NM)%DROP_DEN,GPU_PARTICLES(NM)%DROP_TMP,GPU_PARTICLES(NM)%DROP_RAD,GPU_PARTICLES(NM)%DROP_AREA, &
                GPU_PARTICLES(NM)%AVG_DROP_DEN,GPU_PARTICLES(NM)%AVG_DROP_TMP,GPU_PARTICLES(NM)%AVG_DROP_RAD, &
                GPU_PARTICLES(NM)%AVG_DROP_AREA)
        ENDDO
    END SUBROUTINE UPDATE_GPU_PARTICLE_AVERAGES


    ATTRIBUTES(GLOBAL) SUBROUTINE UPDATE_GPU_PARTICLE_AVERAGES_KERNEL(NPOINTS,IBP1,JBP1,KBP1,ARRAY_INDEX,FACTOR,TMP_MIN, &
        DROP_DEN,DROP_TMP,DROP_RAD,DROP_AREA,AVG_DROP_DEN,AVG_DROP_TMP,AVG_DROP_RAD,AVG_DROP_AREA)
        INTEGER, VALUE :: NPOINTS,IBP1,JBP1,KBP1,ARRAY_INDEX
        REAL(EB), VALUE :: FACTOR,TMP_MIN
        REAL(EB), DEVICE :: DROP_DEN(0:IBP1,0:JBP1,0:KBP1,*),DROP_TMP(0:IBP1,0:JBP1,0:KBP1,*)
        REAL(EB), DEVICE :: DROP_RAD(0:IBP1,0:JBP1,0:KBP1,*),DROP_AREA(0:IBP1,0:JBP1,0:KBP1,*)
        REAL(EB), DEVICE :: AVG_DROP_DEN(0:IBP1,0:JBP1,0:KBP1,*),AVG_DROP_TMP(0:IBP1,0:JBP1,0:KBP1,*)
        REAL(EB), DEVICE :: AVG_DROP_RAD(0:IBP1,0:JBP1,0:KBP1,*),AVG_DROP_AREA(0:IBP1,0:JBP1,0:KBP1,*)
        INTEGER :: N,I,J,K
        REAL(EB) :: DEN,AREA,RAD,TMP

        N = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X - 1
        IF (N<0 .OR. N>=NPOINTS) RETURN
        I = MOD(N,IBP1+1)
        J = MOD(N/(IBP1+1),JBP1+1)
        K = N/((IBP1+1)*(JBP1+1))

        DEN = DROP_DEN(I,J,K,ARRAY_INDEX)
        AREA = DROP_AREA(I,J,K,ARRAY_INDEX)
        RAD = DROP_RAD(I,J,K,ARRAY_INDEX)/(AREA+TWO_EPSILON_EB)
        TMP = DROP_TMP(I,J,K,ARRAY_INDEX)/(DEN+TWO_EPSILON_EB)
        AVG_DROP_RAD(I,J,K,ARRAY_INDEX) = RAD
        AVG_DROP_TMP(I,J,K,ARRAY_INDEX) = MAX(TMP_MIN,FACTOR*AVG_DROP_TMP(I,J,K,ARRAY_INDEX) + (1._EB-FACTOR)*TMP)
        AVG_DROP_DEN(I,J,K,ARRAY_INDEX) = FACTOR*AVG_DROP_DEN(I,J,K,ARRAY_INDEX) + (1._EB-FACTOR)*DEN
        AVG_DROP_AREA(I,J,K,ARRAY_INDEX) = FACTOR*AVG_DROP_AREA(I,J,K,ARRAY_INDEX) + (1._EB-FACTOR)*AREA
        IF (AVG_DROP_DEN(I,J,K,ARRAY_INDEX)<0.0001_EB .AND. ABS(DEN)<TWO_EPSILON_EB) &
            AVG_DROP_DEN(I,J,K,ARRAY_INDEX) = 0._EB
    END SUBROUTINE UPDATE_GPU_PARTICLE_AVERAGES_KERNEL


    SUBROUTINE COPY_PARTICLE_RANGE(NM,FIRST_PARTICLE,LAST_PARTICLE,DEVICE_FIRST)
        INTEGER, INTENT(IN) :: NM,FIRST_PARTICLE,LAST_PARTICLE
        INTEGER, OPTIONAL, INTENT(IN) :: DEVICE_FIRST
        INTEGER :: IP,N,FIRST,ND
        INTEGER, ALLOCATABLE :: TAG_H(:),CLASS_H(:),BC_H(:),B1_H(:),CELL_I_H(:),CELL_J_H(:),CELL_K_H(:),META_H(:,:)
        REAL(EB), ALLOCATABLE :: X_H(:),Y_H(:),Z_H(:),U_H(:),V_H(:),W_H(:)
        REAL(EB), ALLOCATABLE :: MASS_H(:),RADIUS_H(:),TEMP_H(:),WEIGHT_H(:),RVC_H(:),INSERT_TIME_H(:),MASS_RATE_H(:)

        IF (LAST_PARTICLE<FIRST_PARTICLE) RETURN
        N = LAST_PARTICLE-FIRST_PARTICLE+1
        FIRST = FIRST_PARTICLE
        IF (PRESENT(DEVICE_FIRST)) FIRST = DEVICE_FIRST
        ALLOCATE(TAG_H(N),CLASS_H(N),BC_H(N),B1_H(N),CELL_I_H(N),CELL_J_H(N),CELL_K_H(N),META_H(4,N))
        ALLOCATE(X_H(N),Y_H(N),Z_H(N),U_H(N),V_H(N),W_H(N))
        ALLOCATE(MASS_H(N),RADIUS_H(N),TEMP_H(N),WEIGHT_H(N),RVC_H(N),INSERT_TIME_H(N),MASS_RATE_H(N))

        DO IP=FIRST_PARTICLE,LAST_PARTICLE
            N = IP-FIRST_PARTICLE+1
            TAG_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%TAG
            CLASS_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%CLASS_INDEX
            META_H(1,N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%INIT_INDEX
            META_H(2,N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%PROP_INDEX
            META_H(3,N) = MERGE(1,0,MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%SHOW)
            META_H(4,N) = 0
            IF (META_H(1,N)>0) THEN
                DO ND=1,N_DEVC
                    IF (DEVICE(ND)%LP_TAG==TAG_H(N)) META_H(4,N) = DEVICE(ND)%POINT
                ENDDO
            ENDIF
            BC_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%BC_INDEX
            B1_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%B1_INDEX
            CELL_I_H(N) = MESHES(NM)%BOUNDARY_COORD(BC_H(N))%IIG
            CELL_J_H(N) = MESHES(NM)%BOUNDARY_COORD(BC_H(N))%JJG
            CELL_K_H(N) = MESHES(NM)%BOUNDARY_COORD(BC_H(N))%KKG
            X_H(N) = MESHES(NM)%BOUNDARY_COORD(BC_H(N))%X
            Y_H(N) = MESHES(NM)%BOUNDARY_COORD(BC_H(N))%Y
            Z_H(N) = MESHES(NM)%BOUNDARY_COORD(BC_H(N))%Z
            U_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%U
            V_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%V
            W_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%W
            MASS_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%MASS
            RADIUS_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%RADIUS
            WEIGHT_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%PWT
            RVC_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%RVC
            INSERT_TIME_H(N) = MESHES(NM)%LAGRANGIAN_PARTICLE(IP)%T_INSERT
            MASS_RATE_H(N) = 0._EB
            TEMP_H(N) = TMPM
            IF (B1_H(N)>0) TEMP_H(N) = MESHES(NM)%BOUNDARY_PROP1(B1_H(N))%TMP_F
        ENDDO

        ! Explicit H2D avoids compiler-generated read/modify/write of an entire device pointer section.
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%TAG,TAG_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%CLASS_INDEX,CLASS_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%META,META_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%CELL_I,CELL_I_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%CELL_J,CELL_J_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%CELL_K,CELL_K_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%X,X_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%Y,Y_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%Z,Z_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%U,U_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%V,V_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%W,W_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%MASS,MASS_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%RADIUS,RADIUS_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%TEMPERATURE,TEMP_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%WEIGHT,WEIGHT_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%RVC,RVC_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%INSERT_TIME,INSERT_TIME_H,FIRST)
        CALL GPU_COPY_H2D(GPU_PARTICLES(NM)%MASS_RATE,MASS_RATE_H,FIRST)
    END SUBROUTINE COPY_PARTICLE_RANGE


    SUBROUTINE FINISH_GPU_PARTICLES
        INTEGER :: NM,IERR

        IF (.NOT.ALLOCATED(GPU_PARTICLES)) RETURN
        DO NM=1,SIZE(GPU_PARTICLES)
            CALL RELEASE_PARTICLE_MESH(NM)
        ENDDO
        DEALLOCATE(GPU_PARTICLES)
        IF (ALLOCATED(CLASS_Y_INDEX_D)) DEALLOCATE(CLASS_Y_INDEX_D,CLASS_Z_INDEX_D,CLASS_ARRAY_INDEX_D,CLASS_EVAP_MODEL_D)
        IF (ALLOCATED(CLASS_LIQUID_D)) DEALLOCATE(CLASS_LIQUID_D,CLASS_STATIC_D)
        IF (ALLOCATED(CLASS_DENSITY_D)) DEALLOCATE(CLASS_DENSITY_D,CLASS_CP_L_D,CLASS_MW_D)
        IF (ALLOCATED(CLASS_DENSE_VOLUME_FRACTION_D)) DEALLOCATE(CLASS_DENSE_VOLUME_FRACTION_D)
        IF (ALLOCATED(CLASS_T_BOIL_D)) DEALLOCATE(CLASS_T_BOIL_D,CLASS_T_MELT_D,CLASS_ADJUST_D,CLASS_KILL_RADIUS_D)
        IF (ALLOCATED(CLASS_H_HEAT_D)) DEALLOCATE(CLASS_H_HEAT_D,CLASS_H_MASS_D)
        IF (ALLOCATED(CLASS_H_V_D)) DEALLOCATE(CLASS_H_V_D)
        IF (ALLOCATED(SPECIES_MW_D)) DEALLOCATE(SPECIES_MW_D)
        IF (ALLOCATED(CLASS_R50_D)) DEALLOCATE(CLASS_R50_D,CLASS_WQABS_D,CLASS_WQSCA_D)
        IF (ALLOCATED(CLASS_LIFETIME_D)) DEALLOCATE(CLASS_LIFETIME_D)
        IF (ALLOCATED(MESH_BOUNDS_D)) DEALLOCATE(MESH_BOUNDS_D)
        IF (ALLOCATED(PARTICLE_PEER)) DEALLOCATE(PARTICLE_PEER,PARTICLE_REQUEST)
        IF (PARTICLE_COMM/=MPI_COMM_NULL) CALL MPI_COMM_FREE(PARTICLE_COMM,IERR)
        GPU_PARTICLE_CLASSES_READY = .FALSE.
    END SUBROUTINE FINISH_GPU_PARTICLES


    SUBROUTINE RELEASE_PARTICLE_MESH(NM)
        INTEGER, INTENT(IN) :: NM

        IF (ASSOCIATED(GPU_PARTICLES(NM)%CLASS_INDEX)) DEALLOCATE(GPU_PARTICLES(NM)%CLASS_INDEX)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%TAG)) DEALLOCATE(GPU_PARTICLES(NM)%TAG)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%META)) DEALLOCATE(GPU_PARTICLES(NM)%META)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DESTINATION)) &
            DEALLOCATE(GPU_PARTICLES(NM)%DESTINATION,GPU_PARTICLES(NM)%SLOT)
        IF (ALLOCATED(GPU_PARTICLES(NM)%COUNTS)) DEALLOCATE(GPU_PARTICLES(NM)%COUNTS,GPU_PARTICLES(NM)%OFFSETS)
        IF (ALLOCATED(GPU_PARTICLES(NM)%NEIGHBORS)) DEALLOCATE(GPU_PARTICLES(NM)%NEIGHBORS)
        IF (ALLOCATED(GPU_PARTICLES(NM)%SEND_COUNT)) &
            DEALLOCATE(GPU_PARTICLES(NM)%SEND_COUNT,GPU_PARTICLES(NM)%RECV_COUNT, &
                       GPU_PARTICLES(NM)%SEND_OFFSET,GPU_PARTICLES(NM)%RECV_OFFSET)
        IF (ALLOCATED(GPU_PARTICLES(NM)%SEND_INT)) DEALLOCATE(GPU_PARTICLES(NM)%SEND_INT,GPU_PARTICLES(NM)%SEND_REAL)
        IF (ALLOCATED(GPU_PARTICLES(NM)%RECV_INT)) DEALLOCATE(GPU_PARTICLES(NM)%RECV_INT,GPU_PARTICLES(NM)%RECV_REAL)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%CELL_I)) DEALLOCATE(GPU_PARTICLES(NM)%CELL_I)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%CELL_J)) DEALLOCATE(GPU_PARTICLES(NM)%CELL_J)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%CELL_K)) DEALLOCATE(GPU_PARTICLES(NM)%CELL_K)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%X)) DEALLOCATE(GPU_PARTICLES(NM)%X)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%Y)) DEALLOCATE(GPU_PARTICLES(NM)%Y)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%Z)) DEALLOCATE(GPU_PARTICLES(NM)%Z)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%U)) DEALLOCATE(GPU_PARTICLES(NM)%U)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%V)) DEALLOCATE(GPU_PARTICLES(NM)%V)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%W)) DEALLOCATE(GPU_PARTICLES(NM)%W)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%MASS)) DEALLOCATE(GPU_PARTICLES(NM)%MASS)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%RADIUS)) DEALLOCATE(GPU_PARTICLES(NM)%RADIUS)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%TEMPERATURE)) DEALLOCATE(GPU_PARTICLES(NM)%TEMPERATURE)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%WEIGHT)) DEALLOCATE(GPU_PARTICLES(NM)%WEIGHT)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%RVC)) DEALLOCATE(GPU_PARTICLES(NM)%RVC)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%INSERT_TIME)) DEALLOCATE(GPU_PARTICLES(NM)%INSERT_TIME)
        IF (ASSOCIATED(GPU_PARTICLES(NM)%MASS_RATE)) DEALLOCATE(GPU_PARTICLES(NM)%MASS_RATE)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DRAG_X)) DEALLOCATE(GPU_PARTICLES(NM)%DRAG_X)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DRAG_Y)) DEALLOCATE(GPU_PARTICLES(NM)%DRAG_Y)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DRAG_Z)) DEALLOCATE(GPU_PARTICLES(NM)%DRAG_Z)
        IF (ALLOCATED(GPU_PARTICLES(NM)%MVAP_TOT)) DEALLOCATE(GPU_PARTICLES(NM)%MVAP_TOT)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DROP_DEN)) DEALLOCATE(GPU_PARTICLES(NM)%DROP_DEN)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DROP_TMP)) DEALLOCATE(GPU_PARTICLES(NM)%DROP_TMP)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DROP_RAD)) DEALLOCATE(GPU_PARTICLES(NM)%DROP_RAD)
        IF (ALLOCATED(GPU_PARTICLES(NM)%DROP_AREA)) DEALLOCATE(GPU_PARTICLES(NM)%DROP_AREA)
