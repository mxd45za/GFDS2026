!------------------------------------------------------------------------------
! Module: G_ERRO
! Purpose: CUDA/MPI service operations and error handling.
!------------------------------------------------------------------------------
MODULE G_ERRO
    USE PRECISION_PARAMETERS, ONLY: EB
    USE GLOBAL_CONSTANTS, ONLY: LU_ERR,MY_RANK
    USE CUDAFOR
    USE MPI_F08, ONLY: MPI_REQUEST,MPI_COMM,MPI_COMM_WORLD,MPI_DOUBLE_PRECISION,MPI_INTEGER,MPI_STATUSES_IGNORE, &
                       MPI_SUCCESS,MPI_IRECV,MPI_ISEND,MPI_WAITALL,MPI_ABORT
    IMPLICIT NONE
    PRIVATE
    PUBLIC :: GPU_WAIT,GPU_WAIT_ALL,GPU_MPI_IRECV,GPU_MPI_ISEND,GPU_MPI_WAITALL,GPU_CREATE_STREAM
    PUBLIC :: GPU_COPY_H2D
    INTERFACE GPU_COPY_H2D
        MODULE PROCEDURE GPU_COPY_H2D_REAL,GPU_COPY_H2D_INT,GPU_COPY_H2D_META
    END INTERFACE
    INTERFACE GPU_MPI_IRECV
        MODULE PROCEDURE GPU_MPI_IRECV_1D,GPU_MPI_IRECV_3D,GPU_MPI_IRECV_INTEGER
    END INTERFACE
    INTERFACE GPU_MPI_ISEND
        MODULE PROCEDURE GPU_MPI_ISEND_1D,GPU_MPI_ISEND_3D,GPU_MPI_ISEND_INTEGER
    END INTERFACE

    CONTAINS

    SUBROUTINE GPU_COPY_H2D_REAL(BUFFER,HOST,FIRST)
        REAL(EB), DEVICE, CONTIGUOUS, INTENT(INOUT) :: BUFFER(:)
        REAL(EB), CONTIGUOUS, INTENT(IN) :: HOST(:)
        INTEGER, INTENT(IN) :: FIRST
        INTEGER :: STATUS

        STATUS = cudaMemcpy(BUFFER(FIRST:),HOST,SIZE(HOST),cudaMemcpyHostToDevice)
        IF (STATUS/=0) CALL RUNTIME_FAILURE('particle real H2D copy',STATUS)
    END SUBROUTINE GPU_COPY_H2D_REAL

    SUBROUTINE GPU_COPY_H2D_INT(BUFFER,HOST,FIRST)
        INTEGER, DEVICE, CONTIGUOUS, INTENT(INOUT) :: BUFFER(:)
        INTEGER, CONTIGUOUS, INTENT(IN) :: HOST(:)
        INTEGER, INTENT(IN) :: FIRST
        INTEGER :: STATUS

        STATUS = cudaMemcpy(BUFFER(FIRST:),HOST,SIZE(HOST),cudaMemcpyHostToDevice)
        IF (STATUS/=0) CALL RUNTIME_FAILURE('particle integer H2D copy',STATUS)
    END SUBROUTINE GPU_COPY_H2D_INT

    SUBROUTINE GPU_COPY_H2D_META(BUFFER,HOST,FIRST)
        INTEGER, DEVICE, CONTIGUOUS, INTENT(INOUT) :: BUFFER(:,:)
        INTEGER, CONTIGUOUS, INTENT(IN) :: HOST(:,:)
        INTEGER, INTENT(IN) :: FIRST
        INTEGER :: STATUS

        STATUS = cudaMemcpy(BUFFER(:,FIRST:),HOST,SIZE(HOST),cudaMemcpyHostToDevice)
        IF (STATUS/=0) CALL RUNTIME_FAILURE('particle metadata H2D copy',STATUS)
    END SUBROUTINE GPU_COPY_H2D_META

    SUBROUTINE GPU_CREATE_STREAM(STREAM)
        INTEGER(KIND=cuda_stream_kind), INTENT(OUT) :: STREAM
        INTEGER :: STATUS

        STATUS = cudaStreamCreate(STREAM)
        IF (STATUS/=0) CALL RUNTIME_FAILURE('CUDA stream creation',STATUS)
    END SUBROUTINE GPU_CREATE_STREAM

    SUBROUTINE GPU_WAIT(STREAM)
        INTEGER(KIND=cuda_stream_kind), INTENT(IN) :: STREAM
        INTEGER :: STATUS

        STATUS = cudaStreamSynchronize(STREAM)
        IF (STATUS/=0) CALL RUNTIME_FAILURE('CUDA stream synchronization',STATUS)
    END SUBROUTINE GPU_WAIT

    SUBROUTINE GPU_WAIT_ALL
        INTEGER :: STATUS

        STATUS = cudaDeviceSynchronize()
        IF (STATUS/=0) CALL RUNTIME_FAILURE('CUDA device synchronization',STATUS)
    END SUBROUTINE GPU_WAIT_ALL

    SUBROUTINE GPU_MPI_IRECV_1D(BUFFER,COUNT,PEER,TAG,REQUEST,COMM)
        REAL(EB), DEVICE, CONTIGUOUS, INTENT(INOUT) :: BUFFER(:)
        INTEGER, INTENT(IN) :: COUNT,PEER,TAG
        TYPE(MPI_REQUEST), INTENT(OUT) :: REQUEST
        TYPE(MPI_COMM), OPTIONAL, INTENT(IN) :: COMM
        TYPE(MPI_COMM) :: CHANNEL
        INTEGER :: STATUS

        CHANNEL = MPI_COMM_WORLD
        IF (PRESENT(COMM)) CHANNEL = COMM
        CALL MPI_IRECV(BUFFER,COUNT,MPI_DOUBLE_PRECISION,PEER,TAG,CHANNEL,REQUEST,STATUS)
        IF (STATUS/=MPI_SUCCESS) CALL RUNTIME_FAILURE('MPI_Irecv',STATUS)
    END SUBROUTINE GPU_MPI_IRECV_1D

    SUBROUTINE GPU_MPI_ISEND_1D(BUFFER,COUNT,PEER,TAG,REQUEST,COMM)
        REAL(EB), DEVICE, CONTIGUOUS, INTENT(IN) :: BUFFER(:)
        INTEGER, INTENT(IN) :: COUNT,PEER,TAG
        TYPE(MPI_REQUEST), INTENT(OUT) :: REQUEST
        TYPE(MPI_COMM), OPTIONAL, INTENT(IN) :: COMM
        TYPE(MPI_COMM) :: CHANNEL
        INTEGER :: STATUS

        CHANNEL = MPI_COMM_WORLD
        IF (PRESENT(COMM)) CHANNEL = COMM
        CALL MPI_ISEND(BUFFER,COUNT,MPI_DOUBLE_PRECISION,PEER,TAG,CHANNEL,REQUEST,STATUS)
        IF (STATUS/=MPI_SUCCESS) CALL RUNTIME_FAILURE('MPI_Isend',STATUS)
    END SUBROUTINE GPU_MPI_ISEND_1D

    SUBROUTINE GPU_MPI_IRECV_INTEGER(BUFFER,COUNT,PEER,TAG,REQUEST,COMM)
        INTEGER, DEVICE, CONTIGUOUS, INTENT(INOUT) :: BUFFER(:)
        INTEGER, INTENT(IN) :: COUNT,PEER,TAG
        TYPE(MPI_REQUEST), INTENT(OUT) :: REQUEST
        TYPE(MPI_COMM), INTENT(IN) :: COMM
        INTEGER :: STATUS

        CALL MPI_IRECV(BUFFER,COUNT,MPI_INTEGER,PEER,TAG,COMM,REQUEST,STATUS)
        IF (STATUS/=MPI_SUCCESS) CALL RUNTIME_FAILURE('particle MPI_Irecv',STATUS)
    END SUBROUTINE GPU_MPI_IRECV_INTEGER

    SUBROUTINE GPU_MPI_ISEND_INTEGER(BUFFER,COUNT,PEER,TAG,REQUEST,COMM)
        INTEGER, DEVICE, CONTIGUOUS, INTENT(IN) :: BUFFER(:)
        INTEGER, INTENT(IN) :: COUNT,PEER,TAG
        TYPE(MPI_REQUEST), INTENT(OUT) :: REQUEST
        TYPE(MPI_COMM), INTENT(IN) :: COMM
        INTEGER :: STATUS

        CALL MPI_ISEND(BUFFER,COUNT,MPI_INTEGER,PEER,TAG,COMM,REQUEST,STATUS)
        IF (STATUS/=MPI_SUCCESS) CALL RUNTIME_FAILURE('particle MPI_Isend',STATUS)
    END SUBROUTINE GPU_MPI_ISEND_INTEGER

    SUBROUTINE GPU_MPI_IRECV_3D(BUFFER,COUNT,PEER,TAG,REQUEST)
        REAL(EB), DEVICE, CONTIGUOUS, INTENT(INOUT) :: BUFFER(:,:,:)
        INTEGER, INTENT(IN) :: COUNT,PEER,TAG
        TYPE(MPI_REQUEST), INTENT(OUT) :: REQUEST
        INTEGER :: STATUS

        CALL MPI_IRECV(BUFFER,COUNT,MPI_DOUBLE_PRECISION,PEER,TAG,MPI_COMM_WORLD,REQUEST,STATUS)
        IF (STATUS/=MPI_SUCCESS) CALL RUNTIME_FAILURE('MPI_Irecv',STATUS)
    END SUBROUTINE GPU_MPI_IRECV_3D

    SUBROUTINE GPU_MPI_ISEND_3D(BUFFER,COUNT,PEER,TAG,REQUEST)
        REAL(EB), DEVICE, CONTIGUOUS, INTENT(IN) :: BUFFER(:,:,:)
        INTEGER, INTENT(IN) :: COUNT,PEER,TAG
        TYPE(MPI_REQUEST), INTENT(OUT) :: REQUEST
        INTEGER :: STATUS

        CALL MPI_ISEND(BUFFER,COUNT,MPI_DOUBLE_PRECISION,PEER,TAG,MPI_COMM_WORLD,REQUEST,STATUS)
        IF (STATUS/=MPI_SUCCESS) CALL RUNTIME_FAILURE('MPI_Isend',STATUS)
    END SUBROUTINE GPU_MPI_ISEND_3D

    SUBROUTINE GPU_MPI_WAITALL(REQUEST)
        TYPE(MPI_REQUEST), INTENT(INOUT) :: REQUEST(:)
        INTEGER :: STATUS

        CALL MPI_WAITALL(SIZE(REQUEST),REQUEST,MPI_STATUSES_IGNORE,STATUS)
        IF (STATUS/=MPI_SUCCESS) CALL RUNTIME_FAILURE('MPI_Waitall',STATUS)
    END SUBROUTINE GPU_MPI_WAITALL

    SUBROUTINE RUNTIME_FAILURE(OPERATION,STATUS)
        CHARACTER(*), INTENT(IN) :: OPERATION
        INTEGER, INTENT(IN) :: STATUS
        INTEGER :: IERR

        WRITE(LU_ERR,'(A,I0,3A,I0)') 'ERROR: rank ',MY_RANK,', ',OPERATION,', status=',STATUS
        CALL MPI_ABORT(MPI_COMM_WORLD,STATUS,IERR)
        ERROR STOP 'GPU runtime failure'
    END SUBROUTINE RUNTIME_FAILURE
END MODULE G_ERRO
