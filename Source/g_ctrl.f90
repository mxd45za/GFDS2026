    SUBROUTINE UPDATE_GPU_LINK_DETECTORS(T,DT,NM)
        IMPLICIT NONE

        REAL(EB), INTENT(IN) :: T,DT
        INTEGER, INTENT(IN) :: NM
        INTEGER :: N
        TYPE(DEVICE_TYPE), POINTER :: DV
        TYPE(SUBDEVICE_TYPE), POINTER :: SDV

        IF (GPU_MESHES(NM)%LD_N<=0) RETURN
        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)

        DO N=1,GM%LD_N
            DV => DEVICE(GM%LD_DEVICE_INDEX_H(N))
            SDV => DV%SUBDEVICE(DV%SUBDEVICE_INDEX(NM))
            SDV%GPU_VALUE_READY = .FALSE.
            GM%LD_UPDATE_H(N) = 1
            IF (ABS(T-T_BEGIN)>TWO_EPSILON_EB) THEN
                IF (DV%NO_UPDATE_DEVC_INDEX>0) THEN
                    IF (DEVICE(DV%NO_UPDATE_DEVC_INDEX)%CURRENT_STATE) GM%LD_UPDATE_H(N) = 0
                ELSEIF (DV%NO_UPDATE_CTRL_INDEX>0) THEN
                    IF (CONTROL(DV%NO_UPDATE_CTRL_INDEX)%CURRENT_STATE) GM%LD_UPDATE_H(N) = 0
                ENDIF
            ENDIF
        ENDDO
        GM%LD_UPDATE_D = GM%LD_UPDATE_H

        CALL UPDATE_LINK_DETECTOR_KERNEL<<<DIM3(GM%LD_BLOCKS,1,1),GPU_LD_BLOCK,0,GM%STRM>>>( &
            GM%LD_I_D,GM%LD_J_D,GM%LD_K_D,GM%LD_RTI_D,GM%LD_TMP_L_D,GM%LD_UPDATE_D,GM%TMPD,GM%UD,GM%VD,GM%WD, &
            GM%LD_N,IBP1,JBP1,KBP1,DT)
        CALL GPU_WAIT(GM%STRM)
        GM%LD_TMP_L_H = GM%LD_TMP_L_D

        DO N=1,GM%LD_N
            IF (GM%LD_UPDATE_H(N)==0) CYCLE
            DV => DEVICE(GM%LD_DEVICE_INDEX_H(N))
            SDV => DV%SUBDEVICE(DV%SUBDEVICE_INDEX(NM))
            DV%TMP_L = GM%LD_TMP_L_H(N)
            SDV%VALUE_1 = DV%TMP_L - TMPM
            SDV%VALUE_2 = 0._EB
            SDV%VALUE_3 = 0._EB
            SDV%VALUE_4 = 0._EB
            SDV%N_VALUES = 1
            SDV%GPU_VALUE_READY = .TRUE.
        ENDDO
    END SUBROUTINE UPDATE_GPU_LINK_DETECTORS

    ATTRIBUTES(GLOBAL) SUBROUTINE UPDATE_LINK_DETECTOR_KERNEL( &
        LD_I,LD_J,LD_K,LD_RTI,LD_TMP_L,LD_UPDATE,TMPD,UD,VD,WD,ND,IBP1_IN,JBP1_IN,KBP1_IN,DT_IN)
        IMPLICIT NONE

        INTEGER, VALUE :: ND,IBP1_IN,JBP1_IN,KBP1_IN
        REAL(EB), VALUE :: DT_IN
        INTEGER, DEVICE :: LD_I(*),LD_J(*),LD_K(*),LD_UPDATE(*)
        REAL(EB), DEVICE :: LD_RTI(*),LD_TMP_L(*)
        REAL(EB), DEVICE :: TMPD(0:IBP1_IN,0:JBP1_IN,0:*),UD(0:IBP1_IN,0:JBP1_IN,0:*), &
                            VD(0:IBP1_IN,0:JBP1_IN,0:*),WD(0:IBP1_IN,0:JBP1_IN,0:*)
        INTEGER :: N,I,J,K
        REAL(EB) :: TMP_G,VEL2,VEL,VELSR

        N = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
        IF (N>ND) RETURN
        IF (LD_UPDATE(N)==0) RETURN
        I = LD_I(N)
        J = LD_J(N)
        K = LD_K(N)
        TMP_G = TMPD(I,J,K)
        VEL2 = 0.25_EB*((UD(I,J,K)+UD(I-1,J,K))**2 + (VD(I,J,K)+VD(I,J-1,K))**2 + &
                        (WD(I,J,K)+WD(I,J,K-1))**2)
        VEL = SQRT(VEL2)
        VELSR = SQRT(VEL)
        LD_TMP_L(N) = LD_TMP_L(N) + DT_IN*VELSR*(TMP_G-LD_TMP_L(N))/LD_RTI(N)
    END SUBROUTINE UPDATE_LINK_DETECTOR_KERNEL

