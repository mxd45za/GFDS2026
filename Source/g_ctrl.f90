                MASS_EXT_COEF = SPECIES_MIXTURE(DV%Z_INDEX)%MASS_EXTINCTION_COEFFICIENT
            ELSEIF (SOOT_INDEX>0) THEN
                MASS_EXT_COEF = SPECIES(SOOT_INDEX)%MASS_EXTINCTION_COEFFICIENT
            ELSE
                MASS_EXT_COEF = 0._EB
            ENDIF

            IF (DV%N_T_E>=UBOUND(DV%T_E,1)) THEN
                DV%T_E => REALLOCATE(DV%T_E,0,DV%N_T_E+1000)
                DV%Y_E => REALLOCATE(DV%Y_E,0,DV%N_T_E+1000)
            ENDIF
            DV%N_T_E = DV%N_T_E + 1
            DV%Y_E(DV%N_T_E) = GM%OBS_Y_H(N)
            DV%T_E(DV%N_T_E) = T
            DT_C = PY%ALPHA_C*GM%OBS_VEL_H(N)**PY%BETA_C
            DT_E = PY%ALPHA_E*GM%OBS_VEL_H(N)**PY%BETA_E
            Y_E_LAG = 0._EB
            DO IL=DV%N_T_E-1,0,-1
                IF (DV%T_E(IL)>T-DT_E) CYCLE
                T_RATIO = (T-DT_E-DV%T_E(IL))/(DV%T_E(IL+1)-DV%T_E(IL))
                Y_E_LAG = MAX(0._EB,DV%Y_E(IL)+T_RATIO*(DV%Y_E(IL+1)-DV%Y_E(IL)))
                EXIT
            ENDDO
            DV%Y_C = MAX(0._EB,DV%Y_C+DT*(Y_E_LAG-DV%Y_C)/DT_C)
            SDV%VALUE_1 = (1._EB-EXP(-MASS_EXT_COEF*GM%OBS_RHO_H(N)*DV%Y_C))*100._EB
            SDV%VALUE_2 = 0._EB
            SDV%VALUE_3 = 0._EB
            SDV%VALUE_4 = 0._EB
            SDV%N_VALUES = 1
            SDV%GPU_VALUE_READY = .TRUE.
        ENDDO
    END SUBROUTINE UPDATE_GPU_OBSCURATION

    ATTRIBUTES(GLOBAL) SUBROUTINE SAMPLE_OBSCURATION_KERNEL(OBS_I,OBS_J,OBS_K,OBS_Y_INDEX,OBS_Z_INDEX,OBS_UPDATE, &
        OBS_Y,OBS_RHO,OBS_VEL,RHOD,ZZD,UD,VD,WD,Z2Y_D,ND,IBP1_IN,JBP1_IN,KBP1_IN,N_TRACKED_IN,N_SPECIES_IN)
        IMPLICIT NONE

        INTEGER, VALUE :: ND,IBP1_IN,JBP1_IN,KBP1_IN,N_TRACKED_IN,N_SPECIES_IN
        INTEGER, DEVICE :: OBS_I(*),OBS_J(*),OBS_K(*),OBS_Y_INDEX(*),OBS_Z_INDEX(*),OBS_UPDATE(*)
        INTEGER :: N,I,J,K,NS,Y_INDEX,Z_INDEX
        REAL(EB), DEVICE :: OBS_Y(*),OBS_RHO(*),OBS_VEL(*)
        REAL(EB), DEVICE :: RHOD(0:IBP1_IN,0:JBP1_IN,0:KBP1_IN)
        REAL(EB), DEVICE :: ZZD(0:IBP1_IN,0:JBP1_IN,0:KBP1_IN,1:N_TRACKED_IN)
        REAL(EB), DEVICE :: UD(0:IBP1_IN,0:JBP1_IN,0:KBP1_IN),VD(0:IBP1_IN,0:JBP1_IN,0:KBP1_IN), &
                            WD(0:IBP1_IN,0:JBP1_IN,0:KBP1_IN),Z2Y_D(1:N_SPECIES_IN,1:N_TRACKED_IN)
        REAL(EB) :: Y_SPECIES,VEL2

        N = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
        IF (N>ND) RETURN
        IF (OBS_UPDATE(N)==0) RETURN
        I = OBS_I(N)
        J = OBS_J(N)
        K = OBS_K(N)
        Y_INDEX = OBS_Y_INDEX(N)
        Z_INDEX = OBS_Z_INDEX(N)
        Y_SPECIES = 1._EB
        IF (Z_INDEX>0) THEN
            Y_SPECIES = ZZD(I,J,K,Z_INDEX)
        ELSEIF (Y_INDEX>0) THEN
            Y_SPECIES = 0._EB
            DO NS=1,N_TRACKED_IN
                Y_SPECIES = Y_SPECIES + Z2Y_D(Y_INDEX,NS)*ZZD(I,J,K,NS)
            ENDDO
            Y_SPECIES = MIN(1._EB,MAX(0._EB,Y_SPECIES))
        ENDIF
        VEL2 = 0.25_EB*((UD(I,J,K)+UD(I-1,J,K))**2+(VD(I,J,K)+VD(I,J-1,K))**2+ &
                        (WD(I,J,K)+WD(I,J,K-1))**2)
        OBS_Y(N) = Y_SPECIES
        OBS_RHO(N) = RHOD(I,J,K)
        OBS_VEL(N) = MAX(SQRT(VEL2),1.0E-10_EB)
    END SUBROUTINE SAMPLE_OBSCURATION_KERNEL

