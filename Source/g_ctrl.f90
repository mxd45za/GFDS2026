        SUPPORTED = .TRUE.
        DO N=1,N_DEVC
            DV => DEVICE(N)
            IF (.NOT.ALLOCATED(DV%QUANTITY_INDEX)) CYCLE
            IF (.NOT.ANY(DV%QUANTITY_INDEX==157)) CYCLE
            IF (.NOT.ALLOCATED(DV%SUBDEVICE_INDEX)) CYCLE
            IF (DV%SUBDEVICE_INDEX(NM)==0) CYCLE
            SDV => DV%SUBDEVICE(DV%SUBDEVICE_INDEX(NM))
            IF (SDV%MESH/=NM) CYCLE
            IF (DV%N_QUANTITY/=1 .OR. DV%QUANTITY_INDEX(1)/=157 .OR. DV%SPATIAL_STATISTIC/='null') THEN
                SUPPORTED = .FALSE.
                CYCLE
            ENDIF
            ND = ND + 1
        ENDDO

        IF (.NOT.SUPPORTED .OR. ND==0) RETURN
        GM%LD_N = ND

        ALLOCATE(I_H(ND),J_H(ND),K_H(ND),DEVICE_INDEX_H(ND),RTI_H(ND),TMP_H(ND))
