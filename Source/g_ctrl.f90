    SUBROUTINE SYNC_GPU_VENT_IGNITION(NM)
        IMPLICIT NONE

        INTEGER, INTENT(IN) :: NM
        INTEGER :: NV,IW,II,JJ,KK,IC,IOR,N_MAX,N_UPDATE,POS
        LOGICAL :: CHANGED
        INTEGER, ALLOCATABLE :: WALL_INDEX_H(:),WALL_POSITION_H(:)
        REAL(EB), ALLOCATABLE :: WALL_T_IGN_H(:)
        INTEGER, DEVICE, ALLOCATABLE :: WALL_INDEX_D(:)
        REAL(EB), DEVICE, ALLOCATABLE :: WALL_T_IGN_D(:)
        TYPE(VENTS_TYPE), POINTER :: VT

        IF (.NOT.GPU_DEVICE_ON) RETURN
        IF (.NOT.ALLOCATED(GPU_MESHES)) RETURN
        IF (.NOT.GPU_MESHES(NM)%INITIALIZED) RETURN

        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)
        IF (GM%WALL_UB<=0) RETURN

        N_MAX = 0
        DO NV=1,MESHES(NM)%N_VENT
            VT => MESHES(NM)%VENTS(NV)
            CHANGED = .FALSE.
            IF (VT%DEVC_INDEX>0) THEN
                CHANGED = DEVICE(VT%DEVC_INDEX)%CURRENT_STATE .NEQV. DEVICE(VT%DEVC_INDEX)%PRIOR_STATE
            ELSEIF (VT%CTRL_INDEX>0) THEN
                CHANGED = CONTROL(VT%CTRL_INDEX)%CURRENT_STATE .NEQV. CONTROL(VT%CTRL_INDEX)%PRIOR_STATE
            ENDIF
            IF (.NOT.CHANGED) CYCLE
            N_MAX = N_MAX + MAX(1,VT%I2-VT%I1)*MAX(1,VT%J2-VT%J1)*MAX(1,VT%K2-VT%K1)
        ENDDO
        IF (N_MAX<=0) RETURN

        ALLOCATE(WALL_INDEX_H(1:N_MAX),WALL_T_IGN_H(1:N_MAX))
        ALLOCATE(WALL_POSITION_H(0:GM%WALL_UB))
        WALL_POSITION_H = 0
        N_UPDATE = 0

        ! Keep affected walls; later vents overwrite shared faces.
        DO NV=1,MESHES(NM)%N_VENT
            VT => MESHES(NM)%VENTS(NV)
            CHANGED = .FALSE.
            IF (VT%DEVC_INDEX>0) THEN
                CHANGED = DEVICE(VT%DEVC_INDEX)%CURRENT_STATE .NEQV. DEVICE(VT%DEVC_INDEX)%PRIOR_STATE
            ELSEIF (VT%CTRL_INDEX>0) THEN
                CHANGED = CONTROL(VT%CTRL_INDEX)%CURRENT_STATE .NEQV. CONTROL(VT%CTRL_INDEX)%PRIOR_STATE
            ENDIF
            IF (.NOT.CHANGED) CYCLE

            IOR = VT%IOR
            DO KK=VT%K1+1,MAX(VT%K1+1,VT%K2)
                DO JJ=VT%J1+1,MAX(VT%J1+1,VT%J2)
                    DO II=VT%I1+1,MAX(VT%I1+1,VT%I2)
                        IC = 0
                        SELECT CASE(IOR)
                            CASE(1:)
                                IC = CELL_INDEX(II,JJ,KK)
                            CASE(-1)
                                IC = CELL_INDEX(II-1,JJ,KK)
                            CASE(-2)
                                IC = CELL_INDEX(II,JJ-1,KK)
                            CASE(-3)
                                IC = CELL_INDEX(II,JJ,KK-1)
                        END SELECT
                        IF (IC<=0) CYCLE
                        IW = CELL(IC)%WALL_INDEX(-IOR)
                        IF (IW<=0 .OR. IW>GM%WALL_UB) CYCLE
                        POS = WALL_POSITION_H(IW)
                        IF (POS==0) THEN
                            N_UPDATE = N_UPDATE + 1
                            POS = N_UPDATE
                            WALL_POSITION_H(IW) = POS
                            WALL_INDEX_H(POS) = IW
                        ENDIF
                        WALL_T_IGN_H(POS) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%T_IGN
                    ENDDO
                ENDDO
            ENDDO
        ENDDO

        IF (N_UPDATE<=0) THEN
            DEALLOCATE(WALL_INDEX_H,WALL_T_IGN_H,WALL_POSITION_H)
            RETURN
        ENDIF

        ALLOCATE(WALL_INDEX_D(1:N_UPDATE),WALL_T_IGN_D(1:N_UPDATE))
        CALL GPU_WAIT(GM%STRM)
        WALL_INDEX_D = WALL_INDEX_H(1:N_UPDATE)
        WALL_T_IGN_D = WALL_T_IGN_H(1:N_UPDATE)
        CALL GPU_WAIT(GM%STRM)
        CALL UPDATE_WALL_T_IGN_KERNEL<<<DIM3((N_UPDATE+GPU_LD_BLOCK-1)/GPU_LD_BLOCK,1,1),GPU_LD_BLOCK,0,GM%STRM>>>( &
            GM%WALL_T_IGN,WALL_INDEX_D,WALL_T_IGN_D,N_UPDATE)
        CALL GPU_WAIT(GM%STRM)
        DEALLOCATE(WALL_INDEX_D,WALL_T_IGN_D)
        DEALLOCATE(WALL_INDEX_H,WALL_T_IGN_H,WALL_POSITION_H)
    END SUBROUTINE SYNC_GPU_VENT_IGNITION

    SUBROUTINE SYNC_GPU_OBST(NM)
        IMPLICIT NONE

        INTEGER, INTENT(IN) :: NM
        INTEGER :: IC,IW,N,NC,NW,UPDATE_TMP,NSBUF,NSPECBUF,N_AUX
        INTEGER :: IQ_RHO_D_F,IQ_RHO_D_DZDN_F,IQ_M_DOT_ADJUST,IQ_M_DOT_ACTUAL,IQ_Q_IN,IQ_QDOTPP
        INTEGER, ALLOCATABLE :: CI_H(:),CJ_H(:),CK_H(:),CELL_INDEX_H(:)
        INTEGER, ALLOCATABLE :: WALL_INDEX_H(:),WALL_INT_H(:,:)
        LOGICAL, ALLOCATABLE :: CELL_SOLID_H(:)
        REAL(EB), ALLOCATABLE :: CELL_RHO_H(:),CELL_RHOS_H(:),CELL_TMP_H(:),CELL_RSUM_H(:),CELL_ZZ_H(:,:),CELL_ZZS_H(:,:)
        REAL(EB), ALLOCATABLE :: WALL_REAL_H(:,:),WALL_WORK_H(:),WALL_AUX_H(:,:)
        INTEGER, DEVICE, ALLOCATABLE :: CI_D(:),CJ_D(:),CK_D(:),WALL_INDEX_D(:),WALL_INT_D(:,:)
        LOGICAL, DEVICE, ALLOCATABLE :: CELL_SOLID_D(:)
        REAL(EB), DEVICE, ALLOCATABLE :: CELL_RHO_D(:),CELL_RHOS_D(:),CELL_TMP_D(:),CELL_RSUM_D(:),CELL_ZZ_D(:,:),CELL_ZZS_D(:,:)
        REAL(EB), DEVICE, ALLOCATABLE :: WALL_REAL_D(:,:),WALL_WORK_D(:),WALL_AUX_D(:,:)

        IF (.NOT.GPU_DEVICE_ON .OR. .NOT.OBST_CREATED_OR_REMOVED) RETURN
        IF (.NOT.ALLOCATED(GPU_MESHES)) RETURN
        IF (.NOT.GPU_MESHES(NM)%INITIALIZED) RETURN

        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)
        CALL GPU_WAIT(GM%STRM)

        NC = 0
        DO IC=1,GM%CELL_UB
            IF (GM%CELL_SOLID_PREV_H(IC) .NEQV. CELL(IC)%SOLID) NC = NC + 1
        ENDDO
        NW = 0
        DO IW=1,GM%WALL_UB
            IF (GM%WALL_BTYPE_PREV_H(IW)==WALL(IW)%BOUNDARY_TYPE .AND. &
                GM%WALL_SF_PREV_H(IW)==WALL(IW)%SURF_INDEX) CYCLE
            NW = NW + 1
        ENDDO
        IF (NC==0 .AND. NW==0) RETURN

        IF (NC>0) THEN
            ALLOCATE(CI_H(NC),CJ_H(NC),CK_H(NC),CELL_INDEX_H(NC),CELL_SOLID_H(NC))
            ALLOCATE(CELL_RHO_H(NC),CELL_RHOS_H(NC),CELL_TMP_H(NC),CELL_RSUM_H(NC))
            ALLOCATE(CELL_ZZ_H(1:MAX(1,N_TOTAL_SCALARS),NC),CELL_ZZS_H(1:MAX(1,N_TOTAL_SCALARS),NC))
            N = 0
            DO IC=1,GM%CELL_UB
                IF (GM%CELL_SOLID_PREV_H(IC) .EQV. CELL(IC)%SOLID) CYCLE
                N = N + 1
                CELL_INDEX_H(N) = IC
                CI_H(N) = CELL(IC)%I
                CJ_H(N) = CELL(IC)%J
                CK_H(N) = CELL(IC)%K
                CELL_SOLID_H(N) = CELL(IC)%SOLID
                CELL_RHO_H(N) = RHO(CI_H(N),CJ_H(N),CK_H(N))
                CELL_RHOS_H(N) = RHOS(CI_H(N),CJ_H(N),CK_H(N))
                CELL_TMP_H(N) = TMP(CI_H(N),CJ_H(N),CK_H(N))
                CELL_RSUM_H(N) = RSUM(CI_H(N),CJ_H(N),CK_H(N))
                IF (N_TOTAL_SCALARS>0) THEN
                    CELL_ZZ_H(1:N_TOTAL_SCALARS,N) = ZZ(CI_H(N),CJ_H(N),CK_H(N),1:N_TOTAL_SCALARS)
                    CELL_ZZS_H(1:N_TOTAL_SCALARS,N) = ZZS(CI_H(N),CJ_H(N),CK_H(N),1:N_TOTAL_SCALARS)
                ENDIF
            ENDDO

            ALLOCATE(CI_D(NC),CJ_D(NC),CK_D(NC),CELL_SOLID_D(NC),CELL_RHO_D(NC),CELL_RHOS_D(NC), &
                     CELL_TMP_D(NC),CELL_RSUM_D(NC))
            ALLOCATE(CELL_ZZ_D(1:MAX(1,N_TOTAL_SCALARS),NC),CELL_ZZS_D(1:MAX(1,N_TOTAL_SCALARS),NC))
            CI_D = CI_H
            CJ_D = CJ_H
            CK_D = CK_H
            CELL_SOLID_D = CELL_SOLID_H
            CELL_RHO_D = CELL_RHO_H
            CELL_RHOS_D = CELL_RHOS_H
            CELL_TMP_D = CELL_TMP_H
            CELL_RSUM_D = CELL_RSUM_H
            CELL_ZZ_D = CELL_ZZ_H
            CELL_ZZS_D = CELL_ZZS_H
            CALL GPU_WAIT(GM%STRM)

            UPDATE_TMP = MERGE(1,0,SOLID_PHASE_ONLY)
            CALL UPDATE_OBST_CELLS<<<DIM3((NC+GPU_LD_BLOCK-1)/GPU_LD_BLOCK,1,1),GPU_LD_BLOCK,0,GM%STRM>>>( &
                CI_D,CJ_D,CK_D,CELL_SOLID_D,CELL_RHO_D,CELL_RHOS_D,CELL_TMP_D,CELL_RSUM_D,CELL_ZZ_D,CELL_ZZS_D, &
                GM%CELL_INDEXD,GM%CELL_SOLID,GM%RHOD,GM%RHOSD,GM%TMPD,GM%RSUMD,GM%ZZD,GM%ZZSD, &
                NC,IBP1,JBP1,KBP1,N_TOTAL_SCALARS,MAX(1,N_TOTAL_SCALARS),UPDATE_TMP)
            CALL GPU_WAIT(GM%STRM)
            DO N=1,NC
                GM%CELL_SOLID_PREV_H(CELL_INDEX_H(N)) = CELL_SOLID_H(N)
            ENDDO
            DEALLOCATE(CI_H,CJ_H,CK_H,CELL_INDEX_H,CELL_SOLID_H,CELL_RHO_H,CELL_RHOS_H,CELL_TMP_H, &
                       CELL_RSUM_H,CELL_ZZ_H,CELL_ZZS_H)
            DEALLOCATE(CI_D,CJ_D,CK_D,CELL_SOLID_D,CELL_RHO_D,CELL_RHOS_D,CELL_TMP_D,CELL_RSUM_D,CELL_ZZ_D,CELL_ZZS_D)
        ENDIF

        IF (NW>0) THEN
            NSBUF = MAX(1,N_TOTAL_SCALARS)
            NSPECBUF = MAX(1,N_TRACKED_SPECIES)
            IQ_RHO_D_F = NSBUF
            IQ_RHO_D_DZDN_F = IQ_RHO_D_F + NSPECBUF
            IQ_M_DOT_ADJUST = IQ_RHO_D_DZDN_F + NSPECBUF
            IQ_M_DOT_ACTUAL = IQ_M_DOT_ADJUST + NSPECBUF
            IQ_Q_IN = IQ_M_DOT_ACTUAL + NSPECBUF
            IQ_QDOTPP = IQ_Q_IN + MAX_QDOTPP_REF
            N_AUX = IQ_QDOTPP + MAX_QDOTPP_REF
            ALLOCATE(WALL_INDEX_H(NW),WALL_INT_H(1:4,NW),WALL_REAL_H(1:22,NW))
            ALLOCATE(WALL_WORK_H(NW),WALL_AUX_H(1:N_AUX,NW))
            N = 0
            DO IW=1,GM%WALL_UB
                IF (GM%WALL_BTYPE_PREV_H(IW)==WALL(IW)%BOUNDARY_TYPE .AND. &
                    GM%WALL_SF_PREV_H(IW)==WALL(IW)%SURF_INDEX) CYCLE
                N = N + 1
                WALL_INDEX_H(N) = IW
                WALL_INT_H(1,N) = WALL(IW)%BOUNDARY_TYPE
                WALL_INT_H(2,N) = WALL(IW)%SURF_INDEX
                WALL_INT_H(3,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%PRESSURE_ZONE
                WALL_INT_H(4,N) = NEUMANN
                WALL_REAL_H(1,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%HEAT_TRANS_COEF
                WALL_REAL_H(2,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_CON_F
                WALL_REAL_H(3,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%K_G
                WALL_REAL_H(4,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%RHO_G
                WALL_REAL_H(5,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%TMP_G
                WALL_REAL_H(6,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%TMP_F
                WALL_REAL_H(7,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%RHO_F
                WALL_REAL_H(8,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%RDN
                WALL_REAL_H(9,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%U_NORMAL
                WALL_REAL_H(10,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%U_NORMAL_S
                WALL_REAL_H(11,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%U_NORMAL_0
                WALL_REAL_H(12,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%AREA
                WALL_REAL_H(13,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%AREA_ADJUST
                WALL_REAL_H(14,N) = 0._EB
                IF (IW<=MESHES(NM)%N_EXTERNAL_WALL_CELLS) THEN
                    WALL_INT_H(4,N) = MESHES(NM)%EXTERNAL_WALL(IW)%PRESSURE_BC_TYPE
                    WALL_REAL_H(14,N) = MESHES(NM)%EXTERNAL_WALL(IW)%DUNDT
                ENDIF
                WALL_REAL_H(15,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%EMISSIVITY
                WALL_REAL_H(16,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_RAD_IN
                WALL_REAL_H(17,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_RAD_OUT
                WALL_REAL_H(18,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%T_IGN
                WALL_REAL_H(19,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%BURN_DURATION
                WALL_REAL_H(20,N) = BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_IN_SMOOTH
                WALL_REAL_H(21,N) = BOUNDARY_PROP2(WALL(IW)%B2_INDEX)%U_TAU
                WALL_REAL_H(22,N) = BOUNDARY_PROP2(WALL(IW)%B2_INDEX)%Y_PLUS
                WALL_WORK_H(N) = WALL_WORK1(IW)
                WALL_AUX_H(:,N) = 0._EB
                IF (N_TOTAL_SCALARS>0) WALL_AUX_H(1,N) = 1._EB
                IF (ALLOCATED(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%ZZ_F)) THEN
                    WALL_AUX_H(1:MIN(N_TOTAL_SCALARS,N_TRACKED_SPECIES),N) = &
                        BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%ZZ_F(1:MIN(N_TOTAL_SCALARS,N_TRACKED_SPECIES))
                ENDIF
                IF (ALLOCATED(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%RHO_D_F)) THEN
                    WALL_AUX_H(IQ_RHO_D_F+1:IQ_RHO_D_F+N_TRACKED_SPECIES,N) = &
                        BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%RHO_D_F(1:N_TRACKED_SPECIES)
                ENDIF
                IF (ALLOCATED(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%RHO_D_DZDN_F)) THEN
                    WALL_AUX_H(IQ_RHO_D_DZDN_F+1:IQ_RHO_D_DZDN_F+N_TRACKED_SPECIES,N) = &
                        BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%RHO_D_DZDN_F(1:N_TRACKED_SPECIES)
                ENDIF
                IF (ALLOCATED(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%M_DOT_G_PP_ADJUST)) THEN
                    WALL_AUX_H(IQ_M_DOT_ADJUST+1:IQ_M_DOT_ADJUST+N_TRACKED_SPECIES,N) = &
                        BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES)
                ENDIF
                IF (ALLOCATED(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%M_DOT_G_PP_ACTUAL)) THEN
                    WALL_AUX_H(IQ_M_DOT_ACTUAL+1:IQ_M_DOT_ACTUAL+N_TRACKED_SPECIES,N) = &
                        BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%M_DOT_G_PP_ACTUAL(1:N_TRACKED_SPECIES)
                ENDIF
                IF (ALLOCATED(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_IN_SMOOTH_INT)) THEN
                    WALL_AUX_H(IQ_Q_IN+1:IQ_Q_IN+MIN(MAX_QDOTPP_REF, &
                        SIZE(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_IN_SMOOTH_INT)),N) = &
                        BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_IN_SMOOTH_INT(1:MIN(MAX_QDOTPP_REF, &
                        SIZE(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%Q_IN_SMOOTH_INT)))
                ENDIF
                IF (ALLOCATED(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%QDOTPP_INT)) THEN
                    WALL_AUX_H(IQ_QDOTPP+1:IQ_QDOTPP+MIN(MAX_QDOTPP_REF, &
                        SIZE(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%QDOTPP_INT)),N) = &
                        BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%QDOTPP_INT(1:MIN(MAX_QDOTPP_REF, &
                        SIZE(BOUNDARY_PROP1(WALL(IW)%B1_INDEX)%QDOTPP_INT)))
                ENDIF
            ENDDO
            ALLOCATE(WALL_INDEX_D(NW),WALL_INT_D(1:4,NW),WALL_REAL_D(1:22,NW))
            ALLOCATE(WALL_WORK_D(NW),WALL_AUX_D(1:N_AUX,NW))
            WALL_INDEX_D = WALL_INDEX_H
            WALL_INT_D = WALL_INT_H
            WALL_REAL_D = WALL_REAL_H
            WALL_WORK_D = WALL_WORK_H
            WALL_AUX_D = WALL_AUX_H
            CALL GPU_WAIT(GM%STRM)
            CALL UPDATE_OBST_WALLS<<<DIM3((NW+GPU_LD_BLOCK-1)/GPU_LD_BLOCK,1,1),GPU_LD_BLOCK,0,GM%STRM>>>( &
                GM%WALL_TOPO_AOS,GM%WALL_SF_INDEX,GM%WALL_PRESSURE_ZONE,GM%WALL_PRESSURE_BC_TYPE, &
                GM%WALL_HEAT_TRANS_COEF,GM%WALL_Q_CON_F,GM%WALL_K_G,GM%WALL_RHO_G,GM%WALL_TMP_G,GM%WALL_TMP_F, &
                GM%WALL_RHO_F,GM%WALL_RDN,GM%WALL_U_NORMAL,GM%WALL_U_NORMAL_S,GM%WALL_U_NORMAL_0, &
                GM%WALL_AREA,GM%WALL_AREA_ADJUST,GM%WALL_DUNDTD,GM%WALL_EMISSIVITY,GM%WALL_Q_RAD_IN, &
                GM%WALL_Q_RAD_OUT,GM%WALL_T_IGN,GM%WALL_BURN_DURATION,GM%WALL_Q_IN_SMOOTH, &
                GM%WALL_WORK1D,GM%WALL_U_TAU,GM%WALL_Y_PLUS,GM%WALL_ZZ_F,GM%WALL_RHO_D_F,GM%WALL_RHO_D_DZDN_F, &
                GM%WALL_M_DOT_G_PP_ADJUST,GM%WALL_M_DOT_G_PP_ACTUAL,GM%WALL_Q_IN_SMOOTH_INT,GM%WALL_QDOTPP_INT, &
                WALL_INDEX_D,WALL_INT_D,WALL_REAL_D,WALL_WORK_D,WALL_AUX_D,NW,GM%WALL_UB,N_TOTAL_SCALARS, &
                N_TRACKED_SPECIES,NSBUF,NSPECBUF,N_AUX,IQ_Q_IN,IQ_QDOTPP)
            CALL GPU_WAIT(GM%STRM)
            DO N=1,NW
                IW = WALL_INDEX_H(N)
                GM%WALL_BTYPE_PREV_H(IW) = WALL_INT_H(1,N)
                GM%WALL_SF_PREV_H(IW) = WALL_INT_H(2,N)
            ENDDO
            DEALLOCATE(WALL_INDEX_H,WALL_INT_H,WALL_REAL_H,WALL_WORK_H,WALL_AUX_H)
            DEALLOCATE(WALL_INDEX_D,WALL_INT_D,WALL_REAL_D,WALL_WORK_D,WALL_AUX_D)
        ENDIF
    END SUBROUTINE SYNC_GPU_OBST

    ATTRIBUTES(GLOBAL) SUBROUTINE UPDATE_OBST_CELLS(CI,CJ,CK,SOLID_H,RHO_H,RHOS_H,TMP_H,RSUM_H,ZZ_H,ZZS_H, &
        CELL_INDEXD,SOLID_D,RHOD,RHOSD,TMPD,RSUMD,ZZD,ZZSD,NC,IBP1_IN,JBP1_IN,KBP1_IN,N_SCALARS,NS_BUF,UPDATE_TMP)
        IMPLICIT NONE

        INTEGER, VALUE :: NC,IBP1_IN,JBP1_IN,KBP1_IN,N_SCALARS,NS_BUF,UPDATE_TMP
        INTEGER, DEVICE :: CI(*),CJ(*),CK(*)
        LOGICAL, DEVICE :: SOLID_H(*),SOLID_D(0:*)
        INTEGER, DEVICE :: CELL_INDEXD(0:IBP1_IN,0:JBP1_IN,0:*)
        REAL(EB), DEVICE :: RHO_H(*),RHOS_H(*),TMP_H(*),RSUM_H(*)
