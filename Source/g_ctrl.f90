    SUBROUTINE INITIALIZE_GPU_LINK_DETECTORS(NM)
        IMPLICIT NONE

        INTEGER, INTENT(IN) :: NM
        INTEGER :: N,ND
        LOGICAL :: SUPPORTED
        TYPE(DEVICE_TYPE), POINTER :: DV
        TYPE(SUBDEVICE_TYPE), POINTER :: SDV
        TYPE(PROPERTY_TYPE), POINTER :: PY
        INTEGER, ALLOCATABLE :: I_H(:),J_H(:),K_H(:),DEVICE_INDEX_H(:)
        REAL(EB), ALLOCATABLE :: RTI_H(:),TMP_H(:)

        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)

        IF (ALLOCATED(GM%LD_I_D)) DEALLOCATE(GM%LD_I_D,GM%LD_J_D,GM%LD_K_D,GM%LD_UPDATE_D)
        IF (ALLOCATED(GM%LD_RTI_D)) DEALLOCATE(GM%LD_RTI_D,GM%LD_TMP_L_D)
