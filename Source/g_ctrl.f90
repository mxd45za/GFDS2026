        GM%LD_TMP_L_H = TMP_H
        GM%LD_BLOCKS = (ND+GPU_LD_BLOCK-1)/GPU_LD_BLOCK

        DEALLOCATE(I_H,J_H,K_H,DEVICE_INDEX_H,RTI_H,TMP_H)
    END SUBROUTINE INITIALIZE_GPU_LINK_DETECTORS

