    !------------------------------------------------------------------------------
    ! Optional GPU THERMOCOUPLE path
    !------------------------------------------------------------------------------
    ! Advance thermocouple temperatures and pass the results to UPDATE_DEVICES_1.
    SUBROUTINE INITIALIZE_GPU_THERMOCOUPLES(NM)
        IMPLICIT NONE

        INTEGER, INTENT(IN) :: NM
        INTEGER :: N,NTC
        TYPE(DEVICE_TYPE), POINTER :: DV
        TYPE(SUBDEVICE_TYPE), POINTER :: SDV
        TYPE(PROPERTY_TYPE), POINTER :: PY
        INTEGER, ALLOCATABLE :: I_H(:),J_H(:),K_H(:),DEVICE_INDEX_H(:)
        REAL(EB), ALLOCATABLE :: DENSITY_H(:),DIAMETER_H(:),EMISSIVITY_H(:),CP_H(:),HTC_H(:),TMP_H(:)

        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)

        IF (ALLOCATED(GM%TC_I_D)) DEALLOCATE(GM%TC_I_D,GM%TC_J_D,GM%TC_K_D,GM%TC_DEVICE_INDEX_D)
        IF (ALLOCATED(GM%TC_DENSITY_D)) DEALLOCATE(GM%TC_DENSITY_D,GM%TC_DIAMETER_D,GM%TC_EMISSIVITY_D, &
                                                   GM%TC_SPECIFIC_HEAT_D,GM%TC_HEAT_TRANSFER_COEFFICIENT_D,GM%TC_TMP_L_D)
        IF (ALLOCATED(GM%TC_DEVICE_INDEX_H)) DEALLOCATE(GM%TC_DEVICE_INDEX_H)
        IF (ALLOCATED(GM%TC_TMP_L_H)) DEALLOCATE(GM%TC_TMP_L_H)
        GM%TC_N = 0
        GM%TC_BLOCKS = 0

        NTC = 0
        DO N=1,N_DEVC
            DV => DEVICE(N)
            IF (.NOT.ALLOCATED(DV%QUANTITY_INDEX)) CYCLE
            IF (DV%N_QUANTITY<1 .OR. DV%QUANTITY_INDEX(1)/=110) CYCLE
            IF (.NOT.ALLOCATED(DV%SUBDEVICE_INDEX)) CYCLE
            IF (DV%SUBDEVICE_INDEX(NM)==0) CYCLE
            SDV => DV%SUBDEVICE(DV%SUBDEVICE_INDEX(NM))
            IF (SDV%MESH/=NM) CYCLE
            NTC = NTC + 1
        ENDDO

        GM%TC_N = NTC
        IF (NTC==0) RETURN

        ALLOCATE(I_H(NTC),J_H(NTC),K_H(NTC),DEVICE_INDEX_H(NTC))
        ALLOCATE(DENSITY_H(NTC),DIAMETER_H(NTC),EMISSIVITY_H(NTC),CP_H(NTC),HTC_H(NTC),TMP_H(NTC))

        NTC = 0
        DO N=1,N_DEVC
            DV => DEVICE(N)
            IF (.NOT.ALLOCATED(DV%QUANTITY_INDEX)) CYCLE
            IF (DV%N_QUANTITY<1 .OR. DV%QUANTITY_INDEX(1)/=110) CYCLE
            IF (.NOT.ALLOCATED(DV%SUBDEVICE_INDEX)) CYCLE
            IF (DV%SUBDEVICE_INDEX(NM)==0) CYCLE
            SDV => DV%SUBDEVICE(DV%SUBDEVICE_INDEX(NM))
            IF (SDV%MESH/=NM) CYCLE

            NTC = NTC + 1
            PY => PROPERTY(DV%PROP_INDEX)
            I_H(NTC) = DV%I(1)
            J_H(NTC) = DV%J(1)
            K_H(NTC) = DV%K(1)
            DEVICE_INDEX_H(NTC) = N
            DENSITY_H(NTC) = PY%DENSITY
            DIAMETER_H(NTC) = PY%DIAMETER
            EMISSIVITY_H(NTC) = PY%EMISSIVITY
            CP_H(NTC) = PY%SPECIFIC_HEAT
            HTC_H(NTC) = PY%HEAT_TRANSFER_COEFFICIENT
            TMP_H(NTC) = DV%TMP_L
            SDV%GPU_VALUE_READY = .FALSE.
        ENDDO

        ALLOCATE(GM%TC_I_D(NTC),GM%TC_J_D(NTC),GM%TC_K_D(NTC),GM%TC_DEVICE_INDEX_D(NTC))
        ALLOCATE(GM%TC_DENSITY_D(NTC),GM%TC_DIAMETER_D(NTC),GM%TC_EMISSIVITY_D(NTC), &
                 GM%TC_SPECIFIC_HEAT_D(NTC),GM%TC_HEAT_TRANSFER_COEFFICIENT_D(NTC),GM%TC_TMP_L_D(NTC))
        ALLOCATE(GM%TC_DEVICE_INDEX_H(NTC),GM%TC_TMP_L_H(NTC))

        GM%TC_I_D = I_H
        GM%TC_J_D = J_H
        GM%TC_K_D = K_H
        GM%TC_DEVICE_INDEX_D = DEVICE_INDEX_H
        GM%TC_DENSITY_D = DENSITY_H
        GM%TC_DIAMETER_D = DIAMETER_H
        GM%TC_EMISSIVITY_D = EMISSIVITY_H
        GM%TC_SPECIFIC_HEAT_D = CP_H
        GM%TC_HEAT_TRANSFER_COEFFICIENT_D = HTC_H
        GM%TC_TMP_L_D = TMP_H
        GM%TC_DEVICE_INDEX_H = DEVICE_INDEX_H
        GM%TC_TMP_L_H = TMP_H
        GM%TC_BLOCKS = (NTC+GPU_TC_BLOCK-1)/GPU_TC_BLOCK

        DEALLOCATE(I_H,J_H,K_H,DEVICE_INDEX_H,DENSITY_H,DIAMETER_H,EMISSIVITY_H,CP_H,HTC_H,TMP_H)
    END SUBROUTINE INITIALIZE_GPU_THERMOCOUPLES

    LOGICAL FUNCTION GPU_THERMOCOUPLE_ACTIVE()
        IMPLICIT NONE

        GPU_THERMOCOUPLE_ACTIVE = ASSOCIATED(GM) .AND. GM%TC_N>0
    END FUNCTION GPU_THERMOCOUPLE_ACTIVE

    SUBROUTINE UPDATE_GPU_THERMOCOUPLES(T,DT,NM)
        IMPLICIT NONE

        REAL(EB), INTENT(IN) :: T,DT
        INTEGER, INTENT(IN) :: NM
        INTEGER :: N
        TYPE(DEVICE_TYPE), POINTER :: DV
        TYPE(SUBDEVICE_TYPE), POINTER :: SDV

        IF (GPU_MESHES(NM)%TC_N<=0) RETURN
        CALL POINT_TO_MESH(NM)
        GM => GPU_MESHES(NM)

        ! Clear the output-ready flag before updating each device.
        DO N=1,GM%TC_N
            DV => DEVICE(GM%TC_DEVICE_INDEX_H(N))
            SDV => DV%SUBDEVICE(DV%SUBDEVICE_INDEX(NM))
            SDV%GPU_VALUE_READY = .FALSE.
        ENDDO

        IF (ALLOCATED(GM%RADI)) THEN
            CALL UPDATE_THERMOCOUPLE_KERNEL<<<DIM3(GM%TC_BLOCKS,1,1),GPU_TC_BLOCK,0,GM%STRM>>>( &
                GM%TC_I_D,GM%TC_J_D,GM%TC_K_D,GM%TC_TMP_L_D,GM%TC_DENSITY_D,GM%TC_DIAMETER_D, &
                GM%TC_EMISSIVITY_D,GM%TC_SPECIFIC_HEAT_D,GM%TC_HEAT_TRANSFER_COEFFICIENT_D, &
                GM%TMPD,GM%UD,GM%VD,GM%WD,GM%RHOD,GM%ZZD,GM%RADI%UII_D,1, &
                GM%TC_N,IBP1,JBP1,KBP1,N_TRACKED_SPECIES,I_MAX_TEMP,DT,T,T_BEGIN,PR_ONTH,SIGMA,TMPM)
        ELSE
            CALL UPDATE_THERMOCOUPLE_KERNEL<<<DIM3(GM%TC_BLOCKS,1,1),GPU_TC_BLOCK,0,GM%STRM>>>( &
                GM%TC_I_D,GM%TC_J_D,GM%TC_K_D,GM%TC_TMP_L_D,GM%TC_DENSITY_D,GM%TC_DIAMETER_D, &
                GM%TC_EMISSIVITY_D,GM%TC_SPECIFIC_HEAT_D,GM%TC_HEAT_TRANSFER_COEFFICIENT_D, &
                GM%TMPD,GM%UD,GM%VD,GM%WD,GM%RHOD,GM%ZZD,GM%TMP_0D,0, &
                GM%TC_N,IBP1,JBP1,KBP1,N_TRACKED_SPECIES,I_MAX_TEMP,DT,T,T_BEGIN,PR_ONTH,SIGMA,TMPM)
        ENDIF

        CALL GPU_WAIT(GM%STRM)
        GM%TC_TMP_L_H = GM%TC_TMP_L_D

        DO N=1,GM%TC_N
            DV => DEVICE(GM%TC_DEVICE_INDEX_H(N))
            SDV => DV%SUBDEVICE(DV%SUBDEVICE_INDEX(NM))
            DV%TMP_L = GM%TC_TMP_L_H(N)
            SDV%VALUE_1 = DV%TMP_L - TMPM
            SDV%VALUE_2 = 0._EB
            SDV%VALUE_3 = 0._EB
            SDV%VALUE_4 = 0._EB
            SDV%N_VALUES = 1
            SDV%GPU_VALUE_READY = .TRUE.
        ENDDO
    END SUBROUTINE UPDATE_GPU_THERMOCOUPLES

    ATTRIBUTES(GLOBAL) SUBROUTINE UPDATE_THERMOCOUPLE_KERNEL( &
        TC_I,TC_J,TC_K,TC_TMP_L,TC_DENSITY,TC_DIAMETER,TC_EMISSIVITY,TC_SPECIFIC_HEAT,TC_HTC, &
        TMPD,UD,VD,WD,RHOD,ZZD,UII_IN,RADIATION_FLAG,NTC,IBP1_IN,JBP1_IN,KBP1_IN, &
        N_TRACKED_SPECIES_IN,I_MAX_TEMP_IN,DT_IN,T_IN,T_BEGIN_IN,PR_ONTH_IN,SIGMA_IN,TMPM_IN)
        IMPLICIT NONE

        INTEGER, VALUE :: RADIATION_FLAG,NTC,IBP1_IN,JBP1_IN,KBP1_IN,N_TRACKED_SPECIES_IN,I_MAX_TEMP_IN
        REAL(EB), VALUE :: DT_IN,T_IN,T_BEGIN_IN,PR_ONTH_IN,SIGMA_IN,TMPM_IN
        INTEGER, DEVICE :: TC_I(*),TC_J(*),TC_K(*)
        REAL(EB), DEVICE :: TC_TMP_L(*),TC_DENSITY(*),TC_DIAMETER(*),TC_EMISSIVITY(*),TC_SPECIFIC_HEAT(*),TC_HTC(*)
        REAL(EB), DEVICE :: TMPD(0:IBP1_IN,0:JBP1_IN,0:*),UD(0:IBP1_IN,0:JBP1_IN,0:*), &
                            VD(0:IBP1_IN,0:JBP1_IN,0:*),WD(0:IBP1_IN,0:JBP1_IN,0:*), &
                            RHOD(0:IBP1_IN,0:JBP1_IN,0:*)
        REAL(EB), DEVICE :: ZZD(0:IBP1_IN,0:JBP1_IN,0:KBP1_IN,1:*)
        REAL(EB), DEVICE :: UII_IN(*)
        INTEGER :: N,I,J,K,S,ITMP
        INTEGER :: NX,NY
        REAL(EB) :: TMP_G,TC_TMP,UU,VV,WW,VEL2,RHO_G,MU_G,K_G,NUMER,DENOM,RE_D,NUSSELT,H_TC,RHS,UII_G,ZS

        N = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
        IF (N>NTC) RETURN
        I = TC_I(N)
        J = TC_J(N)
        K = TC_K(N)
        TMP_G = TMPD(I,J,K)
        TC_TMP = TC_TMP_L(N)
        H_TC = TC_HTC(N)

        IF (H_TC<0._EB) THEN
            UU = UD(I,J,K)
            VV = VD(I,J,K)
            WW = WD(I,J,K)
            VEL2 = UU*UU + VV*VV + WW*WW
            ITMP = MAX(0,MIN(I_MAX_TEMP_IN,NINT(TMP_G)))
            NUMER = 0._EB
            DENOM = 0._EB
            DO S=1,N_TRACKED_SPECIES_IN
                ZS = ZZD(I,J,K,S)
                NUMER = NUMER + MU_RSQMW_ZD(ITMP,S)*ZS
                DENOM = DENOM + ZS*RSQ_MW_ZD(S)
            ENDDO
            MU_G = NUMER/DENOM
            NUMER = 0._EB
            DENOM = 0._EB
            DO S=1,N_TRACKED_SPECIES_IN
                ZS = ZZD(I,J,K,S)
                NUMER = NUMER + K_RSQMW_ZD(ITMP,S)*ZS
                DENOM = DENOM + ZS*RSQ_MW_ZD(S)
            ENDDO
            K_G = NUMER/DENOM
            RHO_G = RHOD(I,J,K)
            RE_D = RHO_G*SQRT(VEL2)*TC_DIAMETER(N)/MU_G
            NUSSELT = 2._EB + 0.6_EB*SQRT(RE_D)*PR_ONTH_IN
            H_TC = NUSSELT*K_G/TC_DIAMETER(N)
        ENDIF

        UII_G = 0._EB
        IF (RADIATION_FLAG/=0) THEN
            NX = IBP1_IN+1
            NY = JBP1_IN+1
            UII_G = UII_IN(I+NX*J+NX*NY*K+1)
        ENDIF

        RHS = (6._EB/(TC_DENSITY(N)*TC_SPECIFIC_HEAT(N)*TC_DIAMETER(N))) * &
              (H_TC*(TMP_G-TC_TMP) + TC_EMISSIVITY(N)*(0.25_EB*UII_G-SIGMA_IN*TC_TMP**4))
        ! Advance the bead temperature after its activation time, as in CPU CASE(110).
        IF (T_IN>T_BEGIN_IN) TC_TMP_L(N) = TC_TMP + DT_IN*RHS
    END SUBROUTINE UPDATE_THERMOCOUPLE_KERNEL

    !------------------------------------------------------------------------------
    ! Model-time collection and reporting
