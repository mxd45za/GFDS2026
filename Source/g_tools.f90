    SUBROUTINE MODEL_TIME_INITIALIZE

    LOCAL_STEP_TIMES = 0._EB
    LOCAL_STEP_WALL_TIMES = 0._EB
    TIMER_START_TIME = 0._EB
    TIMER_CHILD_TIME = 0._EB
    STEP_WALL_START_TIME = 0._EB
    TIMER_DEPTH = 0
MODEL_TIME_OUTPUT_WRITTEN = .FALSE.
LAST_GPU_OUTPUT_WALL_CLOCK = -1._EB
GPU_TIME_LOOP_START = 0._EB

END SUBROUTINE MODEL_TIME_INITIALIZE


SUBROUTINE WRITE_GPU_INITIAL_TIME(WALL_CLOCK_START)

REAL(EB), INTENT(IN) :: WALL_CLOCK_START
REAL(EB) :: INITIAL_TIME

INITIAL_TIME = MAX(0._EB,CURRENT_TIME()-WALL_CLOCK_START)
WRITE(LU_ERR,'(1X,A,F8.3,A)') 'INITIAL TIME : ',INITIAL_TIME,' s'

END SUBROUTINE WRITE_GPU_INITIAL_TIME


SUBROUTINE WRITE_GPU_TIME_LOOP_BEGIN(WALL_CLOCK_START)

REAL(EB), INTENT(IN) :: WALL_CLOCK_START
CHARACTER(LEN=8) :: LOOP_BEGIN_TEXT

GPU_TIME_LOOP_START = MAX(0._EB,CURRENT_TIME()-WALL_CLOCK_START)
LAST_GPU_OUTPUT_WALL_CLOCK = GPU_TIME_LOOP_START
CALL FORMAT_GPU_LOCAL_TIME(LOOP_BEGIN_TEXT)
WRITE(LU_ERR,'(1X,A,A)') 'TIME LOOP BEGIN: ',TRIM(LOOP_BEGIN_TEXT)

END SUBROUTINE WRITE_GPU_TIME_LOOP_BEGIN


SUBROUTINE WRITE_GPU_TIME_STATUS(STEP,SIMULATION_TIME,WALL_CLOCK_START)

INTEGER, INTENT(IN) :: STEP
REAL(EB), INTENT(IN) :: SIMULATION_TIME,WALL_CLOCK_START
REAL(EB) :: WALL_CLOCK,DELTA_TIME
CHARACTER(LEN=8) :: WALL_CLOCK_TEXT

WALL_CLOCK = MAX(0._EB,CURRENT_TIME()-WALL_CLOCK_START)
DELTA_TIME = MAX(0._EB,WALL_CLOCK-LAST_GPU_OUTPUT_WALL_CLOCK)
LAST_GPU_OUTPUT_WALL_CLOCK = WALL_CLOCK
CALL FORMAT_GPU_LOCAL_TIME(WALL_CLOCK_TEXT)

WRITE(LU_ERR,'(1X,A,I8,A,F10.5,A,A,A,F8.3,A)') 'Time Step:',STEP, &
     ', Simulation Time:',SIMULATION_TIME,' s, Wall time : ',TRIM(WALL_CLOCK_TEXT), &
     '    delta time : ',DELTA_TIME,' s'
WRITE(LU_OUTPUT,'(1X,A,I8,A,F10.5,A,A,A,F8.3,A)') 'Time Step:',STEP, &
     ', Simulation Time:',SIMULATION_TIME,' s, Wall time : ',TRIM(WALL_CLOCK_TEXT), &
     '    delta time : ',DELTA_TIME,' s'

END SUBROUTINE WRITE_GPU_TIME_STATUS


SUBROUTINE FORMAT_GPU_LOCAL_TIME(TIME_TEXT)

CHARACTER(*), INTENT(OUT) :: TIME_TEXT
CHARACTER(LEN=10) :: LOCAL_TIME

CALL DATE_AND_TIME(TIME=LOCAL_TIME)
TIME_TEXT = LOCAL_TIME(1:2)//':'//LOCAL_TIME(3:4)//':'//LOCAL_TIME(5:6)

END SUBROUTINE FORMAT_GPU_LOCAL_TIME


LOGICAL FUNCTION MODEL_TIME_IS_ACTIVE(STEP)

    INTEGER, INTENT(IN) :: STEP

    MODEL_TIME_IS_ACTIVE = .NOT.MODEL_TIME_OUTPUT_WRITTEN .AND. &
                           STEP>=MODEL_TIME_FIRST_STEP .AND. STEP<=MODEL_TIME_LAST_STEP

    END FUNCTION MODEL_TIME_IS_ACTIVE


    SUBROUTINE MODEL_TIME_BEGIN_STEP(STEP)

    INTEGER, INTENT(IN) :: STEP

    IF (.NOT.MODEL_TIME_IS_ACTIVE(STEP)) RETURN

    CALL GPU_WAIT_ALL
    STEP_WALL_START_TIME = CURRENT_TIME()

    END SUBROUTINE MODEL_TIME_BEGIN_STEP


    SUBROUTINE MODEL_TIME_START(MODULE_ID,STEP)

    INTEGER, INTENT(IN) :: MODULE_ID,STEP

    IF (.NOT.MODEL_TIME_IS_ACTIVE(STEP)) RETURN

    TIMER_DEPTH = TIMER_DEPTH + 1
    TIMER_CHILD_TIME(TIMER_DEPTH) = 0._EB
    TIMER_START_TIME(TIMER_DEPTH) = CURRENT_TIME()

    END SUBROUTINE MODEL_TIME_START


    SUBROUTINE MODEL_TIME_STOP(MODULE_ID,STEP)

    INTEGER, INTENT(IN) :: MODULE_ID,STEP
    INTEGER :: STEP_INDEX
    REAL(EB) :: ELAPSED_TIME,EXCLUSIVE_TIME,STOP_TIME

    IF (.NOT.MODEL_TIME_IS_ACTIVE(STEP)) RETURN

    CALL GPU_WAIT_ALL

    STOP_TIME = CURRENT_TIME()
    ELAPSED_TIME = MAX(0._EB,STOP_TIME-TIMER_START_TIME(TIMER_DEPTH))
    EXCLUSIVE_TIME = MAX(0._EB,ELAPSED_TIME-TIMER_CHILD_TIME(TIMER_DEPTH))
    STEP_INDEX = STEP-MODEL_TIME_FIRST_STEP+1
    LOCAL_STEP_TIMES(MODULE_ID,STEP_INDEX) = LOCAL_STEP_TIMES(MODULE_ID,STEP_INDEX) + EXCLUSIVE_TIME

    IF (TIMER_DEPTH>1) TIMER_CHILD_TIME(TIMER_DEPTH-1) = TIMER_CHILD_TIME(TIMER_DEPTH-1) + ELAPSED_TIME
    TIMER_START_TIME(TIMER_DEPTH) = 0._EB
    TIMER_CHILD_TIME(TIMER_DEPTH) = 0._EB
    TIMER_DEPTH = TIMER_DEPTH - 1

    END SUBROUTINE MODEL_TIME_STOP


    SUBROUTINE MODEL_TIME_FINISH_STEP(STEP,CASE_NAME)

    INTEGER, INTENT(IN) :: STEP
    CHARACTER(*), INTENT(IN) :: CASE_NAME
    INTEGER :: I,IERR,LU,REFERENCE_RANK,STEP_INDEX
    REAL(EB) :: GATHERED_MODULE_TIMES(N_MODEL_TIME_MODULES,N_MODEL_TIME_STEPS,MAX(1,N_MPI_PROCESSES))
    REAL(EB) :: GATHERED_STEP_WALL_TIMES(N_MODEL_TIME_STEPS,MAX(1,N_MPI_PROCESSES))
    REAL(EB) :: REFERENCE_MODULE_TIMES(N_MODEL_TIME_MODULES,N_MODEL_TIME_STEPS)
    REAL(EB) :: REFERENCE_STEP_WALL_TIMES(N_MODEL_TIME_STEPS)
    REAL(EB) :: MODULE_TOTAL,MODULE_AVERAGE,MODULE_PERCENT,OTHER_TOTAL,OTHER_AVERAGE
    REAL(EB) :: STEP_WALL_TOTAL,STEP_WALL_AVERAGE,TRACKED_TOTAL
    CHARACTER(LEN=512) :: FILE_NAME

    IF (.NOT.MODEL_TIME_IS_ACTIVE(STEP)) RETURN

    STEP_INDEX = STEP-MODEL_TIME_FIRST_STEP+1
    LOCAL_STEP_WALL_TIMES(STEP_INDEX) = MAX(0._EB,CURRENT_TIME()-STEP_WALL_START_TIME)
    STEP_WALL_START_TIME = 0._EB
    IF (STEP/=MODEL_TIME_LAST_STEP) RETURN

    IF (N_MPI_PROCESSES>1) THEN
       CALL MPI_GATHER(LOCAL_STEP_TIMES,N_MODEL_TIME_MODULES*N_MODEL_TIME_STEPS,MPI_DOUBLE_PRECISION, &
                       GATHERED_MODULE_TIMES,N_MODEL_TIME_MODULES*N_MODEL_TIME_STEPS,MPI_DOUBLE_PRECISION, &
                       0,MPI_COMM_WORLD,IERR)
       CALL MPI_GATHER(LOCAL_STEP_WALL_TIMES,N_MODEL_TIME_STEPS,MPI_DOUBLE_PRECISION, &
                       GATHERED_STEP_WALL_TIMES,N_MODEL_TIME_STEPS,MPI_DOUBLE_PRECISION,0,MPI_COMM_WORLD,IERR)
    ELSE
       GATHERED_MODULE_TIMES(:,:,1) = LOCAL_STEP_TIMES
       GATHERED_STEP_WALL_TIMES(:,1) = LOCAL_STEP_WALL_TIMES
    ENDIF

    IF (MY_RANK==0) THEN
       REFERENCE_RANK = MAXLOC(SUM(GATHERED_STEP_WALL_TIMES(:,1:N_MPI_PROCESSES),DIM=1),DIM=1)
       REFERENCE_STEP_WALL_TIMES = GATHERED_STEP_WALL_TIMES(:,REFERENCE_RANK)
       REFERENCE_MODULE_TIMES = GATHERED_MODULE_TIMES(:,:,REFERENCE_RANK)

       TRACKED_TOTAL = SUM(REFERENCE_MODULE_TIMES)
       STEP_WALL_TOTAL = SUM(REFERENCE_STEP_WALL_TIMES)
       OTHER_TOTAL = MAX(0._EB,STEP_WALL_TOTAL-TRACKED_TOTAL)
       STEP_WALL_AVERAGE = STEP_WALL_TOTAL/REAL(N_MODEL_TIME_STEPS,EB)
       FILE_NAME = TRIM(CASE_NAME)//'_MODEL_TIME.csv'
       OPEN(NEWUNIT=LU,FILE=TRIM(FILE_NAME),STATUS='REPLACE',ACTION='WRITE',FORM='FORMATTED')
       WRITE(LU,'(A)') 'order,module,reference_rank,sampled_steps,total_seconds,average_seconds_per_step,time_percentage'
       DO I=1,N_MODEL_TIME_MODULES
          MODULE_TOTAL = SUM(REFERENCE_MODULE_TIMES(I,:))
          MODULE_AVERAGE = MODULE_TOTAL/REAL(N_MODEL_TIME_STEPS,EB)
          IF (STEP_WALL_TOTAL>0._EB) THEN
             MODULE_PERCENT = 100._EB*MODULE_TOTAL/STEP_WALL_TOTAL
          ELSE
             MODULE_PERCENT = 0._EB
          ENDIF
          WRITE(LU,'(I0,",",A,",",I0,",",I0,",",ES16.8E3,",",ES16.8E3,",",F10.4)') &
             I,TRIM(MODEL_TIME_NAMES(I)),REFERENCE_RANK-1,N_MODEL_TIME_STEPS,MODULE_TOTAL,MODULE_AVERAGE,MODULE_PERCENT
       ENDDO
       OTHER_AVERAGE = OTHER_TOTAL/REAL(N_MODEL_TIME_STEPS,EB)
       IF (STEP_WALL_TOTAL>0._EB) THEN
          MODULE_PERCENT = 100._EB*OTHER_TOTAL/STEP_WALL_TOTAL
       ELSE
          MODULE_PERCENT = 0._EB
       ENDIF
       WRITE(LU,'(I0,",",A,",",I0,",",I0,",",ES16.8E3,",",ES16.8E3,",",F10.4)') &
          N_MODEL_TIME_MODULES+1,'OTHER_UNTRACKED',REFERENCE_RANK-1,N_MODEL_TIME_STEPS, &
          OTHER_TOTAL,OTHER_AVERAGE,MODULE_PERCENT
       WRITE(LU,'(I0,",",A,",",I0,",",I0,",",ES16.8E3,",",ES16.8E3,",",F10.4)') &
          N_MODEL_TIME_MODULES+2,'TOTAL_STEP_WALL',REFERENCE_RANK-1,N_MODEL_TIME_STEPS, &
          STEP_WALL_TOTAL,STEP_WALL_AVERAGE,100._EB
       CLOSE(LU)
    ENDIF

    MODEL_TIME_OUTPUT_WRITTEN = .TRUE.

    END SUBROUTINE MODEL_TIME_FINISH_STEP

